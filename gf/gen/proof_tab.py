#!/usr/bin/env python3
"""Writes gf/proof_tab_cases.bend: the named fields' facts for the table proofs.

proof_tab.bend proves, for every field, that the tables' fills are lists
(array's of_list form) and that the exp table's entry i is gen^i. What is
left is computation on the named fields (AES's 0x11B with generator 3,
Reed-Solomon's 0x11D with generator 2), and this generator writes it:

  * each table is its fill (gc.<f>.ex0, gc.<f>.el0): --verdict's kernel
    compares a def with its body by running it, so this is stated once per
    table, where both sides are closed;
  * the log table's list, as a literal (gc.<f>.llist, computed here and
    checked by gc.<f>.lmodel against proof_tab.bend's model of the fill);
  * the log table's entry at every byte a is U32.from_nat(Gf8.log(f, a)),
    by cases on a's eight bits, 32 cases per def to stay within --verdict's
    per-def budget (gc.<f>.log);
  * for every field: the zero test on a byte is Gf8.is_zero, and a byte
    whose test is true is 0 (gc.isz, gc.elt0).

Run: python3 gf/gen/proof_tab.py   (from the repository root or anywhere)
"""
import itertools, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "proof_tab_cases.bend")

FIELDS = [("aes", "G.Gf8.aes()", 0x11B, 3), ("rs", "G.Gf8.rs()", 0x11D, 2)]

out = []


def emit(s=""):
    out.append(s)


def gmul(a, b, poly):
    r = 0
    while b:
        if b & 1:
            r ^= a
        b >>= 1
        a <<= 1
        if a & 0x100:
            a ^= poly
    return r


def log_list(poly, gen):
    tab = [0] * 256
    cur = 1
    for i in range(255):
        tab[cur] = i
        cur = gmul(gen, cur, poly)
    return tab


def tf(b):
    return "True{}" if b else "False{}"


BS = [f"b{i}" for i in range(8)]


def gbits(bs):
    return "G.Gf8Bits{" + ", ".join(bs) + "}"


def eltb(bs):
    return f"G.Gf8Bits.to({gbits(bs)})"


def u32pat(plus=True):
    s = ("+" if plus else "") + "r"
    for b in reversed(BS):
        s = "WCon{" + ("+" if plus else "") + b + ", " + s + "}"
    return "U32{" + s + "}"


def u32term():
    s = "r"
    for b in reversed(BS):
        s = "WCon{" + b + ", " + s + "}"
    return "U32{" + s + "}"


def nested(vs, leaf, ind):
    def go(i, env, ind):
        if i == len(vs):
            for line in leaf(env):
                emit(" " * ind + line)
            return
        emit(" " * ind + f"match {vs[i]}:")
        for b in (True, False):
            emit(" " * (ind + 2) + f"case {tf(b)}:")
            go(i + 1, env + [b], ind + 4)
    go(0, [], ind)


def split8(name, goal, leaf, params="", args=""):
    """A lemma for every byte b0..b7, as 8 defs of 32 cases by (b5, b6, b7),
    and a dispatcher."""
    pre = params + ", " if params else ""
    apre = args + ", " if args else ""
    for top in itertools.product((True, False), repeat=3):
        suffix = "".join("1" if t else "0" for t in reversed(top))
        bs = BS[:5] + [tf(t) for t in top]
        ps = pre + ", ".join("+" + b + ": Bool" for b in BS[:5])
        emit(f"def {name}.s{suffix}({ps}) -> {goal(bs)}:")
        nested(BS[:5], lambda env, top=top: leaf(env + list(top)), 2)
        emit()
    ps = pre + ", ".join("+" + b + ": Bool" for b in BS)
    emit(f"def {name}({ps}) -> {goal(BS)}:")
    emit("  match b5 b6 b7:")
    for top in itertools.product((True, False), repeat=3):
        suffix = "".join("1" if t else "0" for t in reversed(top))
        emit("    case " + " ".join(tf(t) for t in top) + ":")
        emit(f"      {name}.s{suffix}({apre}" + ", ".join(BS[:5]) + ")")
    emit()


def main():
    emit("# Generated by gen/proof_tab.py; do not edit by hand.")
    emit("#")
    emit("# The named fields' facts for the table proofs (see gen/proof_tab.py and")
    emit("# proof_tab.bend). Lemmas are prefixed gc.")
    emit("import Base")
    emit("import ../array/array.bend as A")
    emit("import ./gf.bend as G")
    emit("import ./tables.bend as T")
    emit("import ./proof_tab.bend as GT")
    emit()
    emit("# a byte, from its bits")
    emit(f"def gc.elt_bits({', '.join('+' + b + ': Bool' for b in BS)}, +r: Word(24n)) -> {{G.Gf8.elt({u32term()}) == {eltb(BS)} : U32}}:")
    emit("  {==}")
    emit()
    # zero test and zero
    isz_goal = lambda bs: f"{{U32.is_eq({eltb(bs)}, 0) == G.Gf8Bits.is_zero({gbits(bs)}) : Bool}}"
    emit("# the table's zero test on a byte is Gf8.is_zero")
    split8("gc.isz.bits", isz_goal, lambda env: ["{==}"])
    emit(f"def gc.isz(+a: U32) -> {{U32.is_eq(G.Gf8.elt(a), 0) == G.Gf8.is_zero(a) : Bool}}:")
    emit("  match a:")
    emit(f"    case {u32pat()}:")
    emit(f"      %Equal.sym(U32, G.Gf8.elt({u32term()}), {eltb(BS)}, gc.elt_bits({', '.join(BS)}, r)) : {{U32.is_eq(_, 0) == G.Gf8Bits.is_zero({gbits(BS)}) : Bool}}")
    emit(f"      gc.isz.bits({', '.join(BS)})")
    emit()
    emit("# a byte whose zero test is true is 0")
    z_goal = lambda bs: f"{{{eltb(bs)} == 0 : U32}}"

    def z_leaf(env):
        if not any(env):
            return ["{==}"]
        return [f"Empty.absurd({z_goal([tf(b) for b in env])}, GT.gt.ft(h))"]
    # the hypothesis is part of each def
    for top in itertools.product((True, False), repeat=3):
        suffix = "".join("1" if t else "0" for t in reversed(top))
        bs = BS[:5] + [tf(t) for t in top]
        ps = ", ".join("+" + b + ": Bool" for b in BS[:5])
        emit(f"def gc.elt0.s{suffix}({ps}, h: {{U32.is_eq({eltb(bs)}, 0) == True{{}} : Bool}}) -> {z_goal(bs)}:")
        nested(BS[:5], lambda env, top=top: z_leaf(env + list(top)), 2)
        emit()
    ps = ", ".join("+" + b + ": Bool" for b in BS)
    emit(f"def gc.elt0.bits({ps}, h: {{U32.is_eq({eltb(BS)}, 0) == True{{}} : Bool}}) -> {z_goal(BS)}:")
    emit("  match b5 b6 b7:")
    for top in itertools.product((True, False), repeat=3):
        suffix = "".join("1" if t else "0" for t in reversed(top))
        emit("    case " + " ".join(tf(t) for t in top) + ":")
        emit(f"      gc.elt0.s{suffix}(" + ", ".join(BS[:5]) + ", h)")
    emit()
    emit(f"def gc.elt0(+a: U32, h: {{U32.is_eq(G.Gf8.elt(a), 0) == True{{}} : Bool}}) -> {{G.Gf8.elt(a) == 0 : U32}}:")
    emit("  match a:")
    emit(f"    case {u32pat()}:")
    emit(f"      gc.elt0.bits({', '.join(BS)}, h)")
    emit()
    rep8 = "List.replicate(U32, A.Arrays.slots(8n), 0)"
    for (n, F, poly, gen) in FIELDS:
        emit(f"# The {n} field")
        emit()
        emit(f"def gc.{n}.ex0() -> {{T.Gf8Tab.exp_table({F}) == T.gf8tab.fill.exp(510n, Array.new(U32, 9n, 0), {F}, 1, 0) : Array<U32>}}:")
        emit("  {==}")
        emit()
        emit(f"def gc.{n}.el0() -> {{T.Gf8Tab.log_table({F}) == T.gf8tab.fill.log(255n, Array.new(U32, 8n, 0), {F}, 1, 0) : Array<U32>}}:")
        emit("  {==}")
        emit()
        emit(f"def gc.{n}.llist() -> List<&2, U32>:")
        emit("  [" + ", ".join(str(v) for v in log_list(poly, gen)) + "]")
        emit()
        emit(f"def gc.{n}.lmodel() -> {{GT.gt.fl(255n, {rep8}, {F}, 0n) == gc.{n}.llist() : List<&2, U32>}}:")
        emit("  {==}")
        emit()
        emit(f"def gc.{n}.new() -> {{GT.gt.tab({F}, gc.{n}.llist()) == T.Gf8Tab.new({F}) : T.Gf8Tab}}:")
        emit(f"  GT.gt.new({F}, gc.{n}.llist(), gc.{n}.ex0(), gc.{n}.el0(), gc.{n}.lmodel())")
        emit()
        lg = lambda bs, F=F, n=n: f"{{A.Arrays.nth(U32, gc.{n}.llist(), A.Arrays.index(8n, {eltb(bs)}), 0) == U32.from_nat(G.Gf8.log({F}, {eltb(bs)})) : U32}}"
        emit(f"# the {n} log table's entry at a byte")
        split8(f"gc.{n}.log.bits", lg, lambda env: ["{==}"])
        emit(f"def gc.{n}.log(+a: U32) -> {{A.Arrays.nth(U32, gc.{n}.llist(), A.Arrays.index(8n, G.Gf8.elt(a)), 0) == U32.from_nat(G.Gf8.log({F}, a)) : U32}}:")
        emit("  match a:")
        emit(f"    case {u32pat()}:")
        emit(f"      gc.{n}.log.bits({', '.join(BS)})")
        emit()
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out).rstrip("\n") + "\n")


main()
