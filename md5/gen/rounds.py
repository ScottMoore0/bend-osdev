#!/usr/bin/env python3
"""Writes MD5's compression function, unrolled, from the specification's
tables (gen/spec.py).

  python3 gen/rounds.py           rewrite the generated region
  python3 gen/rounds.py --check   only check that it is up to date

The region lies between "# BEGIN GENERATED by gen/rounds.py: md5" and
"# END GENERATED: md5" in md5.bend; everything else is written by hand.
It holds one def, hs.md5.rounds(x, cv): the sixteen words of a block and
the chaining value in, the next chaining value out. Every step of the
specification is one line, binding a fresh name (v<i> for chaining words,
w<j> for the expanded message), so the code reads as the specification's
step list and needs no indexing at run time.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")
sys.dont_write_bytecode = True
sys.path.insert(0, HERE)
import spec  # noqa: E402

XS = ", ".join("+x%d" % i for i in range(16))
W16 = "Hs.HsW16{%s}" % XS


class Names:
    def __init__(self):
        self.i = 0

    def new(self):
        self.i += 1
        return "v%d" % self.i


def add(*xs):
    t = xs[0]
    for x in xs[1:]:
        t = "U32.add(%s, %s)" % (t, x)
    return t


def md5():
    out = ["def hs.md5.rounds(x: Hs.HsW16, cv: Hs.HsW4) -> Hs.HsW4:",
           "  match x cv:",
           "    case %s Hs.HsW4{+a0, +b0, +c0, +d0}:" % W16]
    F = ["hs.md5.f", "hs.md5.g", "hs.md5.h", "hs.md5.i"]
    a, b, c, d = "a0", "b0", "c0", "d0"
    n = Names()
    for j in range(64):
        r = j // 16
        if j % 16 == 0:
            out.append("      # round %d" % (r + 1))
        v = n.new()
        out.append("      +%s = hs.md5.step(%s, %s, %s(%s, %s, %s), x%d, %d, %dn)"
                   % (v, a, b, F[r], b, c, d, spec.MD5_X[r][j % 16], spec.MD5_T[j], spec.MD5_S[r][j % 4]))
        a, b, c, d = d, v, b, c
    out.append("      Hs.HsW4{%s}" % ", ".join("U32.add(%s, %s)" % p for p in [("a0", a), ("b0", b), ("c0", c), ("d0", d)]))
    return "\n".join(out) + "\n"


REGIONS = [("md5.bend", "md5", md5)]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fname, name, body in REGIONS:
        path = os.path.join(PKG, fname)
        with open(path) as f:
            text = f.read()
        begin = "# BEGIN GENERATED by gen/rounds.py: %s\n" % name
        end = "# END GENERATED: %s\n" % name
        i, j = text.index(begin) + len(begin), text.index(end)
        new = text[:i] + body() + text[j:]
        if new != text:
            stale.append(fname)
            if not check:
                with open(path, "w", newline="\n") as f:
                    f.write(new)
    if check:
        if stale:
            print("out of date (run gen/rounds.py): " + ", ".join(stale))
            sys.exit(1)
        print("generated regions up to date")


if __name__ == "__main__":
    main()
