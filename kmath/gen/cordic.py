#!/usr/bin/env python3
"""Writes kmath/cordic_table.bend: CORDIC's constants for cordic.bend.

atan(2^-i) for i = 0 to 29, in binary-angle units (2^32 to the full turn),
rounded; and the gain K = prod 1 / sqrt(1 + 2^-2i) over the 30 steps, in
Q1.30 (2^30 = 1), rounded. Run: python3 kmath/gen/cordic.py
"""
import math, os

N = 30
here = os.path.dirname(os.path.abspath(__file__))
atan = [round(math.atan(2.0 ** -i) * 2 ** 32 / (2 * math.pi)) for i in range(N)]
k = 1.0
for i in range(N):
    k /= math.sqrt(1 + 2.0 ** (-2 * i))
with open(os.path.join(here, "..", "cordic_table.bend"), "w", newline="\n") as f:
    f.write("# Generated by gen/cordic.py; do not edit by hand.\n")
    f.write("# CORDIC's constants (cordic.bend): atan(2^-i), i = 0 to 29, in binary-angle\n")
    f.write("# units (2^32 to the full turn), and the gain of the 30 steps in Q1.30.\n")
    f.write("import Base\n\n")
    f.write("def KCordic.atans() -> List<&2, U32>:\n  [" + ", ".join(map(str, atan)) + "]\n\n")
    f.write("def KCordic.gain() -> U32:\n  %d\n" % round(k * 2 ** 30))
