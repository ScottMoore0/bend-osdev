def pat(n, k):
    """a U32 split into its low k bits (n0 .. n{k-1}) and, if k < 32, the rest."""
    s = "".join("WCon{%s%d, " % (n, i) for i in range(k))
    tail = "WNil{}" if k == 32 else n + "h"
    return "U32{" + s + tail + "}" * k + "}"

def mac(n):
    return "E.MacAddr{" + ", ".join(pat("%s%d_" % (n, i), 8) for i in range(6)) + "}"

def v6(n):
    return "I6.Ipv6Addr{" + ", ".join(pat("%s%d_" % (n, i), 32) for i in range(4)) + "}"

def bits4(v, tail):
    """the U32 whose low 4 bits are v, the rest the Word(28n) variable tail"""
    s = "".join("WCon{%s, " % ("True{}" if v >> i & 1 else "False{}") for i in range(4))
    return "U32{" + s + tail + "}" * 4 + "}"

def conlist(xs, tail="Nil{}"):
    return "".join("Con{%s, " % x for x in xs) + tail + "}" * len(xs)

