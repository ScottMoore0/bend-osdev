# ---- IPv4 and TCP: every header length
def lengthy(law, lenname, fields, widths, mkhdr, parse_list, build_f, norm_f, ty, law_order):
    """fields: the other header fields; mkhdr(lenexpr, optexpr) -> header expr"""
    def goal(lenexpr, optexpr, r="r"):
        h = mkhdr(lenexpr, optexpr)
        return f"{parse_list.replace('@', 'B.append(B.Octets.to_list(' + build_f + '(' + h + ')), ' + r + ')')} == Done{{{norm_f}({h})}} : {res(ty)}"
    fsig = ", ".join("%s: U32" % f for f in fields)
    fargs = ", ".join(fields)
    e1t = lambda l: f"{{U32.is_ge(N.NetField.low(4n, {l}), 5) == True{{}} : Bool}}"
    e2t = lambda l, o: f"{{B.len({o}) == Nat.sub(Nat.mul(4n, U32.to_nat(N.NetField.low(4n, {l}))), 20n) : Nat}}"
    for v in range(5, 16):
        L = 4 * (v - 5)
        lv = bits4(v, "lh")
        xs = ["x%d" % i for i in range(L)]
        # the leaf: options of exactly L bytes
        xsig = "".join(", %s: U32" % x for x in xs)
        w(f"""
def {law}.leaf{v}({fsig}, lh: Word(28n){xsig}, r: {LST}) -> {{{goal(lv, "B.Octets.of_list(" + conlist(xs) + ")")}}}:
  match {" ".join(fields + xs)}:
    case {" ".join([pat(f, k) for f, k in zip(fields, widths)] + [pat(x + "_", 8) for x in xs])}:
      {{==}}
""")
        # the case analysis on the options
        def opts(i, ind):
            pad = "  " * ind
            cur = conlist(xs[:i], "Nil{}")
            v_ = "options" if i == 0 else "o%d" % i
            if i == L:
                over = conlist(xs[:L], "Con{y, u}")
                return (f"{pad}match {v_}:\n"
                        f"{pad}  case Nil{{}}:\n"
                        f"{pad}    {law}.leaf{v}({fargs}, lh{''.join(', ' + x for x in xs)}, r)\n"
                        f"{pad}  case Con{{y, u}}:\n"
                        f"{pad}    %e2 : pick_type(Nat.is_eq(_, {L}n), {{{goal(lv, 'B.Octets.of_list(' + over + ')')}}}, Unit)\n"
                        f"{pad}    Unit{{}}\n")
            return (f"{pad}match {v_}:\n"
                    f"{pad}  case Nil{{}}:\n"
                    f"{pad}    %e2 : pick_type(Nat.is_eq(_, {L}n), {{{goal(lv, 'B.Octets.of_list(' + cur + ')')}}}, Unit)\n"
                    f"{pad}    Unit{{}}\n"
                    f"{pad}  case Con{{x{i}, o{i + 1}}}:\n" + opts(i + 1, ind + 2))
        w(f"""
def {law}.len{v}({fsig}, lh: Word(28n), options: {LST}, e2: {e2t(lv, "options")}, r: {LST}) -> {{{goal(lv, "B.Octets.of_list(options)")}}}:
""" + opts(0, 1))
    # the split on the four bits of the length field: sixteen cases
    def case(val):
        pad = "      "
        if val < 5:
            return (f"{pad}%e1 : pick_type(_, {{{goal(bits4(val, 'lh'), 'B.Octets.of_list(options)')}}}, Unit)" + NL +
                    f"{pad}Unit{{}}" + NL)
        return f"{pad}{law}.len{val}({fargs}, lh, options, e2, r)" + NL
    w(f"""
def {law}.list({lenname}: U32, e1: {e1t(lenname)}, {fsig}, options: {LST}, e2: {e2t(lenname, "options")}, r: {LST}) -> {{{goal(lenname, "B.Octets.of_list(options)")}}}:
  match {lenname}:
""" + "".join(f"    case {bits4(v, 'lh')}:" + NL + case(v) for v in range(16)))
    h = mkhdr(lenname, "B.Octets.of_list(options)")
    w(f"""
def Laws.{law}({", ".join(law_order)}, rest):
  {rew(parse_list, build_f + "(" + h + ")", "rest", "Done{" + norm_f + "(" + h + ")}", res(ty))}
  {law}.list({lenname}, e1, {fargs}, options, e2, B.Octets.to_list(rest))
""")

