# ---- truncation: case analysis on the first n + 1 bytes
def trunc(law, parse, n, ty):
    xs = ["x%d" % i for i in range(n + 1)]
    def go(i, ind):
        pad = "  " * ind
        v = "xs" if i == 0 else "t%d" % i
        if i == n:
            G = lambda tail: f"{{{parse}(B.Octets.of_list({conlist(xs[:n], tail)})) == Fail{{N.NetTruncated{{}}}} : {res(ty)}}}"
            return (f"{pad}match {v}:\n"
                    f"{pad}  case Nil{{}}:\n{pad}    %e : pick_type(_, {G('Nil{}')}, Unit)\n{pad}    Unit{{}}\n"
                    f"{pad}  case Con{{y, u}}:\n{pad}    %e : pick_type(_, {G('Con{y, u}')}, Unit)\n{pad}    Unit{{}}\n")
        return (f"{pad}match {v}:\n{pad}  case Nil{{}}:\n{pad}    {{==}}\n"
                f"{pad}  case Con{{x{i}, t{i + 1}}}:\n" + go(i + 1, ind + 2))
    w(f"\ndef Laws.{law}(xs, e):\n" + go(0, 1))

