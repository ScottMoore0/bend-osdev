#!/usr/bin/env python3
"""Writes kstr/PROOF.bend (the proofs of LAWS.bend's laws) and
kstr/PROOF_dec.bend (the decimal round trips of LAWS_dec.bend,
gen/proof_dec.py).

hex32_round_trip, for every U32 v: v is split into its 32 bits, so that
hex32(v) is the list of the eight digits of its nibbles. Octets hands the
list back masked (bytes' law octets_to_of); each masked digit byte reads as
the token KTDigit of its nibble (a lemma per nibble, by its 16 cases); and
on those tokens the parse is computation: the nibbles go back in, four bits
at a time, and nothing above the top nibble is ever set.

Run: python3 kstr/gen/proof.py
"""
import itertools
import os
import sys

HERE0 = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE0, "..", "..", "scripts"))
sys.path.insert(0, HERE0)
import natproof as N  # noqa: E402
import proof_dec  # noqa: E402

N.CFG["law"] = "UL."
N.OUT.prefix = "ks.r"

HERE = os.path.dirname(os.path.abspath(__file__))


def u32(bits, tail):
    s = tail
    for b in reversed(bits):
        s = f"WCon{{{b}, {s}}}"
    return "U32{" + s + "}"


def nib(bs):
    return f"F.KStr.nib({', '.join(bs)})"


def dig(bs):
    return f"K.KTDigit{{{u32(bs, 'Word.zero(28n)')}}}"


def cases(vs, leaf, depth):
    out = []

    def go(i, ind):
        if i == len(vs):
            out.append("  " * ind + leaf)
            return
        out.append("  " * ind + f"match {vs[i]}:")
        for val in ("True", "False"):
            out.append("  " * (ind + 1) + f"case {val}{{}}:")
            go(i + 1, ind + 2)
    go(0, depth)
    return "\n".join(out)


lines = ["# Generated by gen/proof.py; do not edit by hand.",
         "import Base",
         "import ../word64/word64.bend as W",
         "import ../bytes/bytes.bend as B",
         "import ../bytes/LAWS.bend as BL",
         "import ../bytes/PROOF.bend as BP",
         "import ./kstr.bend as K",
         "import ./format.bend as F",
         "import ./hexdump.bend as H",
         "import ./options.bend as O",
         "import ./LAWS.bend as Laws",
         ""]
b4 = ["b0", "b1", "b2", "b3"]
lines.append("# a nibble's digit byte, masked, reads as the digit (16 cases)")
lines.append(f"def tok_nib({', '.join('+' + b + ': Bool' for b in b4)}) -> {{K.KStr.tok(B.byte({nib(b4)})) == {dig(b4)} : K.KStrTok}}:")
lines.append(cases(b4, "{==}", 1))
lines.append("")
bits = [f"b{i}" for i in range(32)]
groups = [bits[4 * k:4 * k + 4] for k in range(7, -1, -1)]
L = "[" + ", ".join(nib(g) for g in groups) + "]"
D = "[" + ", ".join(dig(g) for g in groups) + "]"
TL = "List<&2, K.KStrTok>"
lines.append("# the token list of the digits")
lines.append(f"def toks_hex({', '.join('+' + b + ': Bool' for b in bits)}) -> {{K.kstr.toks(B.mask({L})) == {D} : {TL}}}:")
for k in range(8):
    cur = [f"K.KStr.tok(B.byte({nib(g)}))" for g in groups[:k]] + ["_"] + [dig(g) for g in groups[k + 1:]]
    lines.append(f"  %tok_nib({', '.join(groups[k])}) : {{K.kstr.toks(B.mask({L})) == [{', '.join(cur)}] : {TL}}}")
lines.append("  {==}")
lines.append("")
R = "Result<&2, &2, K.KStrError, U32>"
V = u32(bits, "WNil{}")


def Hs(ts):
    return f"K.kstr.u32.fin(K.kstr.front(16, K.kstr.strip_nl({ts}), False{{}}))"


t0 = Hs(f"K.kstr.toks(B.Octets.to_list(B.Octets.of_list({L})))")
t1 = Hs(f"K.kstr.toks(B.mask({L}))")
t2 = Hs(D)
e1 = f"Equal.cong(List<&2, U32>, {R}, z => {Hs('K.kstr.toks(z)')}, B.Octets.to_list(B.Octets.of_list({L})), B.mask({L}), BL.octets_to_of({L}))"
e2 = f"Equal.cong({TL}, {R}, z => {Hs('z')}, K.kstr.toks(B.mask({L})), {D}, toks_hex({', '.join(bits)}))"
lines.append("def hex_round(" + ", ".join('+' + b + ': Bool' for b in bits) + f") -> {{{t0} == Done{{{V}}} : {R}}}:")
lines.append(f"  Equal.trans({R}, {t0}, {t1}, Done{{{V}}}, {e1}, Equal.trans({R}, {t1}, {t2}, Done{{{V}}}, {e2}, {{==}}))")
lines.append("")
lines.append("def Laws.hex32_round_trip(v):")
lines.append("  match v:")
lines.append(f"    case {u32(bits, 'WNil{}')}:")
lines.append(f"      hex_round({', '.join(bits)})")
lines.append("")
_flushed = [0]


def put(x=""):
    defs = N.OUT.defs[_flushed[0]:]
    if defs:
        lines.append("\n".join(defs))
        _flushed[0] = len(N.OUT.defs)
    lines.append(x)


VECTORS = ["v_base0", "v_newline", "v_sign", "v_errors", "v_range", "v_signed_bounds", "v_u64", "v_bool", "v_sprintf",
           "v_sprintf_zero_sign", "v_sprintf_errors", "v_hex32", "v_hexdump_doc", "v_hexdump_groups", "v_hexdump_short",
           "v_hexdump_offsets", "v_match_token", "v_match_signed", "v_split_options"]
lines.append("# vectors, by computation")
for v in VECTORS:
    lines.append(f"def Laws.{v}():")
    lines.append("  {==}")
    lines.append("")
with open(os.path.join(HERE, "..", "PROOF.bend"), "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")

# PROOF_dec.bend: the decimal round trips (LAWS_dec.bend)
W64_LAWS = [("LAWS.bend", "WB"), ("LAWS_div.bend", "WD"), ("LAWS_mul.bend", "WM"), ("LAWS_bits.bend", "WT"), ("LAWS_text.bend", "WX")]
lines = ["# Generated by gen/proof.py; do not edit by hand. The proofs of LAWS_dec.bend: decimal round trips.",
         "import Base",
         "import ../u32/u32.bend as U",
         "import ../u32/LAWS.bend as UL",
         "import ../u32/PROOF.bend as UP",
         "import ../word64/word64.bend as W",
         "import ../word64/LAWS.bend as WB",
         "import ../word64/PROOF.bend as WBP",
         "import ../word64/LAWS_div.bend as WD",
         "import ../word64/PROOF_div.bend as WDP",
         "import ../word64/LAWS_mul.bend as WM",
         "import ../word64/PROOF_mul.bend as WMP",
         "import ../bytes/bytes.bend as B",
         "import ../bytes/LAWS.bend as BL",
         "import ../bytes/PROOF.bend as BP",
         "import ./kstr.bend as K",
         "import ./format.bend as F",
         "import ./LAWS_dec.bend as Laws",
         ""]
_flushed[0] = len(N.OUT.defs)
proof_dec.dec(put)
put("")
al = N.law_aliases([(os.path.join(HERE, "..", "..", "word64", f), a) for f, a in W64_LAWS])
with open(os.path.join(HERE, "..", "PROOF_dec.bend"), "w", newline="\n") as f:
    f.write(N.realias("\n".join(lines) + "\n", "WL", al))
