def block(name, title, K, key, enc, dec, fmt, rt, rt_dual, bad):
    """a block cipher: K its key schedule, key the interface's ~key (a def
    with its template arguments), enc and dec, its block format, the laws of
    its own package that decryption undoes encryption (rt) and the reverse
    (rt_dual) -- None where it has none -- and a key length it refuses"""
    d = dict(name=name, title=title, K=K, key=key, enc=enc, dec=dec, rt=rt, rt_dual=rt_dual, bad=bad)
    d.update(fmt)
    return d


def lc_key(K, fn):
    return "LC.CrLc.key(~%s, ~%s)" % (K, fn)


