LAWS, PROOFS = [], []


def law(name, comment, params, stmt):
    head = "".join("  for %s\n" % p for p in params)
    LAWS.append("# %s\nlaw %s:\n%s  %s\n" % (comment, name, head, stmt))


def proof(text):
    PROOFS.append(text)


def block_laws(c):
    n, K, Blk, enc, dec = c["name"], c["K"], c["Blk"], c["enc"], c["dec"]
    L = "List<&2, %s>" % Blk
    if c["rt"]:
        law("%s_block_round_trip" % n, "%s: decryption undoes encryption, for every key and block" % c["title"],
            ["k: %s" % K, "+b: %s" % Blk], "{%s(k, %s(k, b)) == b : %s}" % (dec, enc, Blk))
        proof("def Laws.%s_block_round_trip(k, b):\n  %s(k, b)\n" % (n, c["rt"]))
    if c["rt_dual"]:
        law("%s_block_round_trip_dual" % n, "%s: encryption undoes decryption (a permutation of the blocks)" % c["title"],
            ["k: %s" % K, "+b: %s" % Blk], "{%s(k, %s(k, b)) == b : %s}" % (enc, dec, Blk))
        proof("def Laws.%s_block_round_trip_dual(k, b):\n  %s(k, b)\n" % (n, c["rt_dual"]))
    law("%s_key_length" % n, "%s: a key of %d bytes is refused" % (c["title"], c["bad"]), [],
        "{Result.map(&2, &2, Cr.CrError, %s, Unit, k => Unit{}, %s) == Fail{Cr.CrBadKeyLength{%dn}} : Result<&2, &2, Cr.CrError, Unit>}"
        % (K, call(c["key"], "B.Octets.zeros(%dn)" % c["bad"]), c["bad"]))
    proof("def Laws.%s_key_length():\n  {==}\n" % n)
    if not c["rt"]:
        return
