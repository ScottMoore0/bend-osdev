def call(fn, *args):
    """a def given with its template arguments, called on args"""
    if fn.endswith(")"):
        return fn[:-1] + "".join(", " + a for a in args) + ")" if args else fn
    return "%s(%s)" % (fn, ", ".join(args)) if args else fn


def fill(text, T):
    return text.format(**T)


def stream_laws(c):
    n, S = c["name"], c["S"]
    up = lambda s, m: "%s(%s, %s)" % (c["update"], s, m)
    od = lambda o: "%s(%s)" % (c["out_data"], o)
    os_ = lambda o: "%s(%s)" % (c["out_state"], o)
    law("%s_stream_involution" % n, "%s: from one state, applied twice, the data comes back" % c["title"],
        ["+s: %s" % S, "+m: B.Octets"], "{%s == m : B.Octets}" % od(up("s", od(up("s", "m")))))
    proof("def Laws.%s_stream_involution(s, m):\n  %s(s, m)\n" % (n, c["involution"]))
    law("%s_stream_streaming_data" % n, "%s: the output of a ++ b is the output of a, then of b from the state after a" % c["title"],
        ["+s: %s" % S, "+a: B.Octets", "+b: B.Octets"],
        "{%s == B.Octets.append(%s, %s) : B.Octets}" % (od(up("s", "B.Octets.append(a, b)")), od(up("s", "a")), od(up(os_(up("s", "a")), "b"))))
    proof("def Laws.%s_stream_streaming_data(s, a, b):\n  %s(s, a, b)\n" % (n, c["sdata"]))
    law("%s_stream_streaming_state" % n, "%s: the state after a ++ b is the state after a, then b" % c["title"],
        ["+s: %s" % S, "+a: B.Octets", "+b: B.Octets"],
        "{%s == %s : %s}" % (os_(up("s", "B.Octets.append(a, b)")), os_(up(os_(up("s", "a")), "b")), S))
    proof("def Laws.%s_stream_streaming_state(s, a, b):\n  %s(s, a, b)\n" % (n, c["sstate"]))


def hash_iface_laws(h):
    """the hash interface's laws for a hash of the hashes package, each its
    own package's law (HSL) at the instance's defs"""
    n, H, t, src = h["name"], h["H"], h["title"], h["iface"]
    U = lambda s, m: call(h["update"], s, m)
    F = lambda s: call(h["final"], s)
    D = lambda m: call(h["digest"], m)
    I = h["init"]
    law("%s_hash_streaming" % n, "%s: update over a ++ b is update over a, then b, for every state" % t,
        ["s: %s" % H, "+a: B.Octets", "+b: B.Octets"], "{%s == %s : %s}" % (U("s", "B.Octets.append(a, b)"), U(U("s", "a"), "b"), H))
    proof("def Laws.%s_hash_streaming(s, a, b):\n  HSL.%s_streaming(s, a, b)\n" % (n, src))
    law("%s_hash_split" % n, "%s: streaming equals one-shot, for every split" % t, ["+a: B.Octets", "+b: B.Octets"],
        "{%s == %s : B.Octets}" % (F(U(U(I, "a"), "b")), D("B.Octets.append(a, b)")))
    proof("def Laws.%s_hash_split(a, b):\n  HSL.%s_split(a, b)\n" % (n, src))
    law("%s_hash_split3" % n, "%s: and for every split into three" % t, ["+a: B.Octets", "+b: B.Octets", "+c: B.Octets"],
        "{%s == %s : B.Octets}" % (F(U(U(U(I, "a"), "b"), "c")), D("B.Octets.append(a, B.Octets.append(b, c))")))
    proof("def Laws.%s_hash_split3(a, b, c):\n  HSL.%s_split3(a, b, c)\n" % (n, src))
    law("%s_hash_length" % n, "%s: final(s) has %d bytes, for every state" % (t, h["dsize"]), ["+s: %s" % H],
        "{B.Octets.len(%s) == %dn : Nat}" % (F("s"), h["dsize"]))
    proof("def Laws.%s_hash_length(s):\n  HSL.%s_length(s)\n" % (n, src))


def hash_laws(h):
    """HMAC over the hash (hmac.bend): in pieces, from the hash's laws (the
    streaming law, where it has one, for HMAC's state in pieces; split and
    split3 for the tag in pieces)"""
    n, H = h["name"], h["H"]
    tp = ["~%s: %s" % (v, t) for v, t in h["tparams"]]
    tn = "".join(v + ", " for v, _ in h["tparams"])
    init, upd, fin, dig = h["init"], h["update"], h["final"], h["digest"]
    U = lambda s, m: call(upd, s, m)
    F = lambda s: call(fin, s)
    D = lambda m: call(dig, m)
    SP = lambda a, b: h["split"] % (a, b)
    SP3 = lambda a, b, c: h["split3"] % (a, b, c)
    st = "Hm.CrHmacState<%s>" % H
    hupd = lambda s, m: "Hm.CrHmac.update(~%s, ~%s, %s, %s)" % (H, upd, s, m)
    if h["streaming"]:
        S = lambda s, a, b: h["streaming"] % (s, a, b)
        law("hmac_%s_streaming" % n, "HMAC over %s: the state after a ++ b is the state after a, then b" % h["title"],
            tp + ["s: %s" % st, "+a: B.Octets", "+b: B.Octets"],
            "{%s == %s : %s}" % (hupd("s", "B.Octets.append(a, b)"), hupd(hupd("s", "a"), "b"), st))
        proof("""def Laws.hmac_%s_streaming(%ss, a, b):
  match s:
    case Hm.CrHmacState{h, o}:
      %%%s : {Hm.CrHmacState{%s, o} == Hm.CrHmacState{_, o} : %s}
      {==}
""" % (n, tn, S("h", "a", "b"), U("h", "B.Octets.append(a, b)"), st))
    start = "Hm.CrHmac.start(~%s, ~%s, ~%s, kk)" % (H, init, upd)
    law("hmac_%s_split" % n, "HMAC over %s: the tag in pieces is the tag in one call, for every split" % h["title"],
        tp + ["+kk: Hm.CrHmacKey", "+a: B.Octets", "+b: B.Octets"],
        "{Hm.CrHmac.finish(~%s, ~%s, ~%s, ~%s, %s) == Hm.CrHmac.mac(~%s, kk, B.Octets.append(a, b)) : B.Octets}"
        % (H, init, upd, fin, hupd(hupd(start, "a"), "b"), dig))
    inner = D("B.Octets.append(i, B.Octets.append(a, b))")
    rhs = D("B.Octets.append(o, %s)" % inner)
    proof("""def Laws.hmac_%s_split(%skk, a, b):
  match kk:
    case Hm.CrHmacKey{+i, +o}:
      %%Equal.sym(B.Octets, %s, %s, %s) : {%s == %s : B.Octets}
      %%Equal.sym(B.Octets, %s, %s, %s) : {_ == %s : B.Octets}
      {==}
""" % (n, tn,
       F(U(U(U(init, "i"), "a"), "b")), inner, SP3("i", "a", "b"), F(U(U(init, "o"), "_")), rhs,
       F(U(U(init, "o"), inner)), rhs, SP("o", inner), rhs))


