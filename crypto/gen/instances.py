#!/usr/bin/env python3
"""The instances of the interfaces, and their law schemas.

  python3 gen/instances.py           rewrite the generated regions
  python3 gen/instances.py --check   only check that they are up to date

Each region lies between "# BEGIN GENERATED by gen/instances.py: <name>" and
"# END GENERATED: <name>":
  * "laws" in LAWS.bend: one law per instance and law schema;
  * "proofs" in PROOF.bend: their proofs.
Everything outside the regions is written by hand.

Why per instance. An interface law that needs a property of the algorithm (a
block cipher's decryption undoes its encryption, a hash in pieces is the hash
of the whole) cannot be one law over the template arguments: it would take
that property as a hypothesis, and --verdict has no model of a template
hypothesis (~inv: ...), while an ordinary hypothesis (inv: ...) is affine, so
an induction cannot use it at every step. So each such law is a schema: a
statement and a proof with the instance's defs (and the name of the law that
gives the instance's property) filled in, written out once per instance
below. A law that needs nothing from the algorithm is stated once, by hand,
over the template arguments (LAWS.bend, first part).

Adding an instance: a row in BLOCK, STREAM or HASH (its defs, as template
arguments, and the names of the laws its own package proves), then run this
script. A hash of the hashes package is a hs_row: its interface laws are
written here too, each its own package's law. A new schema: a function
below, and its rows.
"""
