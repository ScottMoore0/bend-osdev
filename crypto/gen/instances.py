# ---------------------------------------------------------------- schemas

LAWS, PROOFS = [], []


def law(name, comment, params, stmt):
    head = "".join("  for %s\n" % p for p in params)
    LAWS.append("# %s\nlaw %s:\n%s  %s\n" % (comment, name, head, stmt))


def proof(text):
    PROOFS.append(text)


def block_laws(c):
    n, K, Blk, enc, dec = c["name"], c["K"], c["Blk"], c["enc"], c["dec"]
    L = "List<&2, %s>" % Blk
    if c["rt"]:
        law("%s_block_round_trip" % n, "%s: decryption undoes encryption, for every key and block" % c["title"],
            ["k: %s" % K, "+b: %s" % Blk], "{%s(k, %s(k, b)) == b : %s}" % (dec, enc, Blk))
        proof("def Laws.%s_block_round_trip(k, b):\n  %s(k, b)\n" % (n, c["rt"]))
    if c["rt_dual"]:
        law("%s_block_round_trip_dual" % n, "%s: encryption undoes decryption (a permutation of the blocks)" % c["title"],
            ["k: %s" % K, "+b: %s" % Blk], "{%s(k, %s(k, b)) == b : %s}" % (enc, dec, Blk))
        proof("def Laws.%s_block_round_trip_dual(k, b):\n  %s(k, b)\n" % (n, c["rt_dual"]))
    law("%s_key_length" % n, "%s: a key of %d bytes is refused" % (c["title"], c["bad"]), [],
        "{Result.map(&2, &2, Cr.CrError, %s, Unit, k => Unit{}, %s) == Fail{Cr.CrBadKeyLength{%dn}} : Result<&2, &2, Cr.CrError, Unit>}"
        % (K, call(c["key"], "B.Octets.zeros(%dn)" % c["bad"]), c["bad"]))
    proof("def Laws.%s_key_length():\n  {==}\n" % n)
    if not c["rt"]:
        return
    T = dict(n=n, K=K, Blk=Blk, enc=enc, dec=dec, rt=c["rt"], L=L, bxor=c["bxor"], xx=c["xx"])
    # ECB, on blocks
    law("%s_ecb_round_trip" % n, "%s in ECB (modes.bend): decryption undoes encryption, for every key and list of blocks" % c["title"],
        ["+k: %s" % K, "+bs: %s" % L],
        "{Md.CrEcb.decrypt_blocks(~%s, ~%s, ~%s, k, Md.CrEcb.encrypt_blocks(~%s, ~%s, ~%s, k, bs)) == bs : %s}" % (K, Blk, dec, K, Blk, enc, L))
    proof(fill("""def ecb_rt.{n}(+k: {K}, bs: {L}) -> {{bs == Md.cr.ecb(~{K}, ~{Blk}, ~{dec}, k, Md.cr.ecb(~{K}, ~{Blk}, ~{enc}, k, bs)) : {L}}}:
  match bs:
    case Nil{{}}:
      {{==}}
    case Con{{b, t}}:
      %Equal.sym({Blk}, {dec}(k, {enc}(k, b)), b, {rt}(k, b)) : {{Con{{b, t}} == Con{{_, Md.cr.ecb(~{K}, ~{Blk}, ~{dec}, k, Md.cr.ecb(~{K}, ~{Blk}, ~{enc}, k, t))}} : {L}}}
      %ecb_rt.{n}(k, t) : {{Con{{b, t}} == Con{{b, _}} : {L}}}
      {{==}}

def Laws.{n}_ecb_round_trip(k, bs):
  %Equal.sym({L}, Md.cr.ecb.go(~{K}, ~{Blk}, ~{enc}, k, bs, Nil{{}}), Md.cr.ecb(~{K}, ~{Blk}, ~{enc}, k, bs), ecb_pub(~{K}, ~{Blk}, ~{enc}, k, bs)) : {{Md.cr.ecb.go(~{K}, ~{Blk}, ~{dec}, k, _, Nil{{}}) == bs : {L}}}
  %Equal.sym({L}, Md.cr.ecb.go(~{K}, ~{Blk}, ~{dec}, k, Md.cr.ecb(~{K}, ~{Blk}, ~{enc}, k, bs), Nil{{}}), Md.cr.ecb(~{K}, ~{Blk}, ~{dec}, k, Md.cr.ecb(~{K}, ~{Blk}, ~{enc}, k, bs)), ecb_pub(~{K}, ~{Blk}, ~{dec}, k, Md.cr.ecb(~{K}, ~{Blk}, ~{enc}, k, bs))) : {{_ == bs : {L}}}
  Equal.sym({L}, bs, Md.cr.ecb(~{K}, ~{Blk}, ~{dec}, k, Md.cr.ecb(~{K}, ~{Blk}, ~{enc}, k, bs)), ecb_rt.{n}(k, bs))
""", T))
    # CBC, on blocks
    law("%s_cbc_round_trip" % n, "%s in CBC (modes.bend): decryption undoes encryption, for every key, IV and list of blocks" % c["title"],
        ["+k: %s" % K, "+iv: %s" % Blk, "+bs: %s" % L],
        "{Md.CrCbc.decrypt_blocks(~%s, ~%s, ~%s, ~%s, k, iv, Md.CrCbc.encrypt_blocks(~%s, ~%s, ~%s, ~%s, k, iv, bs)) == bs : %s}"
        % (K, Blk, dec, c["bxor"], K, Blk, enc, c["bxor"], L))
    T["E"] = "Md.cr.cbc.enc(~{K}, ~{Blk}, ~{enc}, ~{bxor}, k, bs, iv)".format(**T)
    T["DE"] = "Md.cr.cbc.dec(~{K}, ~{Blk}, ~{dec}, ~{bxor}, k, {E}, iv)".format(**T)
    T["C"] = "{enc}(k, {bxor}(p, iv))".format(**T)
    T["REST"] = "Md.cr.cbc.dec(~{K}, ~{Blk}, ~{dec}, ~{bxor}, k, Md.cr.cbc.enc(~{K}, ~{Blk}, ~{enc}, ~{bxor}, k, t, {C}), {C})".format(**T)
    proof(fill("""def cbc_rt.{n}(+k: {K}, bs: {L}, +iv: {Blk}) -> {{bs == {DE} : {L}}}:
  match bs:
    case Nil{{}}:
      {{==}}
    case Con{{+p, t}}:
      %Equal.sym({Blk}, {dec}(k, {C}), {bxor}(p, iv), {rt}(k, {bxor}(p, iv))) : {{Con{{p, t}} == Con{{{bxor}(_, iv), {REST}}} : {L}}}
      %{xx}(p, iv) : {{Con{{p, t}} == Con{{_, {REST}}} : {L}}}
      %cbc_rt.{n}(k, t, {C}) : {{Con{{p, t}} == Con{{p, _}} : {L}}}
      {{==}}

def Laws.{n}_cbc_round_trip(k, iv, bs):
  %Equal.sym({L}, Md.cr.cbc.enc.go(~{K}, ~{Blk}, ~{enc}, ~{bxor}, k, bs, iv, Nil{{}}), {E}, cbc_enc_pub(~{K}, ~{Blk}, ~{enc}, ~{bxor}, k, bs, iv)) : {{Md.cr.cbc.dec.go(~{K}, ~{Blk}, ~{dec}, ~{bxor}, k, _, iv, Nil{{}}) == bs : {L}}}
  %Equal.sym({L}, Md.cr.cbc.dec.go(~{K}, ~{Blk}, ~{dec}, ~{bxor}, k, {E}, iv, Nil{{}}), {DE}, cbc_dec_pub(~{K}, ~{Blk}, ~{dec}, ~{bxor}, k, {E}, iv)) : {{_ == bs : {L}}}
  Equal.sym({L}, bs, {DE}, cbc_rt.{n}(k, bs, iv))
""", T))


def call(fn, *args):
    """a def given with its template arguments, called on args"""
    if fn.endswith(")"):
        return fn[:-1] + "".join(", " + a for a in args) + ")" if args else fn
    return "%s(%s)" % (fn, ", ".join(args)) if args else fn


def fill(text, T):
    return text.format(**T)


def stream_laws(c):
    n, S = c["name"], c["S"]
    up = lambda s, m: "%s(%s, %s)" % (c["update"], s, m)
    od = lambda o: "%s(%s)" % (c["out_data"], o)
    os_ = lambda o: "%s(%s)" % (c["out_state"], o)
    law("%s_stream_involution" % n, "%s: from one state, applied twice, the data comes back" % c["title"],
        ["+s: %s" % S, "+m: B.Octets"], "{%s == m : B.Octets}" % od(up("s", od(up("s", "m")))))
    proof("def Laws.%s_stream_involution(s, m):\n  %s(s, m)\n" % (n, c["involution"]))
    law("%s_stream_streaming_data" % n, "%s: the output of a ++ b is the output of a, then of b from the state after a" % c["title"],
        ["+s: %s" % S, "+a: B.Octets", "+b: B.Octets"],
        "{%s == B.Octets.append(%s, %s) : B.Octets}" % (od(up("s", "B.Octets.append(a, b)")), od(up("s", "a")), od(up(os_(up("s", "a")), "b"))))
    proof("def Laws.%s_stream_streaming_data(s, a, b):\n  %s(s, a, b)\n" % (n, c["sdata"]))
    law("%s_stream_streaming_state" % n, "%s: the state after a ++ b is the state after a, then b" % c["title"],
        ["+s: %s" % S, "+a: B.Octets", "+b: B.Octets"],
        "{%s == %s : %s}" % (os_(up("s", "B.Octets.append(a, b)")), os_(up(os_(up("s", "a")), "b")), S))
    proof("def Laws.%s_stream_streaming_state(s, a, b):\n  %s(s, a, b)\n" % (n, c["sstate"]))


def hash_laws(h):
    """HMAC over the hash (hmac.bend): in pieces, from the hash's laws (the
    streaming law, where it has one, for HMAC's state in pieces; split and
    split3 for the tag in pieces)"""
    n, H = h["name"], h["H"]
    tp = ["~%s: %s" % (v, t) for v, t in h["tparams"]]
    tn = "".join(v + ", " for v, _ in h["tparams"])
    init, upd, fin, dig = h["init"], h["update"], h["final"], h["digest"]
    U = lambda s, m: call(upd, s, m)
    F = lambda s: call(fin, s)
    D = lambda m: call(dig, m)
    SP = lambda a, b: h["split"] % (a, b)
    SP3 = lambda a, b, c: h["split3"] % (a, b, c)
    st = "Hm.CrHmacState<%s>" % H
    hupd = lambda s, m: "Hm.CrHmac.update(~%s, ~%s, %s, %s)" % (H, upd, s, m)
    if h["streaming"]:
        S = lambda s, a, b: h["streaming"] % (s, a, b)
        law("hmac_%s_streaming" % n, "HMAC over %s: the state after a ++ b is the state after a, then b" % h["title"],
            tp + ["s: %s" % st, "+a: B.Octets", "+b: B.Octets"],
            "{%s == %s : %s}" % (hupd("s", "B.Octets.append(a, b)"), hupd(hupd("s", "a"), "b"), st))
        proof("""def Laws.hmac_%s_streaming(%ss, a, b):
  match s:
    case Hm.CrHmacState{h, o}:
      %%%s : {Hm.CrHmacState{%s, o} == Hm.CrHmacState{_, o} : %s}
      {==}
""" % (n, tn, S("h", "a", "b"), U("h", "B.Octets.append(a, b)"), st))
    start = "Hm.CrHmac.start(~%s, ~%s, ~%s, kk)" % (H, init, upd)
    law("hmac_%s_split" % n, "HMAC over %s: the tag in pieces is the tag in one call, for every split" % h["title"],
        tp + ["+kk: Hm.CrHmacKey", "+a: B.Octets", "+b: B.Octets"],
        "{Hm.CrHmac.finish(~%s, ~%s, ~%s, ~%s, %s) == Hm.CrHmac.mac(~%s, kk, B.Octets.append(a, b)) : B.Octets}"
        % (H, init, upd, fin, hupd(hupd(start, "a"), "b"), dig))
    inner = D("B.Octets.append(i, B.Octets.append(a, b))")
    rhs = D("B.Octets.append(o, %s)" % inner)
    proof("""def Laws.hmac_%s_split(%skk, a, b):
  match kk:
    case Hm.CrHmacKey{+i, +o}:
      %%Equal.sym(B.Octets, %s, %s, %s) : {%s == %s : B.Octets}
      %%Equal.sym(B.Octets, %s, %s, %s) : {_ == %s : B.Octets}
      {==}
""" % (n, tn,
       F(U(U(U(init, "i"), "a"), "b")), inner, SP3("i", "a", "b"), F(U(U(init, "o"), "_")), rhs,
       F(U(U(init, "o"), inner)), rhs, SP("o", inner), rhs))


for c in BLOCK:
    block_laws(c)
for c in STREAM:
    stream_laws(c)
for h in HASH:
    hash_laws(h)

# ---------------------------------------------------------------- regions

REGIONS = [("LAWS.bend", "laws", lambda: "\n".join(LAWS)), ("PROOF.bend", "proofs", lambda: "\n".join(PROOFS))]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fname, name, body in REGIONS:
        path = os.path.join(PKG, fname)
        with open(path) as f:
            text = f.read()
        begin = "# BEGIN GENERATED by gen/instances.py: %s\n" % name
        end = "# END GENERATED: %s\n" % name
        i, j = text.index(begin) + len(begin), text.index(end)
        new = text[:i] + body() + text[j:]
        if new != text:
            stale.append("%s (%s)" % (fname, name))
            if not check:
                with open(path, "w", newline="\n") as f:
                    f.write(new)
    if check:
        if stale:
            print("out of date (run gen/instances.py): " + ", ".join(stale))
            sys.exit(1)
        print("generated regions up to date")


if __name__ == "__main__":
    main()
