def block_section():
    emit("# The block: its bytes into the state and back\n\n")
    E = ["e%d" % i for i in range(16)]
    emit("def ap.state_back(+e: %s) -> {X.aes.state16(M.cm.bytes_of(M.cm.block_of(A.bytes_of(e)))) == %s : %s}:\n" % (ST, mask("e"), ST))
