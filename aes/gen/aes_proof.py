#!/usr/bin/env python3
"""Writes the AES round-trip proof (the "aes" region of PROOF.bend).

  python3 gen/aes_proof.py           rewrite the region
  python3 gen/aes_proof.py --check   only check that it is up to date

The region proves LAWS.bend's aes_round_trip: CmAes.decrypt undoes
CmAes.encrypt for every key (every value of CmAesKey: any number of rounds
and any round keys) and every block. Encryption is bend-collections'
cipher (src/crypto/aes/aes.bend: cipher, rounds, round, last_round,
sub_bytes, shift_rows, mix_columns, add_round_key; sbox.bend: sbox, xtime,
mul3), read as written; decryption is aes.bend's inverse of it. The proof
goes round by round:

  * bytes: facts about one byte, each checked on all 256 values: the
    inverse S-box undoes the S-box and the S-box gives a byte (ap.e_sbi,
    ap.e_sbl, one exhaustive lemma each); xtime and mul3 give bytes,
    aes.bend's products by {09}, {0b}, {0d}, {0e} are the field's, and the
    sixteen column facts and four sums MixColumns' inverse needs (below),
    in one exhaustive lemma over the list of them (ap.ex2), so that the 256
    cases are written once. Each fact is used on a byte U32.and(255, x),
    rewritten first to its eight bits (ap.bridge): the kernel then never
    evaluates the S-box's circuit on unknown bits, which blows up;
  * InvMixColumns undoes MixColumns on every column of bytes: its products
    are the field's (ap.imixg), each output byte is GF(2^8)-linear in the
    column (bend-osdev-gf's laws: multiplication distributes over addition,
    which is associative and commutative), so it is four rows of four
    products (ap.row), regrouped by input byte (ap.trans: nine applications
    of ap.swap4), and each input byte's four products sum to that byte or
    to zero (ap.ex2);
  * a round, the last round and the first AddRoundKey undone, and the
    output of each made of bytes again, on states of bytes (X.aes.mask);
  * the rounds and the cipher, by induction on the round keys, as
    bend-collections' rounds and cipher recurse;
  * the block: its bytes into the state and back.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")
BEGIN = "# BEGIN GENERATED by gen/aes_proof.py: aes\n"
END = "# END GENERATED: aes\n"

ST = "TT.State"
Q = "TT.Quad"
F = "G.Gf8.aes()"
LU = "List<&2, U32>"
OUT = []


def emit(s):
    OUT.append(s)


def tf(v):
    return "True{}" if v else "False{}"


def byte8(c="c"):
    return "U32{" + "".join("WCon{%s%d, " % (c, i) for i in range(8)) + "Word.zero(24n)" + "}" * 8 + "}"


def pat8(c="c", r="r"):
    return "U32{" + "".join("WCon{%s%d, " % (c, i) for i in range(8)) + r + "}" * 8 + "}"


def c32_():
    return ", ".join("c%d" % k for k in range(32))


def pat32(c):
    return "U32{" + "".join("WCon{%s%d, " % (c, i) for i in range(32)) + "WNil{}" + "}" * 32 + "}"


def Bb(x):
    """a byte's low 8 bits, as aes.mask takes them"""
    return "U32.and(255, %s)" % x


def G2(a, b):
    return "G.Gf8.add(%s, %s)" % (a, b)


def gm(k, x):
    return "G.Gf8.mul(G.Gf8.aes(), %s, %s)" % (k, x)


def xt(x):
    return "SB.xtime(%s)" % x


def m3(x):
    return "SB.mul3(%s)" % x


def quad(xs):
    return "TT.W{%s}" % ", ".join(xs)


def st(xs):
    return "TT.S{%s}" % ", ".join(quad(xs[4 * i:4 * i + 4]) for i in range(4))


def mask(s):
    return "X.aes.mask(%s)" % s


def rw(T, old, new, proof, motive, rhs, GT=None):
    """rewrite old (of type T) into new where proof : {old == new}; motive
    is the goal's left side with _ at old, rhs its (unchanged) right side,
    GT the goal's type (T by default)"""
    return "  %%Equal.sym(%s, %s, %s, %s) : {%s == %s : %s}\n" % (T, old, new, proof, motive, rhs, GT or T)


def rwd(T, proof, motive, rhs):
    """rewrite with proof : {new == old} directly; T is the goal's type"""
    return "  %%%s : {%s == %s : %s}\n" % (proof, motive, rhs, T)


def lst(xs):
    return "[" + ", ".join(xs) + "]"


# ---------------------------------------------------------------- bytes

# MixColumns' four rows on the column (A, B, C, D) (bend-collections'
# mix_column): row i's terms, in variable order, as functions of the
# variable
ROWF = [["xt", "m3", "id", "id"],
        ["id", "xt", "m3", "id"],
        ["id", "id", "xt", "m3"],
        ["m3", "id", "id", "xt"]]
COEF = [14, 11, 13, 9]


def fn(f, x):
    return {"xt": xt, "m3": m3, "id": lambda y: y}[f](x)


def col_group(j, v, x):
    """output byte j takes rows j, j+1, j+2, j+3 (mod 4) with coefficients
    14, 11, 13, 9 (aes.imix_w); variable v's four products, paired"""
    ts = [gm(COEF[i], fn(ROWF[(j + i) % 4][v], x)) for i in range(4)]
    return G2(G2(ts[0], ts[1]), G2(ts[2], ts[3]))


def fin(j, x):
    rs = [x if v == j else "0" for v in range(4)]
    return G2(G2(rs[0], rs[1]), G2(rs[2], rs[3]))


EX1 = [("sbl", lambda x: "SB.sbox(%s)" % x, lambda x: Bb("SB.sbox(%s)" % x)),
       ("sbi", lambda x: "X.aes.isbox(SB.sbox(%s))" % x, lambda x: x)]
EX2 = [("xtb", lambda x: xt(x), lambda x: Bb(xt(x))),
       ("m3b", lambda x: m3(x), lambda x: Bb(m3(x)))]
for _k in [9, 11, 13, 14]:
    EX2.append(("m%db" % _k, (lambda k: lambda x: "X.aes.m%d(%s)" % (k, x))(_k), (lambda k: lambda x: gm(str(k), x))(_k)))
for _j in range(4):
    for _v in range(4):
        EX2.append(("col%d%d" % (_j, _v), (lambda j, v: lambda x: col_group(j, v, x))(_j, _v),
                    (lambda j, v: lambda x: x if v == j else "0")(_j, _v)))
for _j in range(4):
    EX2.append(("fin%d" % _j, (lambda j: lambda x: fin(j, x))(_j), lambda x: x))


def bytes_section():
    emit("# Bytes: facts about one byte, on all 256 values\n\n")
    emit("def ap.nth(xs: %s, n: Nat) -> U32:\n  match xs n:\n    case Nil{} _:\n      0\n"
         "    case Con{x, t} 0n:\n      x\n    case Con{x, t} 1n+p:\n      ap.nth(t, p)\n\n" % LU)
    emit("def ap.pick(+n: Nat, +xs: %s, +ys: %s, e: {xs == ys : %s}) -> {ap.nth(xs, n) == ap.nth(ys, n) : U32}:\n"
         "  Equal.cong(%s, U32, l => ap.nth(l, n), xs, ys, e)\n\n" % (LU, LU, LU, LU))
    params = ", ".join("c%d: Bool" % i for i in range(8))
    cs = ", ".join("c%d" % k for k in range(8))
    x = byte8()
    # a byte's low 8 bits, as the mask gives them: rewriting U32.and(255, x)
    # into this form first keeps the kernel from evaluating the facts below
    # on unknown bits when it compares them
    c32 = c32_()
    emit("def ap.bridge(%s) -> {%s == %s : U32}:\n  {==}\n\n"
         % (", ".join("+c%d: Bool" % i for i in range(32)), x, Bb(pat32("c"))))

    def cases():
        emit("  match %s:\n" % " ".join("c%d" % i for i in range(8)))
        for v in range(256):
            emit("    case %s:\n      {==}\n" % " ".join(tf((v >> i) & 1) for i in range(8)))
        emit("\n")

    # the S-box facts: one exhaustive lemma each (the kernel must never
    # evaluate the S-box's circuit on unknown bits, so each fact's form after
    # the bridge is its lemma's type exactly)
    for f, l, r in EX1:
        emit("def ap.e_%s(%s) -> {%s == %s : U32}:\n" % (f, params, l(x), r(x)))
        cases()
        emit("def ap.%s(+x: U32) -> {%s == %s : U32}:\n  match x:\n    case %s:\n"
             "      %%ap.bridge(%s) : {%s == %s : U32}\n      ap.e_%s(%s)\n\n"
             % (f, l(Bb("x")), r(Bb("x")), pat32("c"), c32, l("_"), r("_"), f, cs))
    # the others: one exhaustive lemma over the list of them
    name, ex = "ex2", EX2
    emit("def ap.%s.l(+x: U32) -> %s:\n  %s\n\n" % (name, LU, lst([l("x") for _, l, r in ex])))
    emit("def ap.%s.r(+x: U32) -> %s:\n  %s\n\n" % (name, LU, lst([r("x") for _, l, r in ex])))
    emit("def ap.%s(%s) -> {ap.%s.l(%s) == ap.%s.r(%s) : %s}:\n" % (name, params, name, x, name, x, LU))
    cases()
    for i, (f, l, r) in enumerate(ex):
        emit("def ap.%s(+x: U32) -> {%s == %s : U32}:\n  match x:\n    case %s:\n"
             "      %%ap.bridge(%s) : {%s == %s : U32}\n      ap.pick(%dn, ap.%s.l(%s), ap.%s.r(%s), ap.%s(%s))\n\n"
             % (f, l(Bb("x")), r(Bb("x")), pat32("c"), c32, l("_"), r("_"), i, name, x, name, x, name, cs))
    emit("def ap.bb(+x: U32) -> {%s == %s : U32}:\n  match x:\n    case %s:\n      {==}\n\n" % (Bb(Bb("x")), Bb("x"), pat32("c")))
    emit("def ap.xorb(+a: U32, +b: U32) -> {%s == %s : U32}:\n"
         "  match a b:\n    case %s %s:\n      {==}\n\n"
         % ("U32.xor(%s, %s)" % (Bb("a"), Bb("b")), Bb("U32.xor(%s, %s)" % (Bb("a"), Bb("b"))), pat32("a"), pat32("b")))
    # bytes' B.byte is the same mask
    emit("def ap.bylo(+x: U32) -> {B.byte(x) == %s : U32}:\n  match x:\n    case %s:\n      {==}\n\n" % (Bb("x"), pat32("c")))
    # x == mask(y) makes x a byte
    emit("def ap.isb(+x: U32, +y: U32, +e: {x == %s : U32}) -> {x == %s : U32}:\n"
         "  %%Equal.sym(U32, x, %s, e) : {_ == U32.and(255, _) : U32}\n"
         "  Equal.sym(U32, %s, %s, ap.bb(y))\n\n" % (Bb("y"), Bb("x"), Bb("y"), Bb(Bb("y")), Bb("y")))
    # GF(2^8): a product of an XOR is the sum of the products
    emit("def ap.gx(+k: U32, +u: U32, +v: U32) -> {%s == %s : U32}:\n  match u v:\n    case %s %s:\n      {==}\n\n"
         % (gm("k", "U32.xor(u, v)"), gm("k", G2("u", "v")), pat8("a", "ra"), pat8("b", "rb")))
    emit("def ap.mx(+k: U32, +u: U32, +v: U32) -> {%s == %s : U32}:\n" % (gm("k", "U32.xor(u, v)"), G2(gm("k", "u"), gm("k", "v"))))
    emit(rw("U32", gm("k", "U32.xor(u, v)"), gm("k", G2("u", "v")), "ap.gx(k, u, v)", "_", G2(gm("k", "u"), gm("k", "v"))))
    emit("  GL.mul_distrib(%s, k, u, v)\n\n" % F)
    # the field's product reads a byte's low 8 bits
    emit("def ap.glo(+k: U32, +x: U32) -> {%s == %s : U32}:\n  match x:\n    case %s:\n      {==}\n\n"
         % (gm("k", Bb("x")), gm("k", "x"), pat32("c")))
    for k in [9, 11, 13, 14]:
        # aes.m<k>(x) is aes.c<k> of x's low byte: the field's product
        emit("def ap.m%d(+x: U32) -> {X.aes.m%d(x) == %s : U32}:\n" % (k, k, gm(str(k), "x")))
        emit(rw("U32", Bb("x"), Bb(Bb("x")), "Equal.sym(U32, %s, %s, ap.bb(x))" % (Bb(Bb("x")), Bb("x")), "X.aes.c%d(_)" % k, gm(str(k), "x")))
        emit("  %%ap.glo(%d, x) : {X.aes.c%d(%s) == _ : U32}\n" % (k, k, Bb(Bb("x"))))
        emit("  ap.m%db(x)\n\n" % k)
    emit("def ap.xg0(m1: G.Gf8Bits, m2: G.Gf8Bits) -> {U32.xor(G.Gf8Bits.to(m1), G.Gf8Bits.to(m2)) == %s : U32}:\n"
         "  match m1 m2:\n    case G.Gf8Bits{%s} G.Gf8Bits{%s}:\n      {==}\n\n"
         % (G2("G.Gf8Bits.to(m1)", "G.Gf8Bits.to(m2)"), ", ".join("a%d" % i for i in range(8)), ", ".join("b%d" % i for i in range(8))))
    emit("def ap.xg(+k1: U32, +k2: U32, +u: U32, +v: U32) -> {U32.xor(%s, %s) == %s : U32}:\n"
         "  ap.xg0(G.Gf8Bits.mul(G.Gf8Bits.of(k1), G.Gf8Bits.of(u), G.Gf8Bits.of(283)), G.Gf8Bits.mul(G.Gf8Bits.of(k2), G.Gf8Bits.of(v), G.Gf8Bits.of(283)))\n\n"
         % (gm("k1", "u"), gm("k2", "v"), G2(gm("k1", "u"), gm("k2", "v"))))
    # InvMixColumns' output byte, as the field's sum of products
    gform = G2(G2(gm("14", "p"), gm("11", "q")), G2(gm("13", "r"), gm("9", "s")))
    emit("def ap.imixg(+p: U32, +q: U32, +r: U32, +s: U32) -> {X.aes.imix0(p, q, r, s) == %s : U32}:\n" % gform)
    cur = ["X.aes.m14(p)", "X.aes.m11(q)", "X.aes.m13(r)", "X.aes.m9(s)"]
    new = [gm("14", "p"), gm("11", "q"), gm("13", "r"), gm("9", "s")]
    lem = ["ap.m14(p)", "ap.m11(q)", "ap.m13(r)", "ap.m9(s)"]

    def xform(cs):
        return "U32.xor(U32.xor(%s, %s), U32.xor(%s, %s))" % tuple(cs)

    for i in range(4):
        nxt = cur[:]
        nxt[i] = "_"
        emit(rw("U32", cur[i], new[i], lem[i], xform(nxt), gform))
        cur[i] = new[i]
    emit(rw("U32", "U32.xor(%s, %s)" % (new[0], new[1]), G2(new[0], new[1]), "ap.xg(14, 11, p, q)", "U32.xor(_, U32.xor(%s, %s))" % (new[2], new[3]), gform))
    emit(rw("U32", "U32.xor(%s, %s)" % (new[2], new[3]), G2(new[2], new[3]), "ap.xg(13, 9, r, s)", "U32.xor(%s, _)" % G2(new[0], new[1]), gform))
    emit("  ap.xg0(G.Gf8Bits.xor(G.Gf8Bits.of(%s), G.Gf8Bits.of(%s)), G.Gf8Bits.xor(G.Gf8Bits.of(%s), G.Gf8Bits.of(%s)))\n\n" % (new[0], new[1], new[2], new[3]))


# ---------------------------------------------------------------- MixColumns

V = [Bb(v) for v in "abcd"]


def row_terms(i):
    return [fn(ROWF[i][v], V[v]) for v in range(4)]


def row_xor(i):
    return "U32.xor(U32.xor(U32.xor(%s, %s), %s), %s)" % tuple(row_terms(i))


def mix_section():
    emit("# MixColumns undone, a column at a time\n\n")
    a, b, c, d = "a", "b", "c", "d"
    rhs = G2(G2(a, c), G2(b, d))
    emit("def ap.swap4(+a: U32, +b: U32, +c: U32, +d: U32) -> {%s == %s : U32}:\n" % (G2(G2(a, b), G2(c, d)), rhs))
    # G(G(a,b),G(c,d)) -> G(a, G(b, G(c,d)))
    emit(rw("U32", G2(G2(a, b), G2(c, d)), G2(a, G2(b, G2(c, d))), "GL.add_assoc(a, b, %s)" % G2(c, d), "_", rhs))
    # G(b, G(c,d)) -> G(G(b,c), d)   (assoc(b,c,d) : G(G(b,c),d) == G(b,G(c,d)))
    emit(rwd("U32", "GL.add_assoc(b, c, d)", G2("a", "_"), rhs))
    # G(b, c) -> G(c, b)
    emit(rw("U32", G2(b, c), G2(c, b), "GL.add_comm(b, c)", G2("a", G2("_", d)), rhs))
    # G(G(c,b), d) -> G(c, G(b, d))
    emit(rw("U32", G2(G2(c, b), d), G2(c, G2(b, d)), "GL.add_assoc(c, b, d)", G2("a", "_"), rhs))
    # G(a, G(c, G(b,d))) -> G(G(a,c), G(b,d))
    emit(rwd("U32", "GL.add_assoc(a, c, %s)" % G2(b, d), "_", rhs))
    emit("  {==}\n\n")
    # trans
    t = [["t%d%d" % (i, v) for v in range(4)] for i in range(4)]
    P = [G2(t[i][0], t[i][1]) for i in range(4)]
    Qr = [G2(t[i][2], t[i][3]) for i in range(4)]
    R = [G2(P[i], Qr[i]) for i in range(4)]
    C = [G2(G2(t[0][v], t[1][v]), G2(t[2][v], t[3][v])) for v in range(4)]
    lhs = G2(G2(R[0], R[1]), G2(R[2], R[3]))
    rhs = G2(G2(C[0], C[1]), G2(C[2], C[3]))
    params = ", ".join("+t%d%d: U32" % (i, v) for i in range(4) for v in range(4))
    emit("def ap.trans(%s) -> {%s == %s : U32}:\n" % (params, lhs, rhs))
    A01 = G2(G2(P[0], P[1]), G2(Qr[0], Qr[1]))
    A23 = G2(G2(P[2], P[3]), G2(Qr[2], Qr[3]))
    emit(rw("U32", G2(R[0], R[1]), A01, "ap.swap4(%s, %s, %s, %s)" % (P[0], Qr[0], P[1], Qr[1]), G2("_", G2(R[2], R[3])), rhs))
    emit(rw("U32", G2(R[2], R[3]), A23, "ap.swap4(%s, %s, %s, %s)" % (P[2], Qr[2], P[3], Qr[3]), G2(A01, "_"), rhs))
    PP = G2(G2(P[0], P[1]), G2(P[2], P[3]))
    QQ = G2(G2(Qr[0], Qr[1]), G2(Qr[2], Qr[3]))
    emit(rw("U32", G2(A01, A23), G2(PP, QQ), "ap.swap4(%s, %s, %s, %s)" % (G2(P[0], P[1]), G2(Qr[0], Qr[1]), G2(P[2], P[3]), G2(Qr[2], Qr[3])), "_", rhs))
    B01 = G2(G2(t[0][0], t[1][0]), G2(t[0][1], t[1][1]))
    B23 = G2(G2(t[2][0], t[3][0]), G2(t[2][1], t[3][1]))
    emit(rw("U32", G2(P[0], P[1]), B01, "ap.swap4(%s, %s, %s, %s)" % (t[0][0], t[0][1], t[1][0], t[1][1]), G2(G2("_", G2(P[2], P[3])), QQ), rhs))
    emit(rw("U32", G2(P[2], P[3]), B23, "ap.swap4(%s, %s, %s, %s)" % (t[2][0], t[2][1], t[3][0], t[3][1]), G2(G2(B01, "_"), QQ), rhs))
    emit(rw("U32", G2(B01, B23), G2(C[0], C[1]), "ap.swap4(%s, %s, %s, %s)" % (G2(t[0][0], t[1][0]), G2(t[0][1], t[1][1]), G2(t[2][0], t[3][0]), G2(t[2][1], t[3][1])), G2("_", QQ), rhs))
    D01 = G2(G2(t[0][2], t[1][2]), G2(t[0][3], t[1][3]))
    D23 = G2(G2(t[2][2], t[3][2]), G2(t[2][3], t[3][3]))
    CC = G2(C[0], C[1])
    emit(rw("U32", G2(Qr[0], Qr[1]), D01, "ap.swap4(%s, %s, %s, %s)" % (t[0][2], t[0][3], t[1][2], t[1][3]), G2(CC, G2("_", G2(Qr[2], Qr[3]))), rhs))
    emit(rw("U32", G2(Qr[2], Qr[3]), D23, "ap.swap4(%s, %s, %s, %s)" % (t[2][2], t[2][3], t[3][2], t[3][3]), G2(CC, G2(D01, "_")), rhs))
    emit(rw("U32", G2(D01, D23), G2(C[2], C[3]), "ap.swap4(%s, %s, %s, %s)" % (G2(t[0][2], t[1][2]), G2(t[0][3], t[1][3]), G2(t[2][2], t[3][2]), G2(t[2][3], t[3][3])), G2(CC, "_"), rhs))
    emit("  {==}\n\n")
    # row
    xr = "U32.xor(U32.xor(U32.xor(x1, x2), x3), x4)"
    rr = G2(G2(gm("k", "x1"), gm("k", "x2")), G2(gm("k", "x3"), gm("k", "x4")))
    emit("def ap.row(+k: U32, +x1: U32, +x2: U32, +x3: U32, +x4: U32) -> {%s == %s : U32}:\n" % (gm("k", xr), rr))
    emit(rw("U32", gm("k", xr), G2(gm("k", "U32.xor(U32.xor(x1, x2), x3)"), gm("k", "x4")), "ap.mx(k, U32.xor(U32.xor(x1, x2), x3), x4)", "_", rr))
    emit(rw("U32", gm("k", "U32.xor(U32.xor(x1, x2), x3)"), G2(gm("k", "U32.xor(x1, x2)"), gm("k", "x3")), "ap.mx(k, U32.xor(x1, x2), x3)", G2("_", gm("k", "x4")), rr))
    emit(rw("U32", gm("k", "U32.xor(x1, x2)"), G2(gm("k", "x1"), gm("k", "x2")), "ap.mx(k, x1, x2)", G2(G2("_", gm("k", "x3")), gm("k", "x4")), rr))
    emit("  GL.add_assoc(%s, %s, %s)\n\n" % (G2(gm("k", "x1"), gm("k", "x2")), gm("k", "x3"), gm("k", "x4")))
    rows = [row_xor(i) for i in range(4)]

    def whole(cs):
        return G2(G2(cs[0], cs[1]), G2(cs[2], cs[3]))

    for j in range(4):
        args = [rows[(j + i) % 4] for i in range(4)]
        target = V[j]
        cur = [gm(COEF[i], args[i]) for i in range(4)]
        emit("def ap.out%d(+a: U32, +b: U32, +c: U32, +d: U32) -> {%s == %s : U32}:\n" % (j, whole(cur), target))
        terms = [[gm(COEF[i], fn(ROWF[(j + i) % 4][v], V[v])) for v in range(4)] for i in range(4)]
        rowsum = [G2(G2(terms[i][0], terms[i][1]), G2(terms[i][2], terms[i][3])) for i in range(4)]
        for i in range(4):
            nxt = cur[:]
            nxt[i] = "_"
            emit(rw("U32", cur[i], rowsum[i], "ap.row(%d, %s)" % (COEF[i], ", ".join(row_terms((j + i) % 4))), whole(nxt), target))
            cur[i] = rowsum[i]
        cols = [G2(G2(terms[0][v], terms[1][v]), G2(terms[2][v], terms[3][v])) for v in range(4)]
        emit(rw("U32", whole(cur), whole(cols), "ap.trans(%s)" % ", ".join(terms[i][v] for i in range(4) for v in range(4)), "_", target))
        cur = cols[:]
        for v in range(4):
            nxt = cur[:]
            nxt[v] = "_"
            res = V[v] if v == j else "0"
            emit(rw("U32", cur[v], res, "ap.col%d%d(%s)" % (j, v, "abcd"[v]), whole(nxt), target))
            cur[v] = res
        emit("  ap.fin%d(%s)\n\n" % (j, "abcd"[j]))
    cin = quad(V)
    emit("def ap.mixc(+a: U32, +b: U32, +c: U32, +d: U32) -> {X.aes.imix_w(A.mix_column(%s)) == %s : %s}:\n" % (cin, cin, Q))
    cur = ["X.aes.imix0(%s)" % ", ".join(rows[(j + i) % 4] for i in range(4)) for j in range(4)]
    for j in range(4):
        args = [rows[(j + i) % 4] for i in range(4)]
        gform = whole([gm(COEF[i], args[i]) for i in range(4)])
        nxt = cur[:]
        nxt[j] = "_"
        emit(rw("U32", cur[j], gform, "ap.imixg(%s)" % ", ".join(args), quad(nxt), cin, Q))
        emit(rw("U32", gform, V[j], "ap.out%d(a, b, c, d)" % j, quad(nxt), cin, Q))
        cur[j] = V[j]
    emit("  {==}\n\n")
    # MixColumns' outputs are bytes
    for i in range(4):
        ts = row_terms(i)
        bs = []
        for v in range(4):
            f = ROWF[i][v]
            bs.append(Bb(ts[v]) if f != "id" else ts[v])
        # after the terms are bytes: U32.xor(U32.xor(U32.xor(b0, b1), b2), b3) with each bk = B.byte(_)
        w1 = "U32.xor(%s, %s)" % (bs[0], bs[1])
        w2 = "U32.xor(%s, %s)" % (Bb(w1), bs[2])
        w3 = "U32.xor(%s, %s)" % (Bb(w2), bs[3])
        emit("def ap.rowb%d(+a: U32, +b: U32, +c: U32, +d: U32) -> {%s == %s : U32}:\n" % (i, rows[i], Bb(w3)))
        cur = ts[:]

        def form(cs):
            return "U32.xor(U32.xor(U32.xor(%s, %s), %s), %s)" % tuple(cs)

        for v in range(4):
            f = ROWF[i][v]
            if f == "id":
                continue
            nxt = cur[:]
            nxt[v] = "_"
            emit(rw("U32", cur[v], bs[v], "ap.%sb(%s)" % (f, "abcd"[v]), form(nxt), Bb(w3)))
            cur[v] = bs[v]
        # each term is the mask of u: the variable itself, or its xtime or mul3
        u = [ts[v] if ROWF[i][v] != "id" else "abcd"[v] for v in range(4)]
        emit(rw("U32", w1, Bb(w1), "ap.xorb(%s, %s)" % (u[0], u[1]), "U32.xor(U32.xor(_, %s), %s)" % (bs[2], bs[3]), Bb(w3)))
        emit(rw("U32", w2, Bb(w2), "ap.xorb(%s, %s)" % (w1, u[2]), "U32.xor(_, %s)" % bs[3], Bb(w3)))
        emit(rw("U32", w3, Bb(w3), "ap.xorb(%s, %s)" % (w2, u[3]), "_", Bb(w3)))
        emit("  {==}\n\n")
    rhsq = "X.aes.mask_w(A.mix_column(%s))" % cin
    emit("def ap.mixcb(+a: U32, +b: U32, +c: U32, +d: U32) -> {A.mix_column(%s) == %s : %s}:\n" % (cin, rhsq, Q))
    cur = rows[:]
    for i in range(4):
        nxt = cur[:]
        nxt[i] = "_"
        ts = row_terms(i)
        bs = [Bb(ts[v]) if ROWF[i][v] != "id" else ts[v] for v in range(4)]
        w1 = "U32.xor(%s, %s)" % (bs[0], bs[1])
        w2 = "U32.xor(%s, %s)" % (Bb(w1), bs[2])
        w3 = "U32.xor(%s, %s)" % (Bb(w2), bs[3])
        emit(rw("U32", rows[i], Bb(rows[i]), "ap.isb(%s, %s, ap.rowb%d(a, b, c, d))" % (rows[i], w3, i), quad(nxt), rhsq, Q))
        cur[i] = Bb(rows[i])
    emit("  {==}\n\n")


