#!/usr/bin/env python3
"""Writes SM3's compression function, unrolled, from the specification's
tables (gen/spec.py).

  python3 gen/rounds.py           rewrite the generated region
  python3 gen/rounds.py --check   only check that it is up to date

The region lies between "# BEGIN GENERATED by gen/rounds.py: sm3" and
"# END GENERATED: sm3" in sm3.bend; everything else is written by hand.
It holds one def, hs.sm3.rounds(x, cv): the sixteen words of a block and
the chaining value in, the next chaining value out. Every step of the
specification is one line, binding a fresh name (v<i> for chaining words,
w<j> for the expanded message), so the code reads as the specification's
step list and needs no indexing at run time.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")
sys.dont_write_bytecode = True
sys.path.insert(0, HERE)
import spec  # noqa: E402

XS = ", ".join("+x%d" % i for i in range(16))
W16 = "Hs.HsW16{%s}" % XS


def rot(n, j):
    """the constant n rotated left by j"""
    j %= 32
    return ((n << j) | (n >> (32 - j))) & 0xFFFFFFFF if j else n


class Names:
    def __init__(self):
        self.i = 0

    def new(self):
        self.i += 1
        return "v%d" % self.i


def add(*xs):
    t = xs[0]
    for x in xs[1:]:
        t = "U32.add(%s, %s)" % (t, x)
    return t


def sm3():
    out = ["def hs.sm3.rounds(x: Hs.HsW16, cv: Hs.HsW8) -> Hs.HsW8:",
           "  match x cv:",
           "    case %s Hs.HsW8{+a0, +b0, +c0, +d0, +e0, +f0, +g0, +h0}:" % W16]
    W = ["x%d" % i for i in range(16)]

    def expand(j):
        w = "w%d" % j
        out.append("      +%s = U32.xor(U32.xor(hs.sm3.p1(U32.xor(U32.xor(%s, %s), Hs.hs.rotl(%s, 15n))), Hs.hs.rotl(%s, 7n)), %s)"
                   % (w, W[j - 16], W[j - 9], W[j - 3], W[j - 13], W[j - 6]))
        W.append(w)

    A, B, C, D, E, F, G, H = "a0", "b0", "c0", "d0", "e0", "f0", "g0", "h0"
    n = Names()
    for j in range(64):
        if j % 16 == 0:
            out.append("      # rounds %d to %d" % (j, j + 15))
        while len(W) <= j + 4:
            expand(len(W))
        ff, gg = ("hs.sm3.ff0", "hs.sm3.gg0") if j < 16 else ("hs.sm3.ff1", "hs.sm3.gg1")
        a12 = n.new()
        out.append("      +%s = Hs.hs.rotl(%s, 12n)" % (a12, A))
        ss1 = n.new()
        out.append("      +%s = Hs.hs.rotl(%s, 7n)" % (ss1, add(a12, E, str(rot(spec.SM3_T[j], j)))))
        tt1 = n.new()
        out.append("      +%s = %s" % (tt1, add("%s(%s, %s, %s)" % (ff, A, B, C), D, "U32.xor(%s, %s)" % (ss1, a12), "U32.xor(%s, %s)" % (W[j], W[j + 4]))))
        tt2 = n.new()
        out.append("      +%s = %s" % (tt2, add("%s(%s, %s, %s)" % (gg, E, F, G), H, ss1, W[j])))
        nc, ng, ne = n.new(), n.new(), n.new()
        out.append("      +%s = Hs.hs.rotl(%s, 9n)" % (nc, B))
        out.append("      +%s = Hs.hs.rotl(%s, 19n)" % (ng, F))
        out.append("      +%s = hs.sm3.p0(%s)" % (ne, tt2))
        A, B, C, D = tt1, A, nc, C
        E, F, G, H = ne, E, ng, G
    out.append("      Hs.HsW8{%s}" % ", ".join("U32.xor(%s, %s)" % p for p in
                                             [("a0", A), ("b0", B), ("c0", C), ("d0", D), ("e0", E), ("f0", F), ("g0", G), ("h0", H)]))
    return "\n".join(out) + "\n"


REGIONS = [("sm3.bend", "sm3", sm3)]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fname, name, body in REGIONS:
        path = os.path.join(PKG, fname)
        with open(path) as f:
            text = f.read()
        begin = "# BEGIN GENERATED by gen/rounds.py: %s\n" % name
        end = "# END GENERATED: %s\n" % name
        i, j = text.index(begin) + len(begin), text.index(end)
        new = text[:i] + body() + text[j:]
        if new != text:
            stale.append(fname)
            if not check:
                with open(path, "w", newline="\n") as f:
                    f.write(new)
    if check:
        if stale:
            print("out of date (run gen/rounds.py): " + ", ".join(stale))
            sys.exit(1)
        print("generated regions up to date")


if __name__ == "__main__":
    main()
