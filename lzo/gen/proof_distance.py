#!/usr/bin/env python3
"""Prints the generated part of ../proof_distance.bend: the value of the
distance field D of M3 and M4, for the bytes lo and hi given by their 16 bits
(deep patterns that are tedious to write by hand). proof_distance.bend holds
it after the "# generated by gen/proof_distance.py (d14)" line. Run it and
paste the part:

    proof_distance.py d14
"""
import sys

def wlist(bits, tail):
    s = tail
    for b in reversed(bits):
        s = 'WCon{%s, %s}' % (b, s)
    return s

L = ['l%d' % i for i in range(8)]
H = ['h%d' % i for i in range(8)]
L8 = wlist(L, 'WNil{}')
H8 = wlist(H, 'WNil{}')
LO = 'U32{%s}' % wlist(L, 'Word.zero(24n)')
HI = 'U32{%s}' % wlist(H, 'Word.zero(24n)')
W14 = wlist(['Bool.or(%s, False{})' % l for l in L[2:]] + H, 'WNil{}')
W15 = wlist(['Bool.or(%s, False{})' % l for l in L[2:]] + H + ['False{}'], 'WNil{}')
bits_params = ', '.join('+%s: Bool' % b for b in L + H)
bits_args = ', '.join(L + H)
D14 = 'U32.shrn(U32.or(%s, U32.shln(%s, 8n)), 2n)' % (LO, HI)
VLO = 'Word.to_nat(8n, %s)' % L8
VHI = 'Word.to_nat(8n, %s)' % H8

part = r'''
def ld.d14_v(%BP%) -> {U32.to_nat(%D14%) == Nat.div(Nat.add(U32.to_nat(%LO%), Nat.mul(U32.to_nat(%HI%), 256n)), 4n) : Nat}:
  +vl = ld.zext(8n, 24n, %L8%)
  +vh16 = ld.zext(8n, 16n, %H8%)
  +vh = ld.zext(8n, 24n, %H8%)
  +es = Equal.cong(Nat, Nat, z => U.U32Nat.dbl(8n, z), Word.to_nat(24n, ld.cat(8n, 16n, %H8%, Word.zero(16n))), Word.to_nat(32n, ld.cat(8n, 24n, %H8%, Word.zero(24n))), Equal.trans(Nat, Word.to_nat(24n, ld.cat(8n, 16n, %H8%, Word.zero(16n))), %VHI%, Word.to_nat(32n, ld.cat(8n, 24n, %H8%, Word.zero(24n))), vh16, Equal.sym(Nat, Word.to_nat(32n, ld.cat(8n, 24n, %H8%, Word.zero(24n))), %VHI%, vh)))
  +hl = ld.lt_rw(%VLO%, U32.to_nat(%LO%), U.U32Nat.dbl(8n, 1n), U.U32Nat.dbl(8n, 1n), Equal.sym(Nat, U32.to_nat(%LO%), %VLO%, vl), {==}, UL.word_value_lt(8n, %L8%))
  +ev = Equal.trans(Nat, U32.to_nat(U32.or(%LO%, U32.shln(%HI%, 8n))), U32.to_nat(U32.or(U32.shln(%HI%, 8n), %LO%)), Nat.add(U32.to_nat(U32.shln(%HI%, 8n)), U32.to_nat(%LO%)), Equal.cong(U32, Nat, u => U32.to_nat(u), U32.or(%LO%, U32.shln(%HI%, 8n)), U32.or(U32.shln(%HI%, 8n), %LO%), UL.u32_or_comm(%LO%, U32.shln(%HI%, 8n))), UL.u32_or_split(U32.shln(%HI%, 8n), %LO%, 8n, U32.to_nat(%HI%), es, hl))
  +ew = Equal.trans(Nat, Nat.add(U32.to_nat(U32.shln(%HI%, 8n)), U32.to_nat(%LO%)), Nat.add(Nat.mul(U32.to_nat(%HI%), 256n), U32.to_nat(%LO%)), Nat.add(U32.to_nat(%LO%), Nat.mul(U32.to_nat(%HI%), 256n)), Equal.cong(Nat, Nat, z => Nat.add(z, U32.to_nat(%LO%)), U32.to_nat(U32.shln(%HI%, 8n)), Nat.mul(U32.to_nat(%HI%), 256n), Equal.trans(Nat, U32.to_nat(U32.shln(%HI%, 8n)), U.U32Nat.dbl(8n, U32.to_nat(%HI%)), Nat.mul(U32.to_nat(%HI%), 256n), es, ld.dbl_mul(8n, U32.to_nat(%HI%)))), UL.nat_add_comm(Nat.mul(U32.to_nat(%HI%), 256n), U32.to_nat(%LO%)))
  Equal.trans(Nat, U32.to_nat(%D14%), Nat.div(U32.to_nat(U32.or(%LO%, U32.shln(%HI%, 8n))), 4n), Nat.div(Nat.add(U32.to_nat(%LO%), Nat.mul(U32.to_nat(%HI%), 256n)), 4n), ld.u_shr2(U32.or(%LO%, U32.shln(%HI%, 8n))), Equal.cong(Nat, Nat, z => Nat.div(z, 4n), U32.to_nat(U32.or(%LO%, U32.shln(%HI%, 8n))), Nat.add(U32.to_nat(%LO%), Nat.mul(U32.to_nat(%HI%), 256n)), Equal.trans(Nat, U32.to_nat(U32.or(%LO%, U32.shln(%HI%, 8n))), Nat.add(U32.to_nat(U32.shln(%HI%, 8n)), U32.to_nat(%LO%)), Nat.add(U32.to_nat(%LO%), Nat.mul(U32.to_nat(%HI%), 256n)), ev, ew)))

# the D word is its 14 bits (or 15, the top one 0), zero above
def ld.d14_w(%BP%) -> {U32.to_nat(%D14%) == U32.to_nat(U32{ld.cat(14n, 18n, %W14%, Word.zero(18n))}) : Nat}:
  {==}

def ld.d14_w15(%BP%) -> {U32.to_nat(%D14%) == U32.to_nat(U32{ld.cat(15n, 17n, %W15%, Word.zero(17n))}) : Nat}:
  {==}
'''
part = (part.replace('%BP%', bits_params).replace('%BA%', bits_args).replace('%D14%', D14)
        .replace('%VLO%', VLO).replace('%VHI%', VHI).replace('%L8%', L8).replace('%H8%', H8)
        .replace('%LO%', LO).replace('%HI%', HI).replace('%W14%', W14).replace('%W15%', W15))

PARTS = {'d14': part}

if __name__ == '__main__':
    if len(sys.argv) != 2 or sys.argv[1] not in PARTS:
        sys.exit(__doc__)
    sys.stdout.write(PARTS[sys.argv[1]].strip(chr(10)) + chr(10))
