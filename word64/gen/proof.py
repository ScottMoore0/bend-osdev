#!/usr/bin/env python3
"""Writes word64's further proof files: PROOF_bits.bend (the bitwise
operations and the one-bit shift), PROOF_mul.bend (mulhi from 16-bit
partial products, mul from the halves), PROOF_div.bend (the 64 steps of
shift and subtract) and PROOF_text.bend (decimal text), the proofs of the
laws of LAWS_<part>.bend; PROOF.bend is written by hand. Each file starts
with the bound helpers (helpers()); a part that uses another's laws or
lemmas imports that pair (PARTS). Ring identities are written by
scripts/natproof.py from bend-osdev-u32's Nat laws.

Run: python3 word64/gen/proof.py

A bound such as "a word's value is below 2^64" is a closed power of two, and
the checkers expand one whenever they compare a type holding it by
computation (u32/README.md, "Stating the bounds"). So every lemma that
reasons with a bound takes the width (n, N) as a variable, and a bound on a
U32 or W64 value is made once, in the exact form a lemma's hypothesis has
(wu.lt, wv.lt64: a rewrite keeps the closed power out of any comparison),
and handed to the lemma whole.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "scripts"))
import natproof as N  # noqa: E402
from natproof import P, Pf, calc, cast, chain, hyp, ring, rewrite, sym, trans  # noqa: E402

N.CFG["law"] = "UL."
N.OUT.prefix = "wr.r"
OUTF = os.path.join(HERE, "..", "PROOF.bend")
MARK = "# ---- generated by gen/proof.py from here on: do not edit by hand ----"

out = []
_flushed = [0]


def put(s=""):
    defs = N.OUT.defs[_flushed[0]:]
    if defs:
        out.append("\n".join(defs))
        _flushed[0] = len(N.OUT.defs)
    out.append(s)


def btrue(e):
    return "{" + f"{e} == True{{}} : Bool" + "}"


def bcong(var, body, a, b, e):
    return f"Equal.cong(Nat, Bool, {var} => {body}, {P(a)}, {P(b)}, {e})"


def btrans(a, b, c, ab, bc):
    return f"Equal.trans(Bool, {a}, {b}, {c}, {ab}, {bc})"


def bsym(a, b, e):
    return f"Equal.sym(Bool, {a}, {b}, {e})"


def le_from(x, y, w, pf):
    x, y = P(x), P(y)
    s = N.add(P(w), x)
    assert pf.lhs == s and pf.rhs == y, (pf, s, y)
    return btrans(f"Nat.is_le({x}, {y})", f"Nat.is_le({x}, {s})", "True{}",
                  bsym(f"Nat.is_le({x}, {s})", f"Nat.is_le({x}, {y})", bcong("zz", f"Nat.is_le({x}, zz)", s, y, pf.text)),
                  f"UL.nat_le_add({x}, {P(w)})")


def lt_from(x, y, w, pf):
    x, y = P(x), P(y)
    s = N.add(P(w), N.succ(x))
    assert pf.lhs == s and pf.rhs == y, (pf, s, y)
    return btrans(f"Nat.is_lt({x}, {y})", f"Nat.is_lt({x}, {s})", "True{}",
                  bsym(f"Nat.is_lt({x}, {s})", f"Nat.is_lt({x}, {y})", bcong("zz", f"Nat.is_lt({x}, zz)", s, y, pf.text)),
                  f"UL.nat_lt_add({x}, {P(w)})")


def lt_rw(x, y, x2, y2, ex, ey, h):
    """{is_lt(x2, y2) == True} from h : {is_lt(x, y) == True}, ex : x == x2, ey : y == y2 (texts or None)."""
    cur = h
    a, b = x, y
    if ex is not None:
        cur = btrans(f"Nat.is_lt({x2}, {b})", f"Nat.is_lt({a}, {b})", "True{}", bcong("zz", f"Nat.is_lt(zz, {b})", x2, a, f"Equal.sym(Nat, {a}, {x2}, {ex})"), cur)
        a = x2
    if ey is not None:
        cur = btrans(f"Nat.is_lt({a}, {y2})", f"Nat.is_lt({a}, {b})", "True{}", bcong("zz", f"Nat.is_lt({a}, zz)", y2, b, f"Equal.sym(Nat, {b}, {y2}, {ey})"), cur)
    return cur


def wit_lt(x, y, h):
    """(w, proof add(w, 1n+x) == y) from h : x < y."""
    w = f"Nat.sub({y}, 1n+{x})"
    return w, hyp(f"UL.nat_lt_witness({x}, {y}, {h})", f"Nat.add({w}, 1n+{x})", y)


def wit_le(x, y, h):
    w = f"Nat.sub({y}, {x})"
    return w, hyp(f"UL.nat_le_witness({x}, {y}, {h})", f"Nat.add({w}, {x})", y)


def absurd(ty, w, x, pf):
    w, x = P(w), P(x)
    assert pf.lhs == N.add(w, N.succ(x)) and pf.rhs == x, pf
    return f"Empty.absurd({ty}, UL.nat_succ_add_absurd({w}, {x}, {pf.text}))"


def law(name, lhs, rhs, *args, mod="UL"):
    return Pf(lhs, rhs, f"{mod}.{name}({', '.join(str(a) for a in args)})")


def D(k, x):
    return f"U.U32Nat.dbl({k}, {x})"


def low(k, x):
    return f"U.U32Nat.low({k}, {x})"


def high(k, x):
    return f"U.U32Nat.high({k}, {x})"


def bit(b):
    return f"U.U32Nat.bit({b})"


def v32(x):
    return f"U32.to_nat({x})"


def v64(x):
    return f"W.W64.to_nat({x})"


