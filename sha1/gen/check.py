#!/usr/bin/env python3
"""Writes sha1/check.bend: SHA-1 on the specification's vectors, whole and in
three pieces, through the public interface, with the expected output (the
specification's values, from ref/model.py's tables) as the file's #|
lines.

  python3 gen/check.py           rewrite check.bend
  python3 gen/check.py --check   only check that it is up to date

Beside the laws' vectors, check.bend runs a million bytes "a" (FIPS
180-2's third example, which hashlib also gives), too long for the kernel.
"""
import hashlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.join(PKG, "ref"))
import model  # noqa: E402

MILLION_A_SHA1 = "34aa973cd4c4daa4f61eeb2bdbad27316534016f"
assert hashlib.sha1(b"a" * 1000000).hexdigest() == MILLION_A_SHA1


def octets(bs):
    s = bs.decode("latin-1")
    if all(32 <= ord(c) < 127 and c not in '"\\' for c in s):
        return 'B.Octets.of_string("%s")' % s
    return "B.Octets.of_list([%s])" % ", ".join(str(b) for b in bs)


HASHES = {  # name: (digest, init, update, final)
    "sha1": ("S1.HsSha1.digest", "S1.HsSha1.init()", "S1.HsSha1.update", "S1.HsSha1.final"),
}

VECTORS = [("sha1", m, v) for m, v in model.SHA1_V]

HEADER = '''# Generated by gen/check.py; do not edit by hand.
#
# SHA-1 on FIPS 180-4's examples, through the public interface: the
# digest in one call, then the same message fed in three pieces (init,
# three updates, final); then a million bytes "a" (FIPS 180-2's third
# example). The values are the specifications' (the #| lines).
import Base
import ../bytes/bytes.bend as B
import ../md-engine/md-engine.bend as Hs
import ./sha1.bend as S1

# a byte string in three pieces: [0, n/3), [n/3, 2n/3), [2n/3, n)
def third(+o: B.Octets) -> Nat:
  Nat.div(B.Octets.len(o), 3n)

def p1(+o: B.Octets) -> B.Octets:
  B.Octets.take(third(o), o)

def p2(+o: B.Octets) -> B.Octets:
  B.Octets.take(third(o), B.Octets.drop(third(o), o))

def p3(+o: B.Octets) -> B.Octets:
  B.Octets.drop(Nat.mul(2n, third(o)), o)

# n bytes "a", built tail-recursively
def as.go(n: Nat, acc: List<&2, U32>) -> List<&2, U32>:
  match n:
    case 0n:
      acc
    case 1n+p:
      as.go(p, Con{97, acc})

def million_a() -> B.Octets:
  B.Octets.of_list(as.go(1000000n, Nil{}))
'''


def body():
    lines, want = [], []
    for i, (name, m, v) in enumerate(VECTORS):
        dig, init, upd, fin = HASHES[name]
        o = octets(m)
        lines.append('    IO.print("%s %d " ++ B.Octets.hex(%s(%s)) ++ " " ++ B.Octets.hex(%s(%s(%s(%s(%s, p1(%s)), p2(%s)), p3(%s)))))'
                     % (name, len(m), dig, o, fin, upd, upd, upd, init, o, o, o))
        want.append("%s %d %s %s" % (name, len(m), v, v))
    lines.append('    IO.print("sha1 million a " ++ B.Octets.hex(S1.HsSha1.digest(big)))')
    want.append("sha1 million a " + MILLION_A_SHA1)
    return (HEADER + "\ndef main() -> IO(Unit):\n  +big = million_a()\n  do IO<Unit>:\n" + "\n".join(lines) + "\n\n"
            + "".join("#|%s\n" % w for w in want))


def main():
    path = os.path.join(PKG, "check.bend")
    new = body()
    old = open(path).read() if os.path.exists(path) else None
    if "--check" in sys.argv[1:]:
        if old != new:
            print("out of date (run gen/check.py): check.bend")
            sys.exit(1)
        print("check.bend up to date")
    elif old != new:
        with open(path, "w", newline="\n") as f:
            f.write(new)


if __name__ == "__main__":
    main()
