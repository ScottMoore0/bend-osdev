#!/usr/bin/env python3
"""Writes SHA-1's compression function, unrolled, from the specification's
tables (gen/spec.py).

  python3 gen/rounds.py           rewrite the generated region
  python3 gen/rounds.py --check   only check that it is up to date

The region lies between "# BEGIN GENERATED by gen/rounds.py: sha1" and
"# END GENERATED: sha1" in sha1.bend; everything else is written by hand.
It holds one def, hs.sha1.rounds(x, cv): the sixteen words of a block and
the chaining value in, the next chaining value out. Every step of the
specification is one line, binding a fresh name (v<i> for chaining words,
w<j> for the expanded message), so the code reads as the specification's
step list and needs no indexing at run time.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")
sys.dont_write_bytecode = True
sys.path.insert(0, HERE)
import spec  # noqa: E402

XS = ", ".join("+x%d" % i for i in range(16))
W16 = "Hs.HsW16{%s}" % XS


class Names:
    def __init__(self):
        self.i = 0

    def new(self):
        self.i += 1
        return "v%d" % self.i


def add(*xs):
    t = xs[0]
    for x in xs[1:]:
        t = "U32.add(%s, %s)" % (t, x)
    return t


def sha1():
    out = ["def hs.sha1.rounds(x: Hs.HsW16, cv: Hs.HsW5) -> Hs.HsW5:",
           "  match x cv:",
           "    case %s Hs.HsW5{+a0, +b0, +c0, +d0, +e0}:" % W16]
    F = ["hs.sha1.ch", "hs.sha1.parity", "hs.sha1.maj", "hs.sha1.parity"]
    W = ["x%d" % i for i in range(16)]
    a, b, c, d, e = "a0", "b0", "c0", "d0", "e0"
    n = Names()
    for t in range(80):
        if t % 20 == 0:
            out.append("      # steps %d to %d" % (t, t + 19))
        if t >= 16:
            w = "w%d" % t
            out.append("      +%s = Hs.hs.rotl(U32.xor(U32.xor(%s, %s), U32.xor(%s, %s)), 1n)" % (w, W[t - 3], W[t - 8], W[t - 14], W[t - 16]))
            W.append(w)
        v = n.new()
        out.append("      +%s = %s" % (v, add("Hs.hs.rotl(%s, 5n)" % a, "%s(%s, %s, %s)" % (F[t // 20], b, c, d), e, str(spec.SHA1_K[t // 20]), W[t])))
        nb = n.new()
        out.append("      +%s = Hs.hs.rotl(%s, 30n)" % (nb, b))
        a, b, c, d, e = v, a, nb, c, d
    out.append("      Hs.HsW5{%s}" % ", ".join("U32.add(%s, %s)" % p for p in [("a0", a), ("b0", b), ("c0", c), ("d0", d), ("e0", e)]))
    return "\n".join(out) + "\n"


REGIONS = [("sha1.bend", "sha1", sha1)]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fname, name, body in REGIONS:
        path = os.path.join(PKG, fname)
        with open(path) as f:
            text = f.read()
        begin = "# BEGIN GENERATED by gen/rounds.py: %s\n" % name
        end = "# END GENERATED: %s\n" % name
        i, j = text.index(begin) + len(begin), text.index(end)
        new = text[:i] + body() + text[j:]
        if new != text:
            stale.append(fname)
            if not check:
                with open(path, "w", newline="\n") as f:
                    f.write(new)
    if check:
        if stale:
            print("out of date (run gen/rounds.py): " + ", ".join(stale))
            sys.exit(1)
        print("generated regions up to date")


if __name__ == "__main__":
    main()
