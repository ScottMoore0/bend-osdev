#!/usr/bin/env python3
"""Differential test cases for bend-osdev-sha1.

Writes ref/cases.bend (a Bend program printing, for each case, the digest
in one call, then the digest of the same message fed in three pieces
through init / update / final) and ref/expected.txt (the same from
Python's hashlib (OpenSSL).

The messages are a linear congruential generator's bytes (the same
generator in Bend and here), of lengths around every block boundary up to
three blocks, and some longer ones; the pieces are cut at random points.
"""
import hashlib, os, random, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True
sys.path.insert(0, HERE)
import model  # noqa: E402

HEADER = """# Generated by ref/gen.py; do not edit by hand.
import Base
import ../../bytes/bytes.bend as B
import ../../md-engine/md-engine.bend as Hs
import ../sha1.bend as S1

# n bytes of a linear congruential generator from seed s (last generated
# first, as gen.py's msg() reverses them)
def msg.go(n: Nat, +s: U32, acc: List<&2, U32>) -> List<&2, U32>:
  match n:
    case 0n:
      acc
    case 1n+p:
      +s2 = U32.add(U32.mul(s, 1103515245), 12345)
      msg.go(p, s2, Con{U32.and(U32.shrn(s2, 16n), 255), acc})

def msg(s: U32, n: Nat) -> B.Octets:
  B.Octets.of_list(msg.go(n, s, Nil{}))

# the pieces [0, i), [i, j), [j, end) of o
def p1(+i: Nat, +o: B.Octets) -> B.Octets:
  B.Octets.take(i, o)

def p2(+i: Nat, +j: Nat, +o: B.Octets) -> B.Octets:
  B.Octets.take(Nat.sub(j, i), B.Octets.drop(i, o))

def p3(+j: Nat, +o: B.Octets) -> B.Octets:
  B.Octets.drop(j, o)
"""

# name: (Bend init, update, final, digest; reference)
HASHES = {
    "sha1": ("S1.HsSha1.init()", "S1.HsSha1.update", "S1.HsSha1.final", "S1.HsSha1.digest", lambda m: hashlib.sha1(m).digest(), "hashlib"),
}


def msg(s, n):
    out = []
    for _ in range(n):
        s = (s * 1103515245 + 12345) & 0xFFFFFFFF
        out.append((s >> 16) & 255)
    return bytes(reversed(out))


LENGTHS = [0, 1, 2, 3, 4, 5, 7, 8, 31, 55, 56, 57, 63, 64, 65, 100, 119, 120, 127, 128, 129, 183, 191, 192, 193, 1000, 4103]


def main():
    model.check_vectors()
    rng = random.Random(int(sys.argv[1]) if len(sys.argv) > 1 else 2026)
    lines, want = [], []
    for name, (init, upd, fin, dig, ref, src) in HASHES.items():
        for n in LENGTHS:
            s = rng.getrandbits(32)
            i = rng.randint(0, n)
            j = rng.randint(i, n)
            m = msg(s, n)
            o = "msg(%d, %dn)" % (s, n)
            pieces = "%s(%s(%s(%s(%s, p1(%dn, %s)), p2(%dn, %dn, %s)), p3(%dn, %s)))" % (fin, upd, upd, upd, init, i, o, i, j, o, j, o)
            lines.append('    IO.print("%s %d " ++ B.Octets.hex(%s(%s)) ++ " " ++ B.Octets.hex(%s))' % (name, n, dig, o, pieces))
            d = ref(m).hex()
            want.append("%s %d %s %s" % (name, n, d, d))
    with open(os.path.join(HERE, "cases.bend"), "w", newline="\n") as f:
        f.write(HEADER + "\ndef main() -> IO(Unit):\n  do IO<Unit>:\n" + "\n".join(lines) + "\n")
    with open(os.path.join(HERE, "expected.txt"), "w", newline="\n") as f:
        f.write("\n".join(want) + "\n")
    srcs = {}
    for name, h in HASHES.items():
        srcs.setdefault(h[5], []).append(name)
    print("%d cases (%s)" % (len(want), "; ".join("%s: %s" % (k, ", ".join(v)) for k, v in sorted(srcs.items()))))


if __name__ == "__main__":
    main()
