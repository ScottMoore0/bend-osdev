PLGO = "R.ring.push_list.go(%s, (%s, %s))"
def tk(xs, i):
    return "List.take(&2, U32, %s, Nat.min(List.length(&2, U32, %s), Nat.sub($SO, Nat.sub(%s, u))))" % (xs, xs, i)
def pl_claim(kind, xs, i, l, n):
    ring = fst("Nat", PLGO % (xs, "I.ri.rr(o, %s, u, %s)" % (i, l), n))
    if kind == "items":
        return "{%s == List.append(&2, U32, I.ri.view(Nat.sub(%s, u), u, o, %s), %s) : $L}" % (items(ring), i, l, tk(xs, i))
    if kind == "cap":
        return "{%s == $SO : Nat}" % cap(ring)
    return "{R.ring.sound(%s) == True{} : Bool}" % ring
