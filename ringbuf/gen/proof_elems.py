"""Generates the part of ringbuf/PROOF.bend that ties the Array ring's
elements to the model: everything from the line "# The Array ring's
elements, through bend-osdev-array" to the end. The lemma signatures repeat
long goals and hypotheses, so they are built here from a few shorthands.
The lemmas about the slots and the view are in proof_items.bend (written by
hand).

Every law takes a sound ring apart (el.<law>), reflects its array once into
Arrays.of_list(order, l, 0) (array's `reflect`, el.<law>.ref), rewrites the
goal onto the reflected ring, the model onto RingModel{2^order, the view}
(el.<law>.body), and proves it there (the el.* lemmas below).

Run from anywhere: python3 gen/proof_elems.py rewrites ../PROOF.bend; with
--check it only reports whether the file is up to date (exit 1 if not).
"""
