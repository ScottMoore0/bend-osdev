#!/usr/bin/env python3
"""Writes nlattr/proof_byte.bend: every value k below 256 survives being
made a U32 and masked to a byte (U32.to_nat(B.byte(U32.from_nat(k))) == k),
as a chain of lemmas nb.dK for k + K (K from 0 to 256): each case is a
closed computation or a step to the next. Run from the package directory:
python3 gen/gen_byte.py > proof_byte.bend"""
print("""# Generated by gen/gen_byte.py: do not edit.
#
# Every value k below 256 survives being made a U32 and masked to a byte,
# by a chain of lemmas nb.dK (for K + k, K from 0 to 256), each a closed
# computation or a step to the next.
import Base
import ../bytes/bytes.bend as B

def nb.bt(b: Bool) -> Type:
  match b:
    case True{}:
      Unit
    case False{}:
      Empty

def nb.ft(e: {False{} == True{} : Bool}) -> Empty:
  %Equal.sym(Bool, False{}, True{}, e) : nb.bt(_)
  Unit{}

def nb.abs(+k: Nat, e: Empty) -> {U32.to_nat(B.byte(U32.from_nat(k))) == k : Nat}:
  Empty.absurd({U32.to_nat(B.byte(U32.from_nat(k))) == k : Nat}, e)

def nb.d256(+k: Nat, +lt: {Nat.is_lt(Nat.add(256n, k), 256n) == True{} : Bool}) -> {U32.to_nat(B.byte(U32.from_nat(Nat.add(256n, k)))) == Nat.add(256n, k) : Nat}:
  match k:
    case 0n:
      nb.abs(Nat.add(256n, 0n), nb.ft(lt))
    case 1n+p:
      nb.abs(Nat.add(256n, 1n+p), nb.ft(lt))
""")
for K in range(255, -1, -1):
    print("""def nb.d%d(+k: Nat, +lt: {Nat.is_lt(Nat.add(%dn, k), 256n) == True{} : Bool}) -> {U32.to_nat(B.byte(U32.from_nat(Nat.add(%dn, k)))) == Nat.add(%dn, k) : Nat}:
  match k:
    case 0n:
      {==}
    case 1n+p:
      nb.d%d(p, lt)
""" % (K, K, K, K, K + 1))
print("""# k below 256: k as a byte is k
def nb.byte(+k: Nat, +lt: {Nat.is_lt(k, 256n) == True{} : Bool}) -> {U32.to_nat(B.byte(U32.from_nat(k))) == k : Nat}:
  nb.d0(k, lt)""")
