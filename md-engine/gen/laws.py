#!/usr/bin/env python3
"""Writes md-engine/LAWS.bend and md-engine/PROOF.bend.

  python3 gen/laws.py           rewrite both files
  python3 gen/laws.py --check   only check that they are up to date

The laws:
  * md_streaming: the engine's update(s, a ++ b) == update(update(s, a), b),
    for every chaining value type, compression function, block size, state
    and a, b. update is a fold of a step function over the message's bytes,
    so feeding a ++ b is feeding a and then b, by induction on a, whatever
    the step does; nothing about the compression function, the buffer or
    the block count is needed. Each hash package's streaming law is this law
    at its own defs.
  * w2_le_length, w4_le_length, w5_le_length, w5_be_length, w8_be_length:
    the digest bytes of a chaining value have a fixed length, whatever its
    words are (a list of fixed shape for every value of its words). The
    hash packages' digest-length laws rest on these.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")

IMPORTS = """import Base
import ../bytes/bytes.bend as B
import ./md-engine.bend as Hs
"""

LAWS_HEAD = '''# Generated by gen/laws.py; do not edit by hand.
#
# The laws of the Merkle-Damgard engine every hash package streams through:
# its streaming law, stated once for every chaining value and compression
# function (each hash's streaming law is this law at its own defs), and the
# lengths of the chaining values' digest bytes, which the hashes' digest
# lengths rest on.
''' + IMPORTS + '''
# The engine, for every chaining value type, compression function and block
# size: a ++ b is a, then b, from every state
law md_streaming:
  for ~C: Data
  for ~compress: C -> List<&2, U32> -> C
  for ~last: U32
  for s: Hs.HsMdState<C>
  for +a: B.Octets
  for +b: B.Octets
  {Hs.HsMd.update(~C, ~compress, ~last, s, B.Octets.append(a, b)) == Hs.HsMd.update(~C, ~compress, ~last, Hs.HsMd.update(~C, ~compress, ~last, s, a), b) : Hs.HsMdState<C>}
'''

PROOF_HEAD = '''# Generated by gen/laws.py; do not edit by hand.
''' + IMPORTS + '''import ../bytes/LAWS.bend as BL
import ../bytes/PROOF.bend as BP
import ./LAWS.bend as Laws

# The engine: feeding xs ++ ys is feeding xs, then ys (induction on xs)
def feed_append(~C: Data, ~compress: C -> List<&2, U32> -> C, ~last: U32, xs: List<&2, U32>, +ys: List<&2, U32>, s: Hs.HsMdState<C>) -> {Hs.hs.md.feed(~C, ~compress, ~last, B.append(xs, ys), s) == Hs.hs.md.feed(~C, ~compress, ~last, ys, Hs.hs.md.feed(~C, ~compress, ~last, xs, s)) : Hs.HsMdState<C>}:
  match xs:
    case Nil{}:
      {==}
    case Con{x, t}:
      feed_append(~C, ~compress, ~last, t, ys, Hs.hs.md.step(~C, ~compress, ~last, s, x))

def Laws.md_streaming(C, compress, last, s, a, b):
  %Equal.sym(List<&2, U32>, B.Octets.to_list(B.Octets.append(a, b)), B.append(B.Octets.to_list(a), B.Octets.to_list(b)), BL.octets_append_list(a, b)) : {Hs.hs.md.feed(~C, ~compress, ~last, _, s) == Hs.HsMd.update(~C, ~compress, ~last, Hs.HsMd.update(~C, ~compress, ~last, s, a), b) : Hs.HsMdState<C>}
  feed_append(~C, ~compress, ~last, B.Octets.to_list(a), B.Octets.to_list(b), s)

# Lengths: the bytes of a chaining value are a list of fixed shape whatever
# its words are, and an Octets made from a list has the list's length
# (bytes' octets_len_of_list)
'''


def app(xs):
    t = xs[-1]
    for x in reversed(xs[:-1]):
        t = "B.append(%s, %s)" % (x, t)
    return t


def len_lemma(name, ty, ctor, nwords, order, n, out, first=0):
    """len(out(x)) == n for every x: the words' bytes, through bytes'
    octets_len_of_list"""
    vs = ["a%d" % i for i in range(nwords)]
    used = vs[first:]
    lst = app(["B.%s(%s)" % (order, v) for v in used])
    pat = "%s{%s}" % (ctor, ", ".join("+" + v if v in used else v for v in vs))
    return '''def %s_list(%s) -> {B.len(%s) == %dn : Nat}:
  match %s:
    case %s:
      {==}

def %s(x: %s) -> {B.Octets.len(%s(x)) == %dn : Nat}:
  match x:
    case %s:
      %%Equal.sym(Nat, B.Octets.len(B.Octets.of_list(%s)), B.len(%s), BL.octets_len_of_list(%s)) : {_ == %dn : Nat}
      %s_list(%s)
''' % (name, ", ".join("%s: U32" % v for v in used), lst, n, " ".join(used), " ".join("U32{w%s}" % v for v in used),
       name, ty, out, n, pat, lst, lst, lst, n, name, ", ".join(used))


# name of the law, its private lemma, type, words, byte order, length, digest bytes
LENGTHS = [("w2_le_length", "w2le_len", "Hs.HsW2", 2, "le32", 8, "Hs.HsW2.le"),
           ("w4_le_length", "w4le_len", "Hs.HsW4", 4, "le32", 16, "Hs.HsW4.le"),
           ("w5_le_length", "w5le_len", "Hs.HsW5", 5, "le32", 20, "Hs.HsW5.le"),
           ("w5_be_length", "w5be_len", "Hs.HsW5", 5, "be32", 20, "Hs.HsW5.be"),
           ("w8_be_length", "w8be_len", "Hs.HsW8", 8, "be32", 32, "Hs.HsW8.be")]
LEN_LEMMAS = [len_lemma(lem, ty, ty, k, order, n, out) for _, lem, ty, k, order, n, out in LENGTHS]


LAWS, PROOFS = [], []


def law(name, comment, params, stmt):
    LAWS.append("# %s\nlaw %s:\n%s  %s\n" % (comment, name, "".join("  for %s\n" % p for p in params), stmt))

LAWS.append("# The digest bytes of every chaining value have a fixed length: the hash\n"
            "# packages' digest lengths rest on these\n")
for name, lem, ty, k, order, n, out in LENGTHS:
    law(name, "%s: %d bytes, whatever the words are" % (out, n), ["x: %s" % ty], "{B.Octets.len(%s(x)) == %dn : Nat}" % (out, n))
    PROOFS.append("def Laws.%s(x):\n  %s(x)\n" % (name, lem))


def files():
    laws = LAWS_HEAD + "\n" + "\n".join(LAWS)
    proofs = PROOF_HEAD + "\n" + "\n".join(LEN_LEMMAS) + "\n" + "\n".join(PROOFS)
    return [("LAWS.bend", laws), ("PROOF.bend", proofs)]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fname, body in files():
        path = os.path.join(PKG, fname)
        old = open(path).read() if os.path.exists(path) else None
        if old != body:
            stale.append(fname)
            if not check:
                with open(path, "w", newline="\n") as f:
                    f.write(body)
    if check:
        if stale:
            print("out of date (run gen/laws.py): " + ", ".join(stale))
            sys.exit(1)
        print("LAWS.bend and PROOF.bend up to date")


if __name__ == "__main__":
    main()
