#!/usr/bin/env python3
"""Writes oid/PROOF_valid.bend, the proof of LAWS_valid.bend (each registry
entry whose arcs are all below 10000 is a valid Oid). Run from anywhere:
python3 oid/gen/gen_validproof.py
With --check, writes nothing and fails if PROOF_valid.bend differs from
what it would write (run it after gen/gen_registry.py changes the table).

Each entry's validity is a closed computation (its arcs' decimal digits and
its DER contents), one def per entry (the kernel has a step budget per def);
an entry with an arc of 10000 or more passes by the bound alone, as its
validity is not computed. The rest is induction over any list of entries.

The bound is the kernel's: its natural numbers are unary, and dividing one
of 10000 or more (the digits, the base-128 subidentifiers) runs out of its
step budget, so the entries under 1.2.840.10040, 1.2.840.10045,
1.2.840.10046 and 1.2.840.113549, and id-domainComponent (19200300), are
left out (README.md, Laws).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
OUT = os.path.join(PKG, "PROOF_valid.bend")

reg = open(os.path.join(PKG, "registry.bend"), encoding="utf-8").read()
N = sum(len(re.findall(r'OidEntry\{"', m)) for m in re.findall(r"def oid\.reg\d+\(\) -> List<&2, OidEntry>:\n  \[(.*)\]", reg))

L = []
def w(s=""):
    L.append(s)

LE = "List<&2, R.OidEntry>"
REG = "R.Oid.registry()"
BOUND = "10000n"
def eqT(x):
    return "{%s == True{} : Bool}" % x
def drop(es, k):
    return "List.drop(&2, R.OidEntry, %s, %s)" % (es, k)
def imp(f):
    return "rv.imp(Laws.oidlaw.below(R.OidEntry.arcs(%s), %s), R.OidEntry.arcs(%s))" % (f, BOUND, f)
VALID = "{O.Oid.valid(O.Oid{R.OidEntry.arcs(e)}) == True{} : Bool}"

w('''# Generated by gen/gen_validproof.py: do not edit.
#
# Proof of LAWS_valid.bend: each entry's validity is a closed computation
# (one def per entry), for the entries whose arcs are all below 10000, and
# induction over any list of entries for the rest.
import Base
import ../u32/LAWS.bend as UL
import ../u32/PROOF.bend as UP
import ./oid.bend as O
import ./registry.bend as R
import ./LAWS_valid.bend as Laws

# ---------------------------------------------------------------- logic

def rv.bool(b: Bool) -> Type:
  match b:
    case True{}:
      Unit
    case False{}:
      Empty

def rv.ft(e: {False{} == True{} : Bool}) -> Empty:
  %Equal.sym(Bool, False{}, True{}, e) : rv.bool(_)
  Unit{}

def rv.and_l(a: Bool, -b: Bool, e: {Bool.and(a, b) == True{} : Bool}) -> {a == True{} : Bool}:
  match a:
    case True{}:
      {==}
    case False{}:
      Empty.absurd({False{} == True{} : Bool}, rv.ft(e))

def rv.and_r(a: Bool, -b: Bool, e: {Bool.and(a, b) == True{} : Bool}) -> {b == True{} : Bool}:
  match a:
    case True{}:
      e
    case False{}:
      Empty.absurd({b == True{} : Bool}, rv.ft(e))

def rv.and_i(a: Bool, -b: Bool, ea: {a == True{} : Bool}, eb: {b == True{} : Bool}) -> {Bool.and(a, b) == True{} : Bool}:
  match a:
    case True{}:
      eb
    case False{}:
      Empty.absurd({Bool.and(False{}, b) == True{} : Bool}, rv.ft(ea))

# ---------------------------------------------------------------- Maybe

def rv.mget(m: Maybe<&2, R.OidEntry>, d: R.OidEntry) -> R.OidEntry:
  match m:
    case None{}:
      d
    case Some{x}:
      x

def rv.some_inj(-x: R.OidEntry, -y: R.OidEntry, e: {Some{x} == Some{y} : Maybe<&2, R.OidEntry>}) -> {x == y : R.OidEntry}:
  Equal.cong(Maybe<&2, R.OidEntry>, R.OidEntry, m => rv.mget(m, x), Some{x}, Some{y}, e)

def rv.is_none(m: Maybe<&2, R.OidEntry>) -> Type:
  match m:
    case None{}:
      Unit
    case Some{x}:
      Empty

def rv.ns(-y: R.OidEntry, e: {None{} == Some{y} : Maybe<&2, R.OidEntry>}) -> Empty:
  %e : rv.is_none(_)
  Unit{}

# ---------------------------------------------------------------- an entry's check

# arcs within the bound (b) are a valid Oid; the validity is computed only
# then, in its own branch
def rv.imp(b: Bool, arcs: List<&2, Nat>) -> Bool:
  match b:
    case True{}:
      O.Oid.valid(O.Oid{arcs})
    case False{}:
      True{}

def rv.imp_t(b: Bool, -arcs: List<&2, Nat>, hb: {b == True{} : Bool}, hi: {rv.imp(b, arcs) == True{} : Bool}) -> {O.Oid.valid(O.Oid{arcs}) == True{} : Bool}:
  match b:
    case True{}:
      hi
    case False{}:
      Empty.absurd({O.Oid.valid(O.Oid{arcs}) == True{} : Bool}, rv.ft(hb))

# ---------------------------------------------------------------- lists of entries

# every entry within the bound is valid
def rv.allimp(es: List<&2, R.OidEntry>) -> Bool:
  match es:
    case Nil{}:
      True{}
    case Con{+f, t}:
      Bool.and(@IMPF@, rv.allimp(t))

def rv.dummy() -> R.OidEntry:
  R.OidEntry{"", R.OidKindOther{}, Nil{}, R.OidSrcCSOR{}}

def rv.hd(es: List<&2, R.OidEntry>) -> R.OidEntry:
  match es:
    case Nil{}:
      rv.dummy()
    case Con{f, t}:
      f

def rv.drop0(es: List<&2, R.OidEntry>) -> {List.drop(&2, R.OidEntry, es, 0n) == es : List<&2, R.OidEntry>}:
  match es:
    case Nil{}:
      {==}
    case Con{f, t}:
      {==}

def rv.lt0(m: Nat) -> {Nat.is_lt(m, 0n) == False{} : Bool}:
  match m:
    case 0n:
      {==}
    case 1n+p:
      {==}
'''.replace("@IMPF@", imp("f")))

HD = "rv.hd(%s)" % drop("es", "k")
CH = "{rv.allimp(%s) == Bool.and(%s, rv.allimp(%s)) : Bool}"
def chain_ty(es):
    hd = "rv.hd(%s)" % drop(es, "k")
    return CH % (drop(es, "k"), imp(hd), drop(es, "1n+k"))
w("# the list from position k on: its head, and the rest")
w("def rv.chain(es: %s, k: Nat, h: {Nat.is_lt(k, List.length(&2, R.OidEntry, es)) == True{} : Bool}) -> %s:" % (LE, chain_ty("es")))
w("  match es k:")
w("    case Nil{} _:")
w("      Empty.absurd(%s, rv.ft(Equal.trans(Bool, False{}, Nat.is_lt(k, 0n), True{}, Equal.sym(Bool, Nat.is_lt(k, 0n), False{}, rv.lt0(k)), h)))" % chain_ty("Nil{}"))
w("    case Con{+f, +t} 0n:")
w("      %%Equal.sym(%s, %s, t, rv.drop0(t)) : {rv.allimp(Con{f, t}) == Bool.and(%s, rv.allimp(_)) : Bool}" % (LE, drop("t", "0n"), imp("f")))
w("      {==}")
w("    case Con{f, t} 1n+j:")
w("      rv.chain(t, j, h)")
w()
w("# an entry within the bound of a list whose entries within it are valid is valid")
w("def rv.found(es: %s, i: Nat, +e: R.OidEntry, +hd: {rv.allimp(es) == True{} : Bool}, +h: {List.get(&2, R.OidEntry, es, i) == Some{e} : Maybe<&2, R.OidEntry>}, +hb: {Laws.oidlaw.below(R.OidEntry.arcs(e), %s) == True{} : Bool}) -> %s:" % (LE, BOUND, VALID))
w("  match es i:")
w("    case Nil{} _:")
w("      Empty.absurd(%s, rv.ns(e, h))" % VALID)
w("    case Con{+f, +t} 0n:")
w("      rv.imp_t(Laws.oidlaw.below(R.OidEntry.arcs(e), %s), R.OidEntry.arcs(e), hb, Equal.trans(Bool, %s, %s, True{}, Equal.sym(Bool, %s, %s, Equal.cong(R.OidEntry, Bool, z => %s, f, e, rv.some_inj(f, e, h))), rv.and_l(%s, rv.allimp(t), hd)))" % (BOUND, imp("e"), imp("f"), imp("f"), imp("e"), imp("z"), imp("f")))
w("    case Con{+f, +t} 1n+ii:")
w("      rv.found(t, ii, e, rv.and_r(%s, rv.allimp(t), hd), h, hb)" % imp("f"))
w()

# the closed computations, one def per entry, from the last
w("# ---------------------------------------------------------------- the registry, entry by entry")
w()
w('''def rv.lt_add(k: Nat, +m: Nat) -> {Nat.is_lt(k, Nat.add(k, 1n+m)) == True{} : Bool}:
  match k:
    case 0n:
      {==}
    case 1n+p:
      rv.lt_add(p, m)

def rv.drop_len(xs: List<&2, R.OidEntry>) -> {List.drop(&2, R.OidEntry, xs, List.length(&2, R.OidEntry, xs)) == Nil{} : List<&2, R.OidEntry>}:
  match xs:
    case Nil{}:
      {==}
    case Con{f, t}:
      rv.drop_len(t)

# The closed computations take the entry by its position k (as
# PROOF_registry.bend does): an entry held in a reused parameter would carry
# the arc 19200300 of id-domainComponent, which --verdict's kernel refuses
# (bendlang/bend#1322), where the position is a small number.

def rv.at(+k: Nat) -> R.OidEntry:
  rv.hd(List.drop(&2, R.OidEntry, R.Oid.registry(), k))

# the entry at position k: within the bound, valid
def rv.impi(+k: Nat) -> Bool:
  @IMPK@

# the entries from position k on, n of them
def rv.upto(n: Nat, +k: Nat) -> Bool:
  match n:
    case 0n:
      True{}
    case 1n+m:
      Bool.and(rv.impi(k), rv.upto(m, 1n+k))
'''.replace("@IMPK@", imp("rv.at(k)")))
LEN = "List.length(&2, R.OidEntry, %s)" % REG
D1 = drop(REG, "1n+k")
A = imp("rv.hd(%s)" % drop(REG, "k"))
w("# the positions' checks give the list's")
w("def rv.bridge(n: Nat, +k: Nat, +h: %s, +hl: {Nat.add(k, n) == %s : Nat}) -> %s:" % (eqT("rv.upto(n, k)"), LEN, eqT("rv.allimp(%s)" % drop(REG, "k"))))
w("  match n:")
w("    case 0n:")
w("      %%Equal.sym(Nat, k, %s, Equal.trans(Nat, k, Nat.add(k, 0n), %s, Equal.sym(Nat, Nat.add(k, 0n), k, UL.nat_add_zero(k)), hl)) : %s" % (LEN, LEN, eqT("rv.allimp(%s)" % drop(REG, "_"))))
w("      %%Equal.sym(%s, %s, Nil{}, rv.drop_len(%s)) : %s" % (LE, drop(REG, LEN), REG, eqT("rv.allimp(_)")))
w("      {==}")
w("    case 1n+ +m:")
LT = "Equal.trans(Bool, Nat.is_lt(k, %s), Nat.is_lt(k, Nat.add(k, 1n+m)), True{}, Equal.cong(Nat, Bool, z => Nat.is_lt(k, z), %s, Nat.add(k, 1n+m), Equal.sym(Nat, Nat.add(k, 1n+m), %s, hl)), rv.lt_add(k, m))" % (LEN, LEN, LEN)
A1 = "rv.and_l(rv.impi(k), rv.upto(m, 1n+k), h)"
HL2 = "Equal.trans(Nat, 1n+Nat.add(k, m), Nat.add(k, 1n+m), %s, Equal.sym(Nat, Nat.add(k, 1n+m), 1n+Nat.add(k, m), UL.nat_add_succ(k, m)), hl)" % LEN
IH = "rv.bridge(m, 1n+k, rv.and_r(rv.impi(k), rv.upto(m, 1n+k), h), %s)" % HL2
w("      Equal.trans(Bool, rv.allimp(%s), Bool.and(%s, rv.allimp(%s)), True{}, rv.chain(%s, k, %s), rv.and_i(%s, rv.allimp(%s), %s, %s))" % (drop(REG, "k"), A, D1, REG, LT, A, D1, A1, IH))
w()
w("# one step of rv.upto, without computing it")
w("def rv.unf(+n: Nat, +k: Nat) -> {rv.upto(1n+n, k) == Bool.and(rv.impi(k), rv.upto(n, 1n+k)) : Bool}:")
w("  {==}")
w()
w("def rv.u%d() -> %s:" % (N, eqT("rv.upto(0n, %dn)" % N)))
w("  {==}")
w()
for k in range(N - 1, -1, -1):
    C = "rv.impi(%dn)" % k
    U = "rv.upto(%dn, 1n+%dn)" % (N - 1 - k, k)
    w("def rv.c%d() -> %s:" % (k, eqT(C)))
    w("  {==}")
    w()
    w("def rv.u%d() -> %s:" % (k, eqT("rv.upto(1n+%dn, %dn)" % (N - 1 - k, k))))
    w("  Equal.trans(Bool, rv.upto(1n+%dn, %dn), Bool.and(%s, %s), True{}, rv.unf(%dn, %dn), rv.and_i(%s, %s, rv.c%d(), rv.u%d()))" % (N - 1 - k, k, C, U, N - 1 - k, k, C, U, k, k + 1))
    w()
w("def rv.d0() -> %s:" % eqT("rv.allimp(%s)" % REG))
w("  %%rv.drop0(%s) : %s" % (REG, eqT("rv.allimp(_)")))
w("  rv.bridge(%dn, 0n, rv.u0(), {==})" % N)
w()
w("# ---------------------------------------------------------------- the law")
w()
w("def Laws.entries_valid(i, e, h, hb):")
w("  rv.found(%s, i, e, rv.d0(), h, hb)" % REG)

text = "\n".join(L).rstrip() + "\n"
if "--check" in sys.argv[1:]:
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if old != text:
        print("oid/PROOF_valid.bend is not what gen/gen_validproof.py writes")
        sys.exit(1)
    print("oid/PROOF_valid.bend ok")
else:
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
