#!/usr/bin/env python3
"""Writes oid/proof_digit.bend: facts about each decimal digit's character,
proved by computation for each of the ten digits. Run from the package
directory:  python3 gen/gen_digit.py proof_digit.bend

For a digit d below 10, og.<fact>(d, lt) unfolds d one successor at a time
(og.<fact>K(k, lt) holds the fact of K + k), so each digit is a closed
computation and 10 or more is refuted by lt.
"""
import sys

L = []
p = L.append

p('''# Generated by gen/gen_digit.py: do not edit.
#
# Proofs for bend-osdev-oid: each decimal digit's character reads back as
# the digit, is not a full stop, and is not the character 0 unless the
# digit is 0.
import Base
import ./text.bend as T
import ./proof_nat.bend as ON
import ../u32/LAWS_order.bend as UO
import ../u32/PROOF_order.bend as UOP
''')


def chain(name, ty):
    p("def og.%s10(+k: Nat, +lt: {Nat.is_lt(Nat.add(10n, k), 10n) == True{} : Bool}) -> %s:" % (name, ty("Nat.add(10n, k)")))
    p("  match k:\n    case 0n:\n      Empty.absurd(%s, ON.on.ft(lt))\n    case 1n+q:\n      Empty.absurd(%s, ON.on.ft(lt))\n" % (ty("Nat.add(10n, 0n)"), ty("Nat.add(10n, 1n+q)")))
    for K in range(9, -1, -1):
        p("def og.%s%d(+k: Nat, +lt: {Nat.is_lt(Nat.add(%dn, k), 10n) == True{} : Bool}) -> %s:" % (name, K, K, ty("Nat.add(%dn, k)" % K)))
        p("  match k:\n    case 0n:\n      {==}\n    case 1n+q:\n      og.%s%d(q, lt)\n" % (name, K + 1))
    p("def og.%s(+d: Nat, +lt: {Nat.is_lt(d, 10n) == True{} : Bool}) -> %s:\n  og.%s0(d, lt)\n" % (name, ty("d"), name))


p("# a digit's character reads back as the digit")
chain("cval", lambda d: "{T.oid.cval(T.oid.dchar(%s)) == Some{%s} : Maybe<&2, Nat>}" % (d, d))
p("# a digit's character is not a full stop")
chain("notdot", lambda d: "{T.oid.is_dot(T.oid.dchar(%s)) == False{} : Bool}" % d)
p("# the character of a digit's successor is not 0")
chain("nzx", lambda d: "{T.oid.is_zero(T.oid.dchar(Nat.add(1n, %s))) == False{} : Bool}" % d)
p('''# a digit from 1 to 9 is not the character 0
def og.nonzero(+d: Nat, +h1: {Nat.is_le(1n, d) == True{} : Bool}, +lt: {Nat.is_lt(d, 10n) == True{} : Bool}) -> {T.oid.is_zero(T.oid.dchar(d)) == False{} : Bool}:
  match d:
    case 0n:
      Empty.absurd({T.oid.is_zero(T.oid.dchar(0n)) == False{} : Bool}, ON.on.ft(h1))
    case 1n+e:
      og.nzx(e, UO.nat_lt_le_trans(e, 9n, 10n, lt, {==}))
''')
open(sys.argv[1], 'w', newline='\n').write("\n".join(L))
