#!/usr/bin/env python3
"""Writes oid/PROOF_registry.bend, the proofs of LAWS_registry.bend (the
registry's names and arcs are unique, and each entry is found again by its
name and by its arcs). Run from anywhere:  python3 oid/gen/gen_regproof.py
With --check, writes nothing and fails if PROOF_registry.bend differs from
what it would write (run it after gen/gen_registry.py changes the table).

The uniqueness is a closed computation over the table, quadratic in its
size, so it is cut into one def per entry (the kernel has a step budget per
def): each entry's name, and its arcs, differ from those of every entry after
it. The rest is induction over any list of entries. Arcs are compared last
arc first (the arcs registered under one arc mostly differ only in their
last), so no two of the large arcs (113549, 19200300) are compared; a
lemma carries that comparison over to Oid.is_eq's.
"""
