#!/usr/bin/env python3
"""Writes ../bits.bend: bit-level access to bytes and words.

Each bit of a U32 is read by a deep pattern on its word, so a bit of an
unknown value is still a term the checker can carry (no shifts or masks),
and a byte or word rebuilt from its bits is the same term again: that is
what lets the proofs follow symbolic bytes through the bit stream.
"""
import os

def pat(k, name="x"):
    # U32{WCon{c0, WCon{c1, ... WCon{ck, r}}}}
    s = "r"
    for i in range(k, -1, -1):
        s = "WCon{c%d, %s}" % (i, s)
    return "U32{%s}" % s

out = []
w = out.append
w("# bend-osdev-c842, bits: bit-level access to bytes and words (generated by")
w("# gen/bits.py; do not edit by hand).")
w("#")
w("# A U32's word holds its bits least significant first. c842.bit.k reads bit")
w("# k with a deep pattern, so the bits of an unknown value are terms the")
w("# checker can carry, and a value rebuilt from its own bits is the same value")
w("# (PROOF.bend proves byte and word round trips this way).")
w("import Base")
w("")
for k in range(32):
    w("def c842.bit.b%d(x: U32) -> Bool:" % k)
    w("  match x:")
    w("    case %s:" % pat(k))
    w("      c%d" % k)
    w("")
w("# a byte's 8 bits, most significant first (the low 8 bits of x)")
w("def c842.bits.byte(+x: U32) -> List<&2, Bool>:")
w("  [" + ", ".join("c842.bit.b%d(x)" % k for k in range(7, -1, -1)) + "]")
w("")
w("# a word's 32 bits, most significant first")
w("def c842.bits.word(+x: U32) -> List<&2, Bool>:")
w("  [" + ", ".join("c842.bit.b%d(x)" % k for k in range(31, -1, -1)) + "]")
w("")
w("# the byte with these bits, least significant first")
w("def c842.byte.of(b0: Bool, b1: Bool, b2: Bool, b3: Bool, b4: Bool, b5: Bool, b6: Bool, b7: Bool) -> U32:")
s = "Word.zero(24n)"
for i in range(7, -1, -1):
    s = "WCon{b%d, %s}" % (i, s)
w("  U32{%s}" % s)
w("")
w("# the word with these bits, least significant first (32 of them, in a list")
w("# read in reverse: the last bit read is the least significant)")
w("def c842.word.of(bs: List<&2, Bool>) -> U32:")
w("  match bs:")
cons = "Nil{}"
for i in range(31, -1, -1):
    cons = "Con{c%d, %s}" % (i, cons)
s = "WNil{}"
for i in range(31, -1, -1):
    s = "WCon{c%d, %s}" % (i, s)
# list order: reversed reading = least significant first
w("    case %s:" % cons.replace("Nil{}", "rest"))
w("      U32{%s}" % s)
w("    case _:")
w("      0")
w("")
w("# a byte from 8 bits read in reverse (least significant first); 0 if fewer")
w("def c842.byte.of_rev(bs: List<&2, Bool>) -> U32:")
w("  match bs:")
cons = "rest"
for i in range(7, -1, -1):
    cons = "Con{c%d, %s}" % (i, cons)
w("    case %s:" % cons)
w("      c842.byte.of(" + ", ".join("c%d" % i for i in range(8)) + ")")
w("    case _:")
w("      0")
w("")
w("# x's low byte, rebuilt from its bits: what the decoder reads back from the")
w("# 8 bits the serialiser writes for x (PROOF.bend: it is B.byte(x))")
w("def c842.rebyte(+x: U32) -> U32:")
w("  c842.byte.of(" + ", ".join("c842.bit.b%d(x)" % k for k in range(8)) + ")")
w("")
w("# x rebuilt from its 32 bits (PROOF.bend: it is x)")
w("def c842.reword(+x: U32) -> U32:")
s2 = "WNil{}"
for i in range(31, -1, -1):
    s2 = "WCon{c842.bit.b%d(x), %s}" % (i, s2)
w("  U32{%s}" % s2)
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "bits.bend"), "w", newline="\n").write("\n".join(out) + "\n")
