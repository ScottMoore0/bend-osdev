def aria_chain():
    """A as elementary steps (a, b), meaning x_a ^= x_b, in the order they
    are applied: Gaussian elimination reduces A's matrix to the identity by
    row additions R_1 .. R_k, so A = R_1 R_2 .. R_k and A x applies R_k
    first"""
    m = [[1 if j in ARIA_A[i] else 0 for j in range(16)] for i in range(16)]
    ops = []
    for c in range(16):
        if m[c][c] == 0:
            r = next(r for r in range(c + 1, 16) if m[r][c])
            m[c] = [x ^ y for x, y in zip(m[c], m[r])]
            ops.append((c, r))
        for r in range(16):
            if r != c and m[r][c]:
                m[r] = [x ^ y for x, y in zip(m[r], m[c])]
                ops.append((r, c))
    assert m == [[int(i == j) for j in range(16)] for i in range(16)]
    chain = list(reversed(ops))
    x = list(range(1, 17))
    for a, b in chain:
        x[a] ^= x[b]
    want = [0] * 16
    for i, row in enumerate(ARIA_A):
        for j in row:
            want[i] ^= j + 1
    assert x == want
    return chain


ARIA_CHAIN = aria_chain()


def aria_steps():
    """the chain's consecutive additions from one source b into several
    targets (none of them b) grouped into one step (b, targets)"""
    steps = []
    for a, b in ARIA_CHAIN:
        if steps and steps[-1][0] == b and a not in steps[-1][1]:
            steps[-1][1].append(a)
        else:
            steps.append((b, [a]))
    return steps


ARIA_STEPS = aria_steps()


# ---------------------------------------------------------------- Bend

def word8(v):
    s = "WNil{}"
    for i in reversed(range(8)):
        s = "WCon{%s, %s}" % ("True{}" if (v >> i) & 1 else "False{}", s)
    return s


def sbox_tree(tab, depth, idx, ind):
    """the decision tree on bits depth .. 7 of w<depth>, least significant
    first"""
    if depth == 8:
        return ind + word8(tab[idx])
    out = [ind + "match w%d:" % depth]
    for val, cons in ((0, "False{}"), (1, "True{}")):
        out.append(ind + "  case WCon{%s, w%d}:" % (cons, depth + 1))
        out.append(sbox_tree(tab, depth + 1, idx | (val << depth), ind + "    "))
    return "\n".join(out)


def sbox_def(name, tab, comment):
    return "# %s\ndef %s(w0: Word(8n)) -> Word(8n):\n%s\n" % (comment, name, sbox_tree(tab, 0, 0, "  "))


def aria_region():
    parts = [sbox_def("aria.sb1", ARIA_SB1, "SB1 (RFC 5794, 2.4.2; the AES S-box), on a byte's bits, least significant\n# first"),
             sbox_def("aria.sb2", ARIA_SB2, "SB2 (RFC 5794, 2.4.2)"),
             sbox_def("aria.sb3", ARIA_SB3, "SB3, the inverse of SB1"),
             sbox_def("aria.sb4", ARIA_SB4, "SB4, the inverse of SB2")]
    return "\n".join(parts)


def aria_diffusion_region():
    n = len(ARIA_STEPS)
    out = ["# the steps: e<j> XORs byte b into each byte of its targets"]
    for j, (b, ts) in enumerate(ARIA_STEPS):
        pat = ", ".join(("+x%d" % i) if i == b else ("x%d" % i) for i in range(16))
        res = ", ".join(("Word.xor(8n, x%d, x%d)" % (i, b)) if i in ts else ("x%d" % i) for i in range(16))
        out.append("def aria.e%d(s: LcAriaSt) -> LcAriaSt:\n  match s:\n    case LcAriaSt{%s}:\n      LcAriaSt{%s}\n" % (j, pat, res))
    out.append("# d<j>: the first j steps; u<j>: them undone, last first")
    out.append("def aria.d0(s: LcAriaSt) -> LcAriaSt:\n  s\n")
    out.append("def aria.u0(s: LcAriaSt) -> LcAriaSt:\n  s\n")
    for j in range(n):
        out.append("def aria.d%d(s: LcAriaSt) -> LcAriaSt:\n  aria.e%d(aria.d%d(s))\n" % (j + 1, j, j))
        out.append("def aria.u%d(s: LcAriaSt) -> LcAriaSt:\n  aria.u%d(aria.e%d(s))\n" % (j + 1, j, j))
    out.append("# A, and A undone (%d steps)" % n)
    out.append("def aria.diffuse(s: LcAriaSt) -> LcAriaSt:\n  aria.d%d(s)\n" % n)
    out.append("def aria.undiffuse(s: LcAriaSt) -> LcAriaSt:\n  aria.u%d(s)\n" % n)
    return "\n".join(out)


REGIONS = [("aria.bend", "sboxes", aria_region), ("aria.bend", "diffusion", aria_diffusion_region)]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fname, name, body in REGIONS:
        path = os.path.join(PKG, fname)
        with open(path, encoding="utf-8", newline="") as f:
            src = f.read()
        begin = "# BEGIN GENERATED by gen/tables.py: %s\n" % name
        end = "# END GENERATED: %s\n" % name
        i = src.index(begin) + len(begin)
        j = src.index(end, i)
        new = src[:i] + body() + src[j:]
        if new != src:
            stale.append("%s (%s)" % (fname, name))
            if not check:
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(new)
    if check:
        if stale:
            print("out of date (run gen/tables.py): " + ", ".join(stale))
            sys.exit(1)
        print("generated tables up to date")


if __name__ == "__main__":
    main()

