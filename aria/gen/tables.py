#!/usr/bin/env python3
"""ARIA's S-boxes and diffusion layer, and the generator of the Bend code that
holds them.

  python3 gen/tables.py           rewrite the generated regions
  python3 gen/tables.py --check   only check that they are up to date

The data below is transcribed from the specification; what can be
computed from a specification's definition is computed instead:
  * ARIA_SB2: RFC 5794, A Description of the ARIA Encryption Algorithm,
    section 2.4.2 (SB3 and SB4 are the inverses of SB1 and SB2, computed);
  * ARIA's SB1 is the AES S-box (FIPS 197, section 5.1.1), computed from its
    definition: the inverse in GF(2^8) mod x^8+x^4+x^3+x+1, then the affine
    transformation.

They are checked when ref/gen.py runs: RFC 5794's test vectors, and
OpenSSL's ARIA (the openssl command).

Regions, each between "# BEGIN GENERATED by gen/tables.py: <name>" and
"# END GENERATED: <name>":
  aria.bend     "sboxes"   aria.sb1 .. aria.sb4, each a decision tree on the
                           eight bits of a byte (no table at run time, and a
                           proof can compute through it)
  aria.bend     "diffusion" the diffusion layer A (RFC 5794, 2.4.3) as a chain
                           of steps "x_t ^= x_b for each t of a set T not
                           holding b" (aria.e0 ..), found by Gaussian
                           elimination over GF(2) on A's matrix (126 row
                           additions, grouped by their source into 22
                           steps): aria.d<j> applies the first j steps and
                           aria.u<j> undoes them, so A is aria.d<n> and its
                           inverse aria.u<n>, each step undone by itself
"""
