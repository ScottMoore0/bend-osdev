#!/usr/bin/env python3
"""Writes asn1/proof_byte.bend. Run from the package directory:
python3 gen/gen_byte.py > proof_byte.bend

Two facts about single octets, each proved for every value by a chain of
lemmas over K + k (one closed computation per value):

* ab.byte: a value k below 256, made an octet as the encoder writes it
  (a1.b), reads back as k;
* ab.id1: the leading identifier octet of a class, a P/C bit and bits 5 to
  1 below 32 reads back as those three (tag.bend's a1.id1).
"""
CLASSES = ["Asn1Universal", "Asn1Application", "Asn1Context", "Asn1Private"]
BOOLS = ["True", "False"]

out = []
p = out.append
p("""# Generated by gen/gen_byte.py: do not edit.
#
# ab.byte: every value k below 256, written as an octet (a1.b), reads back
# as k. ab.id1: the leading identifier octet of every class, P/C bit and
# low bits below 32 reads back as them. Each by a chain of lemmas over
# K + k, each a closed computation or a step to the next.
import Base
import ../bytes/bytes.bend as B
import ./number.bend as Nu
import ./tag.bend as T
import ./proof_nat.bend as AN

def ab.abs(+k: Nat, e: Empty) -> {U32.to_nat(Nu.a1.b(k)) == k : Nat}:
  Empty.absurd({U32.to_nat(Nu.a1.b(k)) == k : Nat}, e)
""")
p("""def ab.b256(+k: Nat, +lt: {Nat.is_lt(Nat.add(256n, k), 256n) == True{} : Bool}) -> {U32.to_nat(Nu.a1.b(Nat.add(256n, k))) == Nat.add(256n, k) : Nat}:
  match k:
    case 0n:
      ab.abs(Nat.add(256n, 0n), AN.an.ft(lt))
    case 1n+q:
      ab.abs(Nat.add(256n, 1n+q), AN.an.ft(lt))
""")
for K in range(255, -1, -1):
    p("""def ab.b%d(+k: Nat, +lt: {Nat.is_lt(Nat.add(%dn, k), 256n) == True{} : Bool}) -> {U32.to_nat(Nu.a1.b(Nat.add(%dn, k))) == Nat.add(%dn, k) : Nat}:
  match k:
    case 0n:
      {==}
    case 1n+q:
      ab.b%d(q, lt)
""" % (K, K, K, K, K + 1))
p("""# k below 256: k as an octet reads back as k
def ab.byte(+k: Nat, +lt: {Nat.is_lt(k, 256n) == True{} : Bool}) -> {U32.to_nat(Nu.a1.b(k)) == k : Nat}:
  ab.b0(k, lt)
""")
for ci, c in enumerate(CLASSES):
    for b in BOOLS:
        tag = "%s_%s" % (ci, b[0].lower())
        ty = lambda low: "{T.a1.id1(U32.to_nat(Nu.a1.b(T.a1.id_octet(T.%s{}, %s{}, %s)))) == T.A1Id1{T.%s{}, %s{}, %s} : T.A1Id1}" % (c, b, low, c, b, low)
        p("""def ab.i%s_32(+k: Nat, +lt: {Nat.is_lt(Nat.add(32n, k), 32n) == True{} : Bool}) -> %s:
  match k:
    case 0n:
      Empty.absurd(%s, AN.an.ft(lt))
    case 1n+q:
      Empty.absurd(%s, AN.an.ft(lt))
""" % (tag, ty("Nat.add(32n, k)"), ty("Nat.add(32n, 0n)"), ty("Nat.add(32n, 1n+q)")))
        for K in range(31, -1, -1):
            p("""def ab.i%s_%d(+k: Nat, +lt: {Nat.is_lt(Nat.add(%dn, k), 32n) == True{} : Bool}) -> %s:
  match k:
    case 0n:
      {==}
    case 1n+q:
      ab.i%s_%d(q, lt)
""" % (tag, K, K, ty("Nat.add(%dn, k)" % K), tag, K + 1))
p("""# the leading identifier octet of a class, P/C bit and low bits (below 32)
# reads back as them
def ab.id1(c: T.Asn1Class, cons: Bool, +low: Nat, +lt: {Nat.is_lt(low, 32n) == True{} : Bool}) -> {T.a1.id1(U32.to_nat(Nu.a1.b(T.a1.id_octet(c, cons, low)))) == T.A1Id1{c, cons, low} : T.A1Id1}:
  match c cons:""")
for ci, c in enumerate(CLASSES):
    for b in BOOLS:
        p("""    case T.%s{} %s{}:
      ab.i%s_%s_0(low, lt)""" % (c, b, ci, b[0].lower()))
print("\n".join(out))
