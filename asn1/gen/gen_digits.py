#!/usr/bin/env python3
"""Writes asn1/proof_d2.bend, the digit library of the time proofs. Run from
the package directory:

    python3 gen/gen_digits.py           writes proof_d2.bend
    python3 gen/gen_digits.py --check   fails if proof_d2.bend differs

pk.d2(v, lt): for every v below 100, the two characters time.bend's writer
puts down for v (a1.t.d2: the tens digit, then the units digit) are digits
(a1.t.dig), are octets (fixed by bytes' byte), and read back as v
(a1.t.val, tens times ten plus units). A chain of lemmas over K + k, one
closed computation per value; 100 or more is refuted by lt.
"""
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def gen():
    L = []
    p = L.append
    p('''# Generated by gen/gen_digits.py: do not edit.
#
# The digit library of the time proofs: for every v below 100, the two
# characters the writer puts down for v (time.bend's a1.t.d2) are digits,
# are octets, and read back as v. A chain of lemmas over K + k, each a
# closed computation or a step to the next.
import Base
import ../bytes/bytes.bend as B
import ./time.bend as Ti
import ./proof_nat.bend as AN

# what is checked of v's two characters a and b: both digits, both octets,
# and the value they read as
type PkD2 is Data:
  PkD2{da: Bool, db: Bool, ma: Bool, mb: Bool, v: Nat}

def pk.d2f.go(+a: U32, +b: U32) -> PkD2:
  PkD2{Ti.a1.t.dig(a), Ti.a1.t.dig(b), U32.is_eq(B.byte(a), a), U32.is_eq(B.byte(b), b), Nat.add(Nat.mul(Ti.a1.t.val(a), 10n), Ti.a1.t.val(b))}

def pk.d2f(+v: Nat) -> PkD2:
  pk.d2f.go(U32.from_nat(Nat.add(48n, Nat.div(v, 10n))), U32.from_nat(Nat.add(48n, Nat.mod(v, 10n))))
''')

    def ty(v):
        return "{pk.d2f(%s) == PkD2{True{}, True{}, True{}, True{}, %s} : PkD2}" % (v, v)

    p("def pk.d2_100(+k: Nat, +lt: {Nat.is_lt(Nat.add(100n, k), 100n) == True{} : Bool}) -> %s:" % ty("Nat.add(100n, k)"))
    p("  match k:\n    case 0n:\n      Empty.absurd(%s, AN.an.ft(lt))\n    case 1n+q:\n      Empty.absurd(%s, AN.an.ft(lt))\n" % (ty("Nat.add(100n, 0n)"), ty("Nat.add(100n, 1n+q)")))
    for K in range(99, -1, -1):
        p("def pk.d2_%d(+k: Nat, +lt: {Nat.is_lt(Nat.add(%dn, k), 100n) == True{} : Bool}) -> %s:" % (K, K, ty("Nat.add(%dn, k)" % K)))
        p("  match k:\n    case 0n:\n      {==}\n    case 1n+q:\n      pk.d2_%d(q, lt)\n" % (K + 1))
    p("# v below 100: its two characters are digits and octets, and read back as v")
    p("def pk.d2(+v: Nat, +lt: {Nat.is_lt(v, 100n) == True{} : Bool}) -> %s:\n  pk.d2_0(v, lt)" % ty("v"))
    return "\n".join(L) + "\n"


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        raise SystemExit("usage: python3 gen/gen_digits.py [--check]")
    path = os.path.join(HERE, "proof_d2.bend")
    text = gen()
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        if check:
            raise SystemExit("not what gen/gen_digits.py writes: proof_d2.bend")
        with open(path, "w", newline="\n") as f:
            f.write(text)


main()
