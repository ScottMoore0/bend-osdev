def al_step(slot, t):
    A_ = 'Sc.a1.s.align(rest, Sc.a1.s.hit_head(rest, %s), %s)' % (t, t)
    return ('Equal.trans(%s, cf.sch(cf.sl(Sc.a1.s.slot(%s, %s))), Con{s, cf.sch(cf.sl(%s))}, Con{s, rest}, cf.slot_sch(%s, %s), '
            'Equal.cong(%s, %s, z => Con{s, z}, cf.sch(cf.sl(%s)), rest, cf.al(rest, Sc.a1.s.hit_head(rest, %s), %s)))') % (
        LS, slot, A_, A_, slot, A_, LS, LS, A_, t, t)

w('# the slots of a sequence\'s fields are its fields, in order')
