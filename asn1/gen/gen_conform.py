w('def cf.present(+D: Nat, ok: Bool, +s: Sc.Asn1Schema, +e: A.Asn1Tlv, +res: %s, +h: {cf.r(D, Sc.A1WOne{Sc.a1.s.inner(s), e}, res) == True{} : Bool}) -> {cf.slot(1n+D, s, Sc.a1.s.present(ok, res)) == True{} : Bool}:' % RL)
