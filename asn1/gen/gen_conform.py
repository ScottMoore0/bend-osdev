w('        case Con{+x, +t}:')
w('          match ms:')
w('            case Nil{}:')
w('              {==}')
w('            case Con{+y, +ys}:')
a, b = conf('p', ONE, '[item]', '[y]'), conf('1n+p', FLD, 'cf.sch(Sc.a1.s.of_slots(t, item))', 'ys')
w('              cf.and2(%s, %s, cf.and_l(%s, %s, h), cf.ofs(1n+p, t, item, ys, cf.and_r(%s, %s, h)))' % (
    a, conf('1n+p', ALL, '[item]', 'ys'), a, b, a, b))
w('')

