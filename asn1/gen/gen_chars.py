#!/usr/bin/env python3
"""Writes asn1/proof_chars.bend: the string checks of the one-octet types
against X.680's tables (LAWS_typed.bend's asn1law.*_chars). Run from the
package directory:

    python3 gen/gen_chars.py           writes proof_chars.bend
    python3 gen/gen_chars.py --check   fails if proof_chars.bend differs

pc.oct(x): for every octet (the byte of any word), the checks of
NumericString, PrintableString, IA5String and VisibleString (string.bend's
a1.charset) answer as membership of the tables does. The octet's eight bits
are split one at a time (pc.t_<bits>, one def per prefix of known bits), so
each of the 256 octets is a closed computation.
"""
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def word(bits):
    s = "Word.zero(24n)"
    for b in reversed(bits):
        s = "WCon{%s, %s}" % (b, s)
    return "U32{%s}" % s


def name(prefix):
    return "pc.t_" + ("".join(prefix) if prefix else "x")


def gen():
    L = []
    p = L.append
    p('''# Generated by gen/gen_chars.py: do not edit.
#
# The string checks of the one-octet types against X.680's tables
# (LAWS_typed.bend): for every octet, NumericString's, PrintableString's,
# IA5String's and VisibleString's checks answer as membership of their
# tables does. The octet's bits are split one at a time (pc.t_<bits>), so
# each of the 256 octets is a closed computation.
import Base
import ../bytes/bytes.bend as B
import ./string.bend as S
import ./LAWS_typed.bend as Laws

# the four checks of an octet, and its membership of the four tables
type PcCh is Data:
  PcCh{num: Bool, pr: Bool, ia: Bool, vi: Bool}

def pc.chk(+x: U32) -> PcCh:
  PcCh{S.a1.charset(S.Asn1Numeric{}, x), S.a1.charset(S.Asn1Printable{}, x), S.a1.charset(S.Asn1Ia5{}, x), S.a1.charset(S.Asn1Visible{}, x)}

def pc.tbl(+x: U32) -> PcCh:
  PcCh{Laws.asn1law.member(x, Laws.asn1law.numeric_chars()), Laws.asn1law.member(x, Laws.asn1law.printable_chars()), Laws.asn1law.member(x, Laws.asn1law.ia5_chars()), Laws.asn1law.member(x, Laws.asn1law.visible_chars())}
''')
    for k in range(7, -1, -1):
        for n in range(2 ** k):
            prefix = [("True{}" if (n >> (k - 1 - i)) & 1 else "False{}") for i in range(k)]
            short = ["1" if (n >> (k - 1 - i)) & 1 else "0" for i in range(k)]
            free = ["b%d" % i for i in range(k, 8)]
            w = word(prefix + free)
            params = ", ".join("%s: Bool" % f for f in free)
            p("def %s(%s) -> {pc.chk(%s) == pc.tbl(%s) : PcCh}:" % (name(short), params, w, w))
            p("  match b%d:" % k)
            for bit, tag in (("True{}", "1"), ("False{}", "0")):
                p("    case %s:" % bit)
                if k == 7:
                    p("      {==}")
                else:
                    p("      %s(%s)" % (name(short + [tag]), ", ".join(free[1:])))
            p("")
    p("# every octet: the checks answer as the tables do")
    p("def pc.oct(x: U32) -> {pc.chk(B.byte(x)) == pc.tbl(B.byte(x)) : PcCh}:")
    p("  match x:")
    p("    case U32{WCon{c0, WCon{c1, WCon{c2, WCon{c3, WCon{c4, WCon{c5, WCon{c6, WCon{c7, hi}}}}}}}}}:")
    p("      pc.t_x(c0, c1, c2, c3, c4, c5, c6, c7)")
    return "\n".join(L) + "\n"


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        raise SystemExit("usage: python3 gen/gen_chars.py [--check]")
    path = os.path.join(HERE, "proof_chars.bend")
    text = gen()
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        if check:
            raise SystemExit("not what gen/gen_chars.py writes: proof_chars.bend")
        with open(path, "w", newline="\n") as f:
            f.write(text)


main()
