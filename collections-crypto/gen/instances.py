    dict(name="blake3", title="BLAKE3-256", tp=[], digest="Bl.CcBlake.blake3"),
    dict(name="blake2b_n", title="BLAKE2b with an nn-byte digest, for every nn", tp=["~nn: Nat"],
         digest="Bl.CcBlake.blake2b_n(~nn)"),
