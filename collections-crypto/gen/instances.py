# ---------------------------------------------------------------- schemas

LAWS, PROOFS = [], []


def law(name, comment, params, stmt):
    head = "".join("  for %s\n" % p for p in params)
    com = "".join("# %s\n" % l for l in textwrap.wrap(comment, 76))
    LAWS.append("%slaw %s:\n%s  %s\n" % (com, name, head, stmt))


def proof(text):
    PROOFS.append(text)


def call(fn, *args):
    """a def given with its template arguments, called on args"""
    if fn.endswith(")"):
        return fn[:-1] + "".join(", " + a for a in args) + ")" if args else fn
    return "%s(%s)" % (fn, ", ".join(args)) if args else fn


def res(E, A):
    return "Result<&2, &2, %s, %s>" % (E, A)


def tnames(c):
    return "".join(t.split(":")[0].strip("~ ") + ", " for t in c["tp"])


def hash_laws(c):
    n, d = c["name"], c["digest"]
    upd = "C.CcBuf.update"
    fin = "C.CcBuf.final(~%s)" % d
    law("%s_hash_split" % n,
        "%s as a hash (buffered): streaming in two pieces is the one-shot digest, for every split" % c["title"],
        c["tp"] + ["+a: B.Octets", "+b: B.Octets"],
        "{%s == %s : B.Octets}" % (call(fin, "%s(%s(C.CcBuf.init(), a), b)" % (upd, upd)), call(d, "B.Octets.append(a, b)")))
    proof("def Laws.%s_hash_split(%sa, b):\n  Laws.buf_split(~%s, a, b)\n" % (n, tnames(c), d))
    law("%s_hash_split3" % n,
        "%s as a hash (buffered): streaming in three pieces is the one-shot digest" % c["title"],
        c["tp"] + ["+a: B.Octets", "+b: B.Octets", "+c: B.Octets"],
        "{%s == %s : B.Octets}" % (call(fin, "%s(%s(%s(C.CcBuf.init(), a), b), c)" % (upd, upd, upd)),
                                   call(d, "B.Octets.append(a, B.Octets.append(b, c))")))
    proof("def Laws.%s_hash_split3(%sa, b, c):\n  Laws.buf_split3(~%s, a, b, c)\n" % (n, tnames(c), d))


def stream_laws(c):
    n, S, nx = c["name"], c["S"], c["next"]
    up = lambda s, m: call(c["update"], s, m)
    od = lambda o: call(c["out_data"], o)
    os_ = lambda o: call(c["out_state"], o)
    law("%s_stream_involution" % n,
        "%s as a stream cipher: decryption is encryption, for every state and data" % c["title"],
        c["tp"] + ["+s: %s" % S, "+m: B.Octets"],
        "{%s == m : B.Octets}" % od(up("s", od(up("s", "m")))))
    proof("def Laws.%s_stream_involution(%ss, m):\n  cc_xor_involution(~%s, ~%s, s, m)\n" % (n, tnames(c), S, nx))
    law("%s_stream_streaming_data" % n,
        "%s: the data a ++ b gives the output of a, then the output of b from the state after a" % c["title"],
        c["tp"] + ["+s: %s" % S, "+a: B.Octets", "+b: B.Octets"],
        "{%s == B.Octets.append(%s, %s) : B.Octets}" % (od(up("s", "B.Octets.append(a, b)")), od(up("s", "a")),
                                                        od(up(os_(up("s", "a")), "b"))))
    proof("def Laws.%s_stream_streaming_data(%ss, a, b):\n  cc_xor_streaming_data(~%s, ~%s, s, a, b)\n" % (n, tnames(c), S, nx))
    law("%s_stream_streaming_state" % n,
        "%s: the state after a ++ b is the state after a, then b" % c["title"],
        c["tp"] + ["+s: %s" % S, "+a: B.Octets", "+b: B.Octets"],
        "{%s == %s : %s}" % (os_(up("s", "B.Octets.append(a, b)")), os_(up(os_(up("s", "a")), "b")), S))
    proof("def Laws.%s_stream_streaming_state(%ss, a, b):\n  cc_xor_streaming_state(~%s, ~%s, s, a, b)\n" % (n, tnames(c), S, nx))


def mac_laws(c):
    n, K = c["name"], c["K"]
    law("%s_accepts" % n, "%s as a MAC: verify accepts the computed tag, for every key and message" % c["title"],
        ["+k: %s" % K, "+m: B.Octets"],
        "{%s == True{} : Bool}" % call(c["verify"], "k", "m", call(c["compute"], "k", "m")))
    proof("def Laws.%s_accepts(k, m):\n  BL.octets_is_eq_refl(%s)\n" % (n, call(c["compute"], "k", "m")))
    law("%s_agrees" % n, "%s: verify accepts exactly the computed tag, comparing every byte" % c["title"],
        ["+k: %s" % K, "+m: B.Octets", "t: B.Octets"],
        "{%s == B.Octets.is_eq(%s, t) : Bool}" % (call(c["verify"], "k", "m", "t"), call(c["compute"], "k", "m")))
    proof("def Laws.%s_agrees(k, m, t):\n  {==}\n" % n)


def sign_laws(c):
    n, SK, PK = c["name"], c["SK"], c["PK"]
    R = res("Cr.CrError", PK)
    pub = call(c["public"], "sk")
    sig = call(c["sign"], "sk", "m")
    law("%s_verify_bytes_if" % n,
        "%s (crypto's sign_verify_bytes_if): a signature checked from the public key's bytes is accepted, for every key and message, when the public key survives its bytes (hf) and the scheme accepts the signature (ha)" % c["title"],
        c["tp"] + ["+sk: %s" % SK, "+m: B.Octets", "hf: {%s == Done{%s} : %s}" % (call(c["pk_of"], call(c["pk_to"], pub)), pub, R),
                   "ha: {%s == True{} : Bool}" % call(c["verify"], pub, "m", sig)],
        "{Sg.CrSign.verify_bytes(~%s, ~%s, ~%s, %s, m, %s) == True{} : Bool}" % (PK, c["pk_of"], c["verify"], call(c["pk_to"], pub), sig))
    proof("def Laws.%s_verify_bytes_if(%ssk, m, hf, ha):\n"
          "  %%Equal.sym(%s, %s, Done{%s}, hf) : {Sg.cr.sign.check(~%s, ~%s, _, m, %s) == True{} : Bool}\n"
          "  ha\n" % (n, tnames(c), R, call(c["pk_of"], call(c["pk_to"], pub)), pub, PK, c["verify"], sig))


def kex_laws(c):
    n, SK, PK = c["name"], c["SK"], c["PK"]
    RS, RP, RO = res("Cr.CrError", SK), res("Cr.CrError", PK), res("Cr.CrError", "B.Octets")
    px, py = call(c["public"], "x"), call(c["public"], "y")
    fx, fy = call(c["pk_of"], call(c["pk_to"], px)), call(c["pk_of"], call(c["pk_to"], py))

    def agree(k, peer):
        return "Kx.CrKex.agree(~%s, ~%s, ~%s, ~%s, ~%s, %s, %s)" % (SK, PK, c["secret"], c["pk_of"], c["shared"], k, peer)

    def with_(sk, pk):
        return "Kx.cr.kex.with(~%s, ~%s, ~%s, %s, %s)" % (SK, PK, c["shared"], sk, pk)

    lhs, rhs = agree("a", call(c["pk_to"], py)), agree("b", call(c["pk_to"], px))
    law("%s_agree_if" % n,
        "%s (crypto's kex_agree_if): two parties agree from each other's public-key bytes, for every pair of keys, when the keys parse (hx, hy), the public keys survive their bytes (hfx, hfy) and the shared secrets agree (h)" % c["title"],
        c["tp"] + ["+a: B.Octets", "+b: B.Octets", "+x: %s" % SK, "+y: %s" % SK,
                   "hx: {%s == Done{x} : %s}" % (call(c["secret"], "a"), RS), "hy: {%s == Done{y} : %s}" % (call(c["secret"], "b"), RS),
                   "hfx: {%s == Done{%s} : %s}" % (fx, px, RP), "hfy: {%s == Done{%s} : %s}" % (fy, py, RP),
                   "h: {%s == %s : %s}" % (call(c["shared"], "x", py), call(c["shared"], "y", px), RO)],
        "{%s == %s : %s}" % (lhs, rhs, RO))
    sx = call(c["shared"], "x", py)
    proof("def Laws.%s_agree_if(%sa, b, x, y, hx, hy, hfx, hfy, h):\n" % (n, tnames(c))
          + "  %%Equal.sym(%s, %s, Done{x}, hx) : {%s == %s : %s}\n" % (RS, call(c["secret"], "a"), with_("_", fy), rhs, RO)
          + "  %%Equal.sym(%s, %s, Done{%s}, hfy) : {%s == %s : %s}\n" % (RP, fy, py, with_("Done{x}", "_"), rhs, RO)
          + "  %%Equal.sym(%s, %s, Done{y}, hy) : {%s == %s : %s}\n" % (RS, call(c["secret"], "b"), sx, with_("_", fx), RO)
          + "  %%Equal.sym(%s, %s, Done{%s}, hfx) : {%s == %s : %s}\n" % (RP, fx, px, sx, with_("Done{y}", "_"), RO)
          + "  h\n")


def fmt_laws(c):
    n, PK, ctor, raw = c["name"], c["PK"], c["ctor"], c["raw"]
    R = res("Cr.CrError", PK)
    law("%s_pk_format" % n,
        "%s: a public key read from bytes is read again from the bytes written for it, for every input" % c["title"],
        ["+o: B.Octets", "+p: %s" % PK, "h: {%s == Done{p} : %s}" % (call(c["pk_of"], "o"), R)],
        "{%s == Done{p} : %s}" % (call(c["pk_of"], call(c["pk_to"], "p")), R))
    to = lambda x: call(c["pk_to"], x)
    goal = "{%s(Nat.is_eq(B.Octets.len(%s), 32n), %s) == Done{p} : %s}" % (raw, to("p"), to("p"), R)
    proof("def cc_%s_fmt(+v: Bool, +o: B.Octets, +p: %s, +hv: {Nat.is_eq(B.Octets.len(o), 32n) == v : Bool}, h: {%s(v, o) == Done{p} : %s}) -> %s:\n"
          "  match v:\n"
          "    case False{}:\n"
          "      Empty.absurd(%s, cc_fd_absurd(%s, Cr.CrBadPublicKey{}, p, h))\n"
          "    case True{}:\n"
          "      %%cc_done_inj(%s, %s{o}, p, h) : {%s(Nat.is_eq(B.Octets.len(%s), 32n), %s) == Done{_} : %s}\n"
          "      %%Equal.sym(Bool, Nat.is_eq(B.Octets.len(o), 32n), True{}, hv) : {%s(_, o) == Done{%s{o}} : %s}\n"
          "      {==}\n\n"
          "def Laws.%s_pk_format(o, p, h):\n"
          "  cc_%s_fmt(Nat.is_eq(B.Octets.len(o), 32n), o, p, {==}, h)\n"
          % (n, PK, raw, R, goal, goal, PK, PK, ctor, raw, to("_"), to("_"), R, raw, ctor, R, n, n))


for c in HASH:
    hash_laws(c)
for c in STREAM:
    stream_laws(c)
for c in MAC:
    mac_laws(c)
for c in SIGN:
    sign_laws(c)
for c in KEX:
    kex_laws(c)
for c in FMT:
    fmt_laws(c)

# ---------------------------------------------------------------- bits


def u32(p):
    """the pattern splitting a U32 into its bits p0 .. p31"""
    return "U32{" + "".join("WCon{%s%d, " % (p, i) for i in range(32)) + "WNil{}" + "}" * 32 + "}"


def bits_region():
    return ("# the low byte of a XOR depends only on the low byte of its first operand\n"
            "def cc_byte_xor_byte(z: U32, k: U32) -> {B.byte(U32.xor(z, k)) == B.byte(U32.xor(B.byte(z), k)) : U32}:\n"
            "  match z k:\n    case %s %s:\n      {==}\n" % (u32("a"), u32("b")))


# ---------------------------------------------------------------- regions

REGIONS = [("LAWS.bend", "laws", lambda: "\n".join(LAWS)), ("PROOF.bend", "proofs", lambda: "\n".join(PROOFS)),
           ("PROOF.bend", "bits", bits_region)]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fname, name, body in REGIONS:
        path = os.path.join(PKG, fname)
        with open(path) as f:
            text = f.read()
        begin = "# BEGIN GENERATED by gen/instances.py: %s\n" % name
        end = "# END GENERATED: %s\n" % name
        i, j = text.index(begin) + len(begin), text.index(end)
        new = text[:i] + body() + text[j:]
        if new != text:
            stale.append("%s (%s)" % (fname, name))
            if not check:
                with open(path, "w", newline="\n") as f:
                    f.write(new)
    if check:
        if stale:
            print("out of date (run gen/instances.py): " + ", ".join(stale))
            sys.exit(1)
        print("generated regions up to date")


if __name__ == "__main__":
    main()
