#!/usr/bin/env python3
"""The instances of crypto's interfaces that collections-crypto adapts, and
their laws.

  python3 gen/instances.py           rewrite the generated regions
  python3 gen/instances.py --check   only check that they are up to date

Each region lies between "# BEGIN GENERATED by gen/instances.py: <name>" and
"# END GENERATED: <name>":
  * "laws" in LAWS.bend: one law per instance and law schema;
  * "proofs" in PROOF.bend: their proofs;
  * "bits" in PROOF.bend: the lemma proved on a word's 32 bits that the
    stream laws use (a deep pattern splitting each U32 into its bits, then
    computation).
Everything outside the regions is written by hand.

This is the package's own table, as pubkey's gen/instances.py is: crypto's
check already takes about 2.3 GB of the 3 GB a check may use, so these
instances add no rows to crypto's gen/instances.py.

The schemas:
  * HASH (a buffered hash, collections-crypto.bend's CcBuf, over a one-shot
    digest): <h>_hash_split and <h>_hash_split3, from the generic buf_split
    and buf_split3 (LAWS.bend, by hand); the streaming law is buf_streaming
    itself, the same for every buffered hash (one state type, one update);
  * STREAM (a keystream generator under crypto's CrXor): the stream
    interface's involution, streaming_data and streaming_state, from the
    generic lemmas in PROOF.bend (crypto's, written out);
  * MAC (crypto's named default verify, CrMac.verify_tag): accepts and
    agrees;
  * SIGN, KEX: crypto's sign_verify_bytes_if and kex_agree_if written out
    for the instance, as pubkey's are;
  * FMT (a public key held as its bytes, read from 32 bytes):
    <x>_pk_format, a public key read from bytes is read again from the
    bytes written for it, for every input.

Adding an instance: a row in the table it belongs to, then run this script.
"""
import os, sys, textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")

# ---------------------------------------------------------------- instances

