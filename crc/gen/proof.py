#!/usr/bin/env python3
"""Writes crc/proof_cases.bend and crc/proof_cases64.bend: the case-split
lemmas of crc's fast-path proofs, at 32 and at 64 bits.

The table-driven fast path (table.bend) is tied to the bitwise reference
(crc.bend) for every parameter set and input in proof_fast.bend, by hand,
from the bitwise identities of proof_word.bend and the engine lemmas of
proof_engine.bend. What is left for this generator is what is proved by
splitting words into their bits and computing:

  * the tables as lists: entry i of each table is the engine's eight steps on
    the byte i (ct.er, ct.en), and the model of the fill loop computes to
    that list (ct.er_model, ct.en_model);
  * a table read: the entry at the index of a byte is the engine on that
    byte, by cases on the byte's eight bits (ct.look_r, ct.look_n), 32
    cases per def to stay within --verdict's per-def budget;
  * the parts of a byte step that hold by computation on a register split
    into its 32 bits: XOR with the input byte splits into its high and low
    parts (ct.r_split), and eight steps on a register whose low byte is
    clear (reflected) or whose top byte is clear (most significant bit
    first, one lemma per width from 8 to 32) only shift it;
  * the most-significant-first test of bit k: (x & (1 << k)) != 0 is the
    bit k of x, one case per k below 32.

At 64 bits (proof_cases64.bend), on a W64 given by its halves: word64's
shifts by one and by eight are the clean shifts of proof_engine64.bend (the
OR joining the halves is rewritten to one that reads its second operand
first, and the bits crossing between the halves are split, 32 cases per
def), eight steps on a register whose byte to come is clear only shift it,
and the tables as lists with their reads at a byte.

Run: python3 crc/gen/proof.py   (from the repository root or anywhere)
"""
import itertools, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "proof_cases.bend")

lines = []


def emit(s=""):
    lines.append(s)


def word(bs, tail="WNil{}"):
    s = tail
    for b in reversed(bs):
        s = "WCon{" + b + ", " + s + "}"
    return s


def u32(bs, tail="WNil{}"):
    return "U32{" + word(bs, tail) + "}"


def bitvars(p, n=32):
    return [f"{p}{i}" for i in range(n)]


def pat(p, n=32, plus=False):
    vs = [("+" if plus else "") + v for v in bitvars(p, n)]
    return u32(vs)


def tf(b):
    return "True{}" if b else "False{}"


def byte_u32(bs):
    return u32(bs, "Word.zero(24n)")


def eq(a, b, t="U32"):
    return "{" + a + " == " + b + " : " + t + "}"


def nested(vs, leaf, ind):
    """Nested matches on the Bool variables vs, a leaf per assignment."""
    def go(i, env, ind):
        if i == len(vs):
            emit(" " * ind + leaf(env))
            return
        emit(" " * ind + f"match {vs[i]}:")
        for b in (True, False):
            emit(" " * (ind + 2) + f"case {tf(b)}:")
            go(i + 1, env + [b], ind + 4)
    go(0, [], ind)


def header():
    emit("# Generated by gen/proof.py; do not edit by hand.")
    emit("#")
    emit("# Case-split lemmas of crc's fast-path proof (see gen/proof.py and")
    emit("# proof_fast.bend). Lemmas are prefixed ct.")
    emit("import Base")
    emit("import ./crc.bend as C")
    emit("import ../array/array.bend as A")
    emit("import ./proof_word.bend as PW")
    emit("import ./proof_engine.bend as PE")
    emit("import ../u32/LAWS.bend as UL")
    emit("import ../u32/PROOF.bend as UP")
    emit()


NOT255 = 4294967040


def gen_reflected():
    emit("# Reflected: XOR with the input byte, split at the low byte")
    emit()
    c, h = bitvars("c"), bitvars("h")
    emit(f"def ct.r_split(c: U32, h: U32) -> {eq('U32.xor(c, U32.and(255, h))', f'U32.xor(U32.and({NOT255}, c), U32.and(255, U32.xor(c, h)))')}:")
    emit("  match c h:")
    emit(f"    case {pat('c')} {pat('h')}:")
    emit("      {==}")
    emit()
    emit("# eight reflected steps on a register whose low byte is clear shift it")
    emit(f"def ct.r_high(+p: U32, c: U32) -> {eq(f'PE.ce.rb(8n, p, U32.and({NOT255}, c))', 'U32.shrn(c, 8n)')}:")
    emit("  match c:")
    emit(f"    case {pat('c')}:")
    emit("      {==}")
    emit()


def table_list(name, entry, params):
    emit(f"def {name}({params}) -> List<&2, U32>:")
    emit("  [" + ", ".join(entry(i) for i in range(256)) + "]")
    emit()


def look(name, entry_of_byte, table, params, args, T="U32", fill="0"):
    """nth(table, to_nat(byte b0..b7), fill) == entry(byte), split into 8
    defs of 32 cases by (b5, b6, b7)."""
    bs = bitvars("b", 8)
    goal = lambda bb: eq(f"A.Arrays.nth({T}, {table}, U32.to_nat({byte_u32(bb)}), {fill})", entry_of_byte(byte_u32(bb)), T)
    for top in itertools.product((True, False), repeat=3):
        suffix = "".join("1" if t else "0" for t in reversed(top))
        bb = bs[:5] + [tf(t) for t in top]
        ps = params + ", " + ", ".join("+" + b + ": Bool" for b in bs[:5])
        emit(f"def {name}.s{suffix}({ps}) -> {goal(bb)}:")
        nested(bs[:5], lambda env: "{==}", 2)
        emit()
    ps = params + ", " + ", ".join("+" + b + ": Bool" for b in bs)
    emit(f"def {name}({ps}) -> {goal(bs)}:")
    emit("  match b5 b6 b7:")
    for top in itertools.product((True, False), repeat=3):
        suffix = "".join("1" if t else "0" for t in reversed(top))
        emit("    case " + " ".join(tf(t) for t in top) + ":")
        emit(f"      {name}.s{suffix}({args}, " + ", ".join(bs[:5]) + ")")
    emit()


def gen_tables():
    emit("# A table as a list: entry i is the engine e on the byte i")
    emit()
    table_list("ct.tab", lambda i: f"PE.ce.ev(e, U32.from_nat({i}n))", "+e: PE.CrcPfEng")
    emit(f"def ct.tab_model(+e: PE.CrcPfEng) -> {eq('PE.ce.fill_model(256n, List.replicate(U32, A.Arrays.slots(8n), 0), e, 0n)', 'ct.tab(e)', 'List<&2, U32>')}:")
    emit("  {==}")
    emit()
    emit("# a table read at a byte is the engine on the byte")
    look("ct.look", lambda b: f"PE.ce.ev(e, {b})", "ct.tab(e)", "+e: PE.CrcPfEng", "e")


def goal_core(width):
    S, K, M = f"Nat.sub({width}, 8n)", f"Nat.sub({width}, 1n)", f"U32.sub(U32.shln(1, {width}), 1)"
    lhs = f"U32.and({M}, U32.xor(U32.shln(c, 8n), PE.ce.nb(8n, p, {K}, {M}, U32.shln(U32.and(255, U32.xor(U32.shrn(c, {S}), h)), {S}))))"
    rhs = f"PE.ce.nb(8n, p, {K}, {M}, U32.xor(c, U32.shln(U32.and(255, h), {S})))"
    return eq(lhs, rhs)


def gen_msb():
    emit("# Most significant bit first: the test (x & (1 << k)) != 0 is bit k of x")
    emit()
    emit("def ct.test(+k: Nat, +x: U32) -> {Bool.not(U32.is_eq(U32.and(x, U32.shln(1, k)), 0)) == PW.cw.bitk(k, x) : Bool}:")
    ind = 2
    kv = "k"
    for K in range(32):
        emit(" " * ind + f"match {kv}:")
        emit(" " * (ind + 2) + "case 0n:")
        i2 = ind + 4
        emit(" " * i2 + "match x:")
        for b in (True, False):
            bs = [f"x{i}" for i in range(32)]
            bs[K] = tf(b)
            X = u32(bs)
            emit(" " * (i2 + 2) + f"case {X}:")
            emit(" " * (i2 + 4) + f"%UL.u32_and_comm(U32.shln(1, {K}n), {X}) : {{Bool.not(U32.is_eq(_, 0)) == PW.cw.bitk({K}n, {X}) : Bool}}")
            emit(" " * (i2 + 4) + "{==}")
        nk = f"k{K + 1}"
        emit(" " * (ind + 2) + f"case 1n+{nk}:")
        kv = nk
        ind += 4
    j = kv
    K32 = f"Nat.add(32n, {j})"
    emit(" " * ind + f"%Equal.sym(U32, U32.shln(U32.shln(1, {j}), 32n), 0, PW.cw.shl32(U32.shln(1, {j}))) : {{Bool.not(U32.is_eq(U32.and(x, _), 0)) == PW.cw.bitk({K32}, x) : Bool}}")
    emit(" " * ind + f"%UL.u32_and_comm(0, x) : {{Bool.not(U32.is_eq(_, 0)) == PW.cw.bitk({K32}, x) : Bool}}")
    emit(" " * ind + f"%Equal.sym(U32, U32.and(0, x), 0, PW.cw.ua_zero_l(x)) : {{Bool.not(U32.is_eq(_, 0)) == PW.cw.bitk({K32}, x) : Bool}}")
    emit(" " * ind + f"Equal.sym(Bool, PW.cw.bitk({K32}, x), False{{}}, PE.ce.bit_deg({j}, x))")
    emit()
    emit("# For each width w from 8 to 32 (s = w - 8, k = w - 1, m = 2^w - 1, and")
    emit("# win = 255 << s): the input byte's window of the register c, and eight")
    emit("# steps on a register whose window is clear")
    emit()
    for w in range(8, 33):
        s_, k_ = w - 8, w - 1
        m = (1 << w) - 1
        win = 255 << s_
        emit(f"def ct.win{w}(c: U32) -> {eq(f'U32.shln(U32.and(255, U32.shrn(c, {s_}n)), {s_}n)', f'U32.and({win}, c)')}:")
        emit("  match c:")
        emit(f"    case {pat('c')}:")
        emit("      {==}")
        emit()
        emit(f"def ct.high{w}(+p: U32, c: U32) -> {eq(f'PE.ce.nb(8n, p, {k_}n, {m}, U32.and(U32.not({win}), c))', f'U32.and({m}, U32.shln(c, 8n))')}:")
        emit("  match c:")
        emit(f"    case {pat('c')}:")
        emit("      {==}")
        emit()
    emit("# The most-significant-first byte step for every width of 8 and up: by")
    emit("# cases on the width, from proof_engine.bend's core_n with the facts")
    emit("# above (8 to 32), or core_deg (above 32)")
    emit("def ct.core(+width: Nat, +hw: {Nat.is_lt(width, 8n) == False{} : Bool}, +c: U32, +h: U32, +p: U32) -> " + goal_core("width") + ":")
    ind = 2
    wv = "width"
    for w in range(33):
        emit(" " * ind + f"match {wv}:")
        emit(" " * (ind + 2) + "case 0n:")
        i2 = ind + 4
        if w < 8:
            emit(" " * i2 + f"Empty.absurd({goal_core(f'{w}n')}, PW.cw.tf(hw))")
        else:
            s_, k_ = w - 8, w - 1
            m = (1 << w) - 1
            win = 255 << s_
            emit(" " * i2 + f"PE.ce.core_n({s_}n, {k_}n, {m}, {win}, c, h, p, ct.win{w}(c), ct.high{w}(p, c))")
        nw = f"w{w + 1}"
        emit(" " * (ind + 2) + f"case 1n+{nw}:")
        wv = nw
        ind += 4
    emit(" " * ind + f"PE.ce.core_deg({wv}, c, h, p)")
    emit()



# 64 bits: proof_cases64.bend

OUT64 = os.path.join(HERE, "..", "proof_cases64.bend")


def header64():
    emit("# Generated by gen/proof.py; do not edit by hand.")
    emit("#")
    emit("# Case-split lemmas of crc's 64-bit fast-path proof (see gen/proof.py and")
    emit("# proof_fast64.bend): word64's shifts of a word given by its halves are")
    emit("# the clean shifts of proof_engine64.bend (their OR joins bits that do not")
    emit("# overlap), eight engine steps on a register whose byte to come is clear")
    emit("# only shift it, and the tables as lists. Lemmas are prefixed c6t.")
    emit("import Base")
    emit("import ../word64/word64.bend as W")
    emit("import ./crc.bend as C")
    emit("import ../array/array.bend as A")
    emit("import ./proof_word.bend as PW")
    emit("import ./proof_engine64.bend as P6")
    emit()


def with_bits(name_vars, fixed):
    """the 32 bit terms of a word named by its variables, some fixed"""
    return [tf(fixed[v]) if v in fixed else v for v in name_vars]


def or_lemma(name, desc, lhs, rhs, ctx, orl, orr, split):
    """name(h, l): {lhs(h, l) == rhs(h, l)} for every h, l. lhs reduces to a
    word whose part `ctx` (_ for the OR) holds U32.or(orl, orr); the OR is
    rewritten to P6.c6.uor (which reads its second operand first), and the
    bits `split` (where the second operand's bits come from) are split, in
    a helper of 8 defs of 32 cases when there are more than one."""
    hv, lv = bitvars("h"), bitvars("l")
    allv = hv + lv
    HW = lambda fx: u32(with_bits(hv, fx))
    LW = lambda fx: u32(with_bits(lv, fx))
    stmt_b = lambda fx: eq(ctx(HW(fx), LW(fx)).replace("@H@", f"P6.c6.uor({orl(HW(fx), LW(fx))}, {orr(HW(fx), LW(fx))})"), rhs(HW(fx), LW(fx)), "W.W64")
    emit(f"# {desc}")
    if len(split) == 1:
        emit(f"def {name}(h: U32, l: U32) -> {eq(lhs('h', 'l'), rhs('h', 'l'), 'W.W64')}:")
        emit("  match h l:")
        for b in (True, False):
            fx = {split[0]: b}
            hp = u32(["+" + x if x not in fx else tf(fx[x]) for x in hv])
            lp = u32(["+" + x if x not in fx else tf(fx[x]) for x in lv])
            Hf, Lf = HW(fx), LW(fx)
            emit(f"    case {hp} {lp}:")
            emit(f"      %Equal.sym(U32, U32.or({orl(Hf, Lf)}, {orr(Hf, Lf)}), P6.c6.uor({orl(Hf, Lf)}, {orr(Hf, Lf)}), P6.c6.or_uor({orl(Hf, Lf)}, {orr(Hf, Lf)})) : {eq(ctx(Hf, Lf).replace('@H@', '_'), rhs(Hf, Lf), 'W.W64')}")
            emit("      {==}")
        emit()
        return
    # the helper: every bit a parameter, split on `split`
    top3, low = split[-3:], split[:-3]
    for t in itertools.product((True, False), repeat=3):
        suffix = "".join("1" if x else "0" for x in reversed(t))
        fx = dict(zip(top3, t))
        ps = ", ".join("+" + v + ": Bool" for v in allv if v not in fx)
        emit(f"def {name}.s{suffix}({ps}) -> {stmt_b(fx)}:")
        nested(low, lambda env: "{==}", 2)
        emit()
    emit(f"def {name}.b({', '.join('+' + v + ': Bool' for v in allv)}) -> {stmt_b({})}:")
    emit("  match " + " ".join(top3) + ":")
    for t in itertools.product((True, False), repeat=3):
        suffix = "".join("1" if x else "0" for x in reversed(t))
        fx = dict(zip(top3, t))
        emit("    case " + " ".join(tf(x) for x in t) + ":")
        emit(f"      {name}.s{suffix}(" + ", ".join(v for v in allv if v not in fx) + ")")
    emit()
    H, L = u32(hv), u32(lv)
    emit(f"def {name}(h: U32, l: U32) -> {eq(lhs('h', 'l'), rhs('h', 'l'), 'W.W64')}:")
    emit("  match h l:")
    emit(f"    case {pat('h', plus=True)} {pat('l', plus=True)}:")
    emit(f"      %Equal.sym(U32, U32.or({orl(H, L)}, {orr(H, L)}), P6.c6.uor({orl(H, L)}, {orr(H, L)}), P6.c6.or_uor({orl(H, L)}, {orr(H, L)})) : {eq(ctx(H, L).replace('@H@', '_'), rhs(H, L), 'W.W64')}")
    emit(f"      {name}.b(" + ", ".join(allv) + ")")
    emit()


def gen_64():
    FP = lambda h, l: f"W.W64.from_parts({h}, {l})"
    or_lemma("c6t.shr1_eq", "word64's shift right by one is the clean shift",
             lambda h, l: f"W.W64.shr({FP(h, l)}, 1n)", lambda h, l: f"P6.c6.shr1({FP(h, l)})",
             lambda h, l: FP(f"U32.shrn({h}, 1n)", "@H@"),
             lambda h, l: f"U32.shrn({l}, 1n)", lambda h, l: f"U32.shln({h}, 31n)", ["h0"])
    or_lemma("c6t.shl1_eq", "word64's shift left by one is the clean shift",
             lambda h, l: f"W.W64.shl({FP(h, l)}, 1n)", lambda h, l: f"P6.c6.shl1({FP(h, l)})",
             lambda h, l: FP("@H@", f"U32.shln({l}, 1n)"),
             lambda h, l: f"U32.shln({h}, 1n)", lambda h, l: f"U32.shrn({l}, 31n)", ["l31"])
    or_lemma("c6t.shr8_eq", "word64's shift right by eight is eight clean shifts",
             lambda h, l: f"W.W64.shr({FP(h, l)}, 8n)", lambda h, l: f"P6.c6.shr8({FP(h, l)})",
             lambda h, l: FP(f"U32.shrn({h}, 8n)", "@H@"),
             lambda h, l: f"U32.shrn({l}, 8n)", lambda h, l: f"U32.shln({h}, 24n)", [f"h{i}" for i in range(8)])
    or_lemma("c6t.shl8_eq", "word64's shift left by eight is eight clean shifts",
             lambda h, l: f"W.W64.shl({FP(h, l)}, 8n)", lambda h, l: f"P6.c6.shl8({FP(h, l)})",
             lambda h, l: FP("@H@", f"U32.shln({l}, 8n)"),
             lambda h, l: f"U32.shln({h}, 8n)", lambda h, l: f"U32.shrn({l}, 24n)", [f"l{i}" for i in range(24, 32)])
    emit("# eight reflected steps on a register whose low byte is clear only shift it")
    emit(f"def c6t.r_high(+p: W.W64, h: U32, l: U32) -> {eq(f'P6.c6.rb(8n, p, {FP(chr(104), f'U32.and({NOT255}, l)')})', f'P6.c6.shr8({FP(chr(104), chr(108))})', 'W.W64')}:")
    emit("  match h l:")
    emit(f"    case {pat('h')} {pat('l')}:")
    emit("      {==}")
    emit()
    emit("# eight most-significant-first steps on a register whose top byte is clear")
    emit("# only shift it")
    emit(f"def c6t.n_high(+p: W.W64, h: U32, l: U32) -> {eq(f'P6.c6.nb(8n, p, {FP(f'U32.and(U32.not(4278190080), h)', chr(108))})', f'P6.c6.shl8({FP(chr(104), chr(108))})', 'W.W64')}:")
    emit("  match h l:")
    emit(f"    case {pat('h')} {pat('l')}:")
    emit("      {==}")
    emit()
    emit("# A 64-bit table as a list: entry i is the engine e on the byte i")
    emit()
    emit("def c6t.tab(+e: P6.CrcPfEng64) -> List<&2, W.W64>:")
    emit("  [" + ", ".join(f"P6.c6.ev(e, U32.from_nat({i}n))" for i in range(256)) + "]")
    emit()
    emit(f"def c6t.tab_model(+e: P6.CrcPfEng64) -> {eq('P6.c6.fill_model(256n, List.replicate(W.W64, A.Arrays.slots(8n), W.W64.zero()), e, 0n)', 'c6t.tab(e)', 'List<&2, W.W64>')}:")
    emit("  {==}")
    emit()
    emit("# a table read at a byte is the engine on the byte")
    look("c6t.look", lambda b: f"P6.c6.ev(e, {b})", "c6t.tab(e)", "+e: P6.CrcPfEng64", "e", T="W.W64", fill="W.W64.zero()")


def main():
    header()
    gen_reflected()
    gen_tables()
    gen_msb()
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines).rstrip("\n") + "\n")
    lines.clear()
    header64()
    gen_64()
    with open(OUT64, "w", newline="\n") as f:
        f.write("\n".join(lines).rstrip("\n") + "\n")


main()
