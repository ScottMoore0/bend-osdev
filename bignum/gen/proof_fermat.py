"""Writes bignum/PROOF_fermat.bend: the proof of Fermat's little theorem
(LAWS_fermat.bend).

  python3 gen/proof_fermat.py

Euclid's lemma (pr.eu): for a prime p and 0 < x < p, gcd(p, x) = 1 (a
divisor g of p with 2 <= g <= x < p would leave p mod g = 0), so by
kmath's gcd_mul gcd(y p, y x) = y, and p, dividing y p and y x, divides y.
The binomial coefficients (pr.c, Pascal's rule) have (1 + k) C(1 + n, 1 + k)
= (1 + n) C(n, k) (pr.ab, by induction on n), so a prime p = 1 + n divides
C(p, 1 + j) for j < n (pr.pc). The binomial theorem (pr.bin: (1 + a)^n =
sum over k <= n of C(n, k) a^k, pr.bs, by Pascal's rule, pr.bsp) then gives
(1 + a)^p = 1 + a^p (mod p) (pr.step: the terms 0 < k < p vanish, pr.mid),
and induction on a gives a^p = a (mod p). The ring identities come from
scripts/natproof.py.
"""
