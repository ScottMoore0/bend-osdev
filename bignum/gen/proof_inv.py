"""Writes bignum/PROOF_inv.bend: the proofs of the modular inverse laws
(LAWS_inv.bend).

  python3 gen/proof_inv.py

The extended Euclidean algorithm (bn.inv.go) runs Euclid's loop on (r0, r1)
= (m, a mod m) with coefficients (t0, t1) = (0, 1 mod m), and keeps the
Bezout invariant modulo m: r0 = t0 a and r1 = t1 a (mod m), with t0, t1
below m. A step takes q = r0 / r1 and r = r0 mod r1 (through
BnNat.divmod, LAWS_div's divmod_q and divmod_r) and the new coefficient
t = t0 - q t1 mod m (BnMod.sub and BnMod.mul, LAWS_mod); then r = t a
(mod m): with c = q t1 a, r + c = r + q r1 = r0 = t0 a = (t + q t1) a =
t a + c (mod m), and c cancels modulo m (gi.mcan: add m - (c mod m) to
both sides). The loop also keeps kmath's gcd of (r0, r1) (PROOF_gcd's
gc.ks), which at the end, r1 = 0, is r0; so it answers Some{t0} exactly
when gcd(m, a mod m) = gcd(a, m) is 1, and then a t0 = r0 = 1 (mod m).
The fuel is PROOF_gcd's measure (gc.meas, gc.fs, gc.ini). The ring
identities come from scripts/natproof.py.
"""
