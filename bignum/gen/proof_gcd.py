def fuel():
    X, Y, Z = BL("a"), BL("b"), BL("r")
    A, B, R = VAL("a"), VAL("b"), VAL("r")
    XY, YZ = f"Nat.add({X}, {Y})", f"Nat.add({Y}, {Z})"
    M = f"Nat.add({XY}, U.U32Nat.bit(Nat.is_lt({A}, {B})))"
    put("# Euclid's measure: the bit lengths, and 1 while a < b (0 once b is 0)\n")
    put(f"""def gc.meas(z: Bool, +a: N.BnNat, +b: N.BnNat) -> Nat:
  match z:
    case True{{}}:
      0n
    case False{{}}:
      {M}

def gc.mpos(+a: N.BnNat, +b: N.BnNat, +hb: {VT('b')}, +hB: {LT('0n', B)}) -> {LT('0n', M)}:
  PL.bq.ltle(0n, {Y}, {M}, gc.bl1(b, hb, hB), PL.bq.le_trans({Y}, {XY}, {M}, UL.nat_le_add({Y}, {X}), gc.lep({XY}, U.U32Nat.bit(Nat.is_lt({A}, {B})))))
""")
    BR = f"U.U32Nat.bit(Nat.is_lt({B}, {R}))"
    eb = CG("Bool", "Nat", "U.U32Nat.bit(zz)", f"Nat.is_lt({B}, {R})", "False{}", f"gc.asym({R}, {B}, hrl)")
    fin = TR("Bool", f"Nat.is_lt(Nat.add({YZ}, {BR}), p)", f"Nat.is_lt({YZ}, p)", "True{}",
             CG("Nat", "Bool", "Nat.is_lt(zz, p)", f"Nat.add({YZ}, {BR})", YZ,
                TR("Nat", f"Nat.add({YZ}, {BR})", f"Nat.add({YZ}, 0n)", YZ, CG("Nat", "Nat", f"Nat.add({YZ}, zz)", BR, "0n", eb), f"UL.nat_add_zero({YZ})")),
             "core")
    comm = CG("Nat", "Bool", "Nat.is_lt(%s, zz)" % YZ, XY, f"Nat.add({Y}, {X})", f"UL.nat_add_comm({X}, {Y})")
    commle = CG("Nat", "Bool", "Nat.is_le(%s, zz)" % YZ, XY, f"Nat.add({Y}, {X})", f"UL.nat_add_comm({X}, {Y})")
    put(f"""# one step from (a, b) to (b, r), r = a mod b > 0, lowers the measure
def gc.fs2(c: Bool, +a: N.BnNat, +b: N.BnNat, +r: N.BnNat, +p: Nat, ec: {EQ(f'Nat.is_lt({A}, {B})', 'c', 'Bool')}, +ha: {VT('a')}, +hb: {VT('b')}, +hr: {VT('r')}, +hB: {LT('0n', B)}, +hrl: {LT(R, B)}, +er: {EQ(R, f'Nat.mod({A}, {B})')}, +hR: {LT('0n', R)}, hf: {LT(f'Nat.add({XY}, U.U32Nat.bit(c))', '1n+p')}) -> {LT(f'Nat.add({YZ}, {BR})', 'p')}:
  match c:
    case False{{}}:
      +t2 = Equal.trans(Bool, Nat.is_lt(Nat.double({R}), {A}), Nat.is_lt(Nat.double(Nat.mod({A}, {B})), {A}), True{{}}, Equal.cong(Nat, Bool, zz => Nat.is_lt(Nat.double(zz), {A}), {R}, Nat.mod({A}, {B}), er), gc.two({A}, {B}, hB, PL.bq.nlt_le({A}, {B}, ec)))
      +hz = gc.bl(r, {X}, hr, hR, PL.bq.lt_trans(Nat.double({R}), {A}, {D1(X)}, t2, gc.fa(a, ha)))
      +g2 = Equal.trans(Bool, Nat.is_lt({YZ}, {XY}), Nat.is_lt({YZ}, Nat.add({Y}, {X})), True{{}}, {comm}, Equal.trans(Bool, Nat.is_lt({YZ}, Nat.add({Y}, {X})), Nat.is_lt({Z}, {X}), True{{}}, gc.ltl({Y}, {Z}, {X}), hz))
      +g3 = Equal.trans(Bool, Nat.is_le({XY}, p), Nat.is_le(Nat.add({XY}, 0n), p), True{{}}, Equal.cong(Nat, Bool, zz => Nat.is_le(zz, p), {XY}, Nat.add({XY}, 0n), Equal.sym(Nat, Nat.add({XY}, 0n), {XY}, UL.nat_add_zero({XY}))), gc.lts(Nat.add({XY}, 0n), p, hf))
      +core = PL.bq.ltle({YZ}, {XY}, p, g2, g3)
      {fin}
    case True{{}}:
      +eRA = Equal.trans(Nat, {R}, Nat.mod({A}, {B}), {A}, er, PX.bx.msm({A}, {B}, ec))
      +hz = gc.ble(r, {X}, hr, hR, Equal.trans(Bool, Nat.is_lt({R}, {D1(X)}), Nat.is_lt({A}, {D1(X)}), True{{}}, Equal.cong(Nat, Bool, zz => Nat.is_lt(zz, {D1(X)}), {R}, {A}, eRA), gc.fa(a, ha)))
      +g2 = Equal.trans(Bool, Nat.is_le({YZ}, {XY}), Nat.is_le({YZ}, Nat.add({Y}, {X})), True{{}}, {commle}, Equal.trans(Bool, Nat.is_le({YZ}, Nat.add({Y}, {X})), Nat.is_le({Z}, {X}), True{{}}, gc.lel({Y}, {Z}, {X}), hz))
      +g3 = PL.bq.ltle({XY}, Nat.add({XY}, 1n), p, gc.ls1({XY}), gc.lts(Nat.add({XY}, 1n), p, hf))
      +core = PL.bq.lelt({YZ}, {XY}, p, g2, g3)
      {fin}

def gc.fs(z2: Bool, +a: N.BnNat, +b: N.BnNat, +r: N.BnNat, +p: Nat, ez2: {EQ('N.BnNat.is_zero(r)', 'z2', 'Bool')}, +ha: {VT('a')}, +hb: {VT('b')}, +hr: {VT('r')}, +hB: {LT('0n', B)}, +hrl: {LT(R, B)}, +er: {EQ(R, f'Nat.mod({A}, {B})')}, hf: {LT('gc.meas(False{}, a, b)', '1n+p')}) -> {LT('gc.meas(z2, b, r)', 'p')}:
  match z2:
    case True{{}}:
      PL.bq.ltle(0n, {M}, p, gc.mpos(a, b, hb, hB), gc.lts({M}, p, hf))
    case False{{}}:
      gc.fs2(Nat.is_lt({A}, {B}), a, b, r, p, {{==}}, ha, hb, hr, hB, hrl, er, gc.vnz(r, ez2), hf)
""")
    # the fuel at the start: meas <= X + Y + 1 <= T + 1 < 2 T + 4
    W = "Nat.add(Nat.mul(2n, T), 4n)"
    eW = NP.ring("Nat.add(Nat.add(T, 2n), 1n+Nat.add(T, 1n))", W)
    m3 = lt_from("Nat.add(T, 1n)", W, "Nat.add(T, 2n)", eW)
    put(f"""# the fuel 2 T + 4 of a pair whose bit lengths add up to at most T suffices
def gc.ini(z: Bool, +a: N.BnNat, +b: N.BnNat, +T: Nat, hT: {LE(XY, 'T')}) -> {LT('gc.meas(z, a, b)', W)}:
  match z:
    case True{{}}:
      Equal.trans(Bool, Nat.is_lt(0n, {W}), Nat.is_lt(0n, 1n+Nat.add(Nat.mul(2n, T), 3n)), True{{}}, Equal.cong(Nat, Bool, zz => Nat.is_lt(0n, zz), {W}, 1n+Nat.add(Nat.mul(2n, T), 3n), UL.nat_add_succ(Nat.mul(2n, T), 3n)), {{==}})
    case False{{}}:
      +m1 = Equal.trans(Bool, Nat.is_le({M}, Nat.add({XY}, 1n)), Nat.is_le(U.U32Nat.bit(Nat.is_lt({A}, {B})), 1n), True{{}}, gc.lel({XY}, U.U32Nat.bit(Nat.is_lt({A}, {B})), 1n), gc.b1(Nat.is_lt({A}, {B})))
      +m2 = Equal.trans(Bool, Nat.is_le(Nat.add({XY}, 1n), Nat.add(T, 1n)), Nat.is_le({XY}, T), True{{}}, gc.ler({XY}, T, 1n), hT)
      PL.bq.lelt({M}, Nat.add(T, 1n), {W}, PL.bq.le_trans({M}, Nat.add({XY}, 1n), Nat.add(T, 1n), m1, m2), {m3})
""")


def loop():
    A, B = VAL("a"), VAL("b")
    r = "N.BnNat.mod(a, b)"
    G = "Md.bn.gcd.go"
    put("# Euclid's loop: its result is kmath's gcd of the values, and valid\n")
    put(f"""def gc.go(f: Nat, z: Bool, +a: N.BnNat, +b: N.BnNat, ez: {EQ('N.BnNat.is_zero(b)', 'z', 'Bool')}, +ha: {VT('a')}, +hb: {VT('b')}, hf: {LT('gc.meas(z, a, b)', 'f')}) -> {EQ(VAL(f'{G}(f, z, a, b)'), f'K.KMath.gcd({A}, {B})')}:
  match f:
    case 0n:
      Empty.absurd({EQ(VAL(f'{G}(0n, z, a, b)'), f'K.KMath.gcd({A}, {B})')}, gc.lt0(gc.meas(z, a, b), hf))
    case 1n+ +p:
      match z:
        case True{{}}:
          Equal.sym(Nat, K.KMath.gcd({A}, {B}), {A}, Equal.trans(Nat, K.KMath.gcd({A}, {B}), K.KMath.gcd({A}, 0n), {A}, Equal.cong(Nat, Nat, zz => K.KMath.gcd({A}, zz), {B}, 0n, gc.vz(b, ez)), KL.gcd_zero_r({A})))
        case False{{}}:
          +hB = gc.vnz(b, ez)
          +hr = LD.mod_valid(a, b, ha)
          +er = LD.mod_value(a, b, ha, hb)
          +ih = gc.go(p, N.BnNat.is_zero({r}), b, {r}, {{==}}, hb, hr, gc.fs(N.BnNat.is_zero({r}), a, b, {r}, p, {{==}}, ha, hb, hr, hB, LD.mod_lt(a, b, ha, hb, hB), er, hf))
          Equal.trans(Nat, {VAL(f'{G}(p, N.BnNat.is_zero({r}), b, {r})')}, K.KMath.gcd({B}, {VAL(r)}), K.KMath.gcd({A}, {B}), ih, Equal.trans(Nat, K.KMath.gcd({B}, {VAL(r)}), K.KMath.gcd({B}, Nat.mod({A}, {B})), K.KMath.gcd({A}, {B}), Equal.cong(Nat, Nat, zz => K.KMath.gcd({B}, zz), {VAL(r)}, Nat.mod({A}, {B}), er), gc.ks({A}, {B}, hB)))

def gc.vk(f: Nat, z: Bool, +a: N.BnNat, +b: N.BnNat, +ha: {VT('a')}, +hb: {VT('b')}) -> {VT(f'{G}(f, z, a, b)')}:
  match f:
    case 0n:
      ha
    case 1n+p:
      match z:
        case True{{}}:
          ha
        case False{{}}:
          gc.vk(p, N.BnNat.is_zero({r}), b, {r}, hb, LD.mod_valid(a, b, ha))

def gc.top(+a: N.BnNat, +b: N.BnNat, +ha: {VT('a')}, +hb: {VT('b')}) -> {EQ(VAL('Md.BnMod.gcd(a, b)'), f'K.KMath.gcd({A}, {B})')}:
  gc.go(Md.bn.euclid.fuel(a, b), N.BnNat.is_zero(b), a, b, {{==}}, ha, hb, gc.ini(N.BnNat.is_zero(b), a, b, Nat.add({BL('a')}, {BL('b')}), UL.nat_le_refl(Nat.add({BL('a')}, {BL('b')}))))

def gc.gv(+a: N.BnNat, +b: N.BnNat, +ha: {VT('a')}, +hb: {VT('b')}) -> {VT('Md.BnMod.gcd(a, b)')}:
  gc.vk(Md.bn.euclid.fuel(a, b), N.BnNat.is_zero(b), a, b, ha, hb)

# lcm(a, b) = (a / gcd(a, b)) b
def gc.lv(+a: N.BnNat, +b: N.BnNat, +ha: {VT('a')}, +hb: {VT('b')}) -> {EQ(VAL('Md.BnMod.lcm(a, b)'), f'K.KMath.lcm({A}, {B})')}:
  Equal.trans(Nat, {VAL('N.BnNat.mul(N.BnNat.div(a, Md.BnMod.gcd(a, b)), b)')}, Nat.mul({VAL('N.BnNat.div(a, Md.BnMod.gcd(a, b))')}, {B}), Nat.mul(Nat.div({A}, K.KMath.gcd({A}, {B})), {B}), LM.mul_value(N.BnNat.div(a, Md.BnMod.gcd(a, b)), b, LD.div_valid(a, Md.BnMod.gcd(a, b)), hb), Equal.cong(Nat, Nat, zz => Nat.mul(zz, {B}), {VAL('N.BnNat.div(a, Md.BnMod.gcd(a, b))')}, Nat.div({A}, K.KMath.gcd({A}, {B})), Equal.trans(Nat, {VAL('N.BnNat.div(a, Md.BnMod.gcd(a, b))')}, Nat.div({A}, {VAL('Md.BnMod.gcd(a, b)')}), Nat.div({A}, K.KMath.gcd({A}, {B})), LD.div_value(a, Md.BnMod.gcd(a, b), ha, gc.gv(a, b, ha, hb)), Equal.cong(Nat, Nat, zz => Nat.div({A}, zz), {VAL('Md.BnMod.gcd(a, b)')}, K.KMath.gcd({A}, {B}), gc.top(a, b, ha, hb)))))
""")


