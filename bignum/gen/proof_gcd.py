#!/usr/bin/env python3
"""Writes bignum/PROOF_gcd.bend: the proofs of the gcd and lcm laws
(LAWS_gcd.bend).

  python3 gen/proof_gcd.py

Euclid's loop (bn.gcd.go) keeps kmath's KMath.gcd of the values: one step
takes (a, b) to (b, a mod b), and gcd(b, a mod b) = gcd(a, b) (gc.ks: each
divides the other, by kmath's gcd_divides_l, gcd_divides_r and
gcd_greatest, since a common divisor of a and b divides a mod b (gc.dm, by
gc.dc: d | x + y and d | y give d | x) and one of b and a mod b divides
a = q b + r (gc.da); and two numbers dividing each other are equal,
gc.anti). With b = 0 the loop gives a = gcd(a, 0).

The fuel suffices: with X and Y the bit lengths of a and b, the measure
X + Y + [a < b] (gc.meas; 0 once b is 0) is below the fuel at the start
(2 (X + Y) + 4) and falls with every step: for b <= a the remainder r has
2 r < a < 2^X (gc.two), so its bit length is below X; for a < b, r = a,
and the bit length of r is at most X (gc.ble). The bounds of the bit length
are PROOF_div's (bd.fa: x < 2^bits, bd.fb: 2^bits <= 2 x for x > 0).

lcm(a, b) = (a / gcd(a, b)) b is then kmath's KMath.lcm of the values, and
its laws are kmath's. The lemmas gc.* are shared with PROOF_inv.bend. The
ring identities come from scripts/natproof.py.
"""
