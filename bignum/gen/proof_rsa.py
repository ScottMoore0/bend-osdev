def EQ(a, b, ty="Nat"):
    return "{" + f"{a} == {b} : {ty}" + "}"


def LT(x, y):
    return btrue(f"Nat.is_lt({x}, {y})")


def LE(x, y):
    return btrue(f"Nat.is_le({x}, {y})")


def DV(d, x):
    return f"Sigma<&1, &1, Nat, kk => {{Nat.mul(kk, {d}) == {x} : Nat}}>"


def PR(p):
    return btrue(f"LF.bnlaw.prime({p})")


def MOD(a, b):
    return f"Nat.mod({a}, {b})"


def POW(a, b):
    return f"Nat.pow({a}, {b})"


def MUL(a, b):
    return f"Nat.mul({a}, {b})"


def ADD(a, b):
    return f"Nat.add({a}, {b})"


def H(text, lhs, rhs):
    return hyp(text, lhs, rhs)


def P0(p):
    """0 < p from a prime p (rx.p0)."""
    return f"rx.p0({p}, h{p})"


