"""Writes bignum/PROOF_rsa.bend: the proofs of the RSA laws on Nat
(LAWS_rsa.bend).

  python3 gen/proof_rsa.py

Fermat generalised (rx.fg): for a prime p = 1 + n, a^(1 + (k + 1) n) =
a^n a^(1 + k n), and by induction a^(1 + k n) = a mod p, so this is a^n a =
a^p = a (PROOF_fermat.bend's pr.fl); then a^(x + 1 + k n) = a^(1 + x)
(rx.fx), so an exponent D with D mod n > 0 may be reduced modulo n (rx.red).
The CRT's uniqueness (rx.crt): with x <= y and w = y - x, w + x = x mod p
gives p | w (rx.dvd: w + x mod p = x mod p, so w + (x mod p) = Q p + (x mod
p) with Q = (w + x mod p) / p, and w = Q p); likewise q | w, and for p < q,
q divides w = k1 p, so by Euclid's lemma (PROOF_fermat.bend's pr.eu) q | k1
and p q | w (rx.pqa). RSA (rx.rsa): d e = 1 mod p - 1 gives d e = 1 + k (p
- 1) (for p > 2, as 1 mod (p - 1) = 1; for p = 2 since d e > 0, which holds
as p and q are not both 2), so m^(d e) = m mod p and mod q, and so mod p q.
The CRT exponentiation (rx.cx): p q odd makes p, q > 2, so dP = d mod (p -
1) > 0 (dP = 0 would give d e = 0 mod p - 1, against 1), m1 = c^d mod p and
m2 = c^d mod q; m2 + q h = m2 mod q, and mod p it is m2 + (m1 - m2) (q qInv)
= m1 (bx.sbn); it is below p q (m2 < q, h < p), so it is c^d mod p q by the
uniqueness. A congruence modulo L = u c is one modulo c (rx.cdiv: x mod c =
(x mod L) mod c for L > 0, and L = 0 makes x = y). BnNat.is_odd is bit 0 of
the low limb, U32.and(1, x) the parity of its value (PROOF_mod.bend's bx.b1,
bx.hdl, bx.hl), and the parity is x mod 2 (u32's nat_odd_half). The ring
identities come from scripts/natproof.py.
"""
