#!/usr/bin/env python3
"""The instances of crypto's signature and key-agreement interfaces, and
their laws.

  python3 gen/instances.py           rewrite the generated regions
  python3 gen/instances.py --check   only check that they are up to date

Each region lies between "# BEGIN GENERATED by gen/instances.py: <name>" and
"# END GENERATED: <name>":
  * "laws" in LAWS.bend: one law per instance and law schema;
  * "proofs" in PROOF.bend: their proofs.
Everything outside the regions is written by hand.

Why per instance: crypto's interface laws (crypto/LAWS.bend's
sign_verify_bytes_if and kex_agree_if) are stated over template arguments;
here each is written out for an instance's defs, with its proof filled in
(the proofs are short rewrites, so they are written out rather than
imported: crypto's PROOF.bend takes 2 GB of the checker's memory, and the
algorithm packages' PROOF.bend files hold their exhaustive cases). Where an
algorithm's package proves that a public key read from bytes is read again
from the bytes written for it, the instance's pk_format law is stated with
that package's law, at the bytes used, as a hypothesis (hr), and proved
from the generic law lift_pk_format (LAWS.bend, by hand).

Adding an instance: a row in SIGN or KEX (its defs, as template arguments,
with its template parameters), and, if its package proves a public-key
format, a row in FMT (the raw reader, writer and error mapping); then run
this script.
"""
import os, sys, textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")

# ---------------------------------------------------------------- instances

# Each row's laws are stated for every value of its parameters (tp: the
# template parameters, a curve, group, hash, MAC, salt length...), so the
# named instances (P-256 with SHA-256, SM2 with SM3, ...) are special cases,
# and the checker never computes with a concrete curve or group.
PRM = "~prm: EE.EcParams"
DIG = "~digest: B.Octets -> B.Octets"
MAC = "~mac: B.Octets -> B.Octets -> B.Octets"

# ECDH's public-key bytes (SEC 1's uncompressed form): ecc's
# EcCurve.point_of and point_to, whose round trip is ecc's point_round_trip
EC_FMT = dict(name="ecdh", title="ECDH's public keys (ECDSA, SM2, ECDH), for every curve", tp=[PRM],
              E="EE.EcError", err="PE.PkEcc.err", raw_of="PE.PkEcdh.point_of(~prm)", raw_to="PE.PkEcdh.pk_to(~prm)",
              PK="EE.EcPoint", pk_of="PE.PkEcdh.pk_of(~prm)", pk_to="PE.PkEcdh.pk_to(~prm)",
              law="ecc's point_round_trip (ecc/LAWS.bend)")
DH_FMT = dict(name="dh", title="DH's public keys, for every group", tp=["~grp: DD.DhGroup"],
              E="DD.DhError", err="PD.PkDh.err", raw_of="PD.PkDh.public_of(~grp)", raw_to="PD.PkDh.pk_to(~grp)",
              PK="NB.BnNat", pk_of="PD.PkDh.pk_of(~grp)", pk_to="PD.PkDh.pk_to(~grp)",
              law="dh's public_round_trip (dh/LAWS.bend)")
FMT = [EC_FMT, DH_FMT]

# signature schemes: SK and PK the key types, public the public key of a
# secret key, pk_of and pk_to the public key's bytes, sign and verify
SIGN = [
    dict(name="rsa_pkcs1", title="RSASSA-PKCS1-v1_5, for every hash and DigestInfo prefix",
         tp=[DIG, "~prefix: B.Octets"], SK="RR.RsaPrivate", PK="RR.RsaPublic",
         public="RR.Rsa.public", pk_of="PR.PkRsa.pk_of", pk_to="RK.RsaKeys.public_to",
         sign="PR.PkRsa.pkcs1_sign(~digest, ~prefix)", verify="PR.PkRsa.pkcs1_verify(~digest, ~prefix)"),
    dict(name="rsa_pss", title="RSASSA-PSS, for every hash (MGF1 over it) and salt length",
         tp=[DIG, "~slen: Nat"], SK="RR.RsaPrivate", PK="RR.RsaPublic",
         public="RR.Rsa.public", pk_of="PR.PkRsa.pk_of", pk_to="RK.RsaKeys.public_to",
         sign="PR.PkRsa.pss_sign(~digest, ~slen)", verify="PR.PkRsa.pss_verify(~digest, ~slen)"),
    dict(name="ecdsa", title="ECDSA, for every curve, hash and MAC (RFC 6979's k)", tp=[PRM, DIG, MAC],
         SK="NB.BnNat", PK="EE.EcPoint", public="PE.PkEcdh.public(~prm)", pk_of="PE.PkEcdh.pk_of(~prm)",
         pk_to="PE.PkEcdh.pk_to(~prm)", sign="PE.PkEcdsa.sign(~prm, ~digest, ~mac)", verify="PE.PkEcdsa.verify(~prm, ~digest)"),
    dict(name="sm2", title="SM2, for every curve, hash, MAC (RFC 6979's k) and identity",
         tp=[PRM, DIG, MAC, "~id: B.Octets"], SK="NB.BnNat", PK="EE.EcPoint", public="PE.PkEcdh.public(~prm)",
         pk_of="PE.PkEcdh.pk_of(~prm)", pk_to="PE.PkEcdh.pk_to(~prm)",
         sign="PS.PkSm2.sign(~prm, ~digest, ~mac, ~id)", verify="PS.PkSm2.verify(~prm, ~digest, ~id)"),
    dict(name="ecrdsa", title="GOST R 34.10-2012, for every curve, hash and MAC (RFC 6979's k)", tp=[PRM, DIG, MAC],
         SK="NB.BnNat", PK="EE.EcPoint", public="PE.PkEcdh.public(~prm)", pk_of="PG.PkEcrdsa.pk_of(~prm)",
         pk_to="PG.PkEcrdsa.pk_to(~prm)", sign="PG.PkEcrdsa.sign(~prm, ~digest, ~mac)", verify="PG.PkEcrdsa.verify(~prm, ~digest)"),
]

# key agreements: secret the secret key from its bytes, shared the shared
# secret of a secret key and the peer's public key
KEX = [
    dict(name="dh", title="finite-field Diffie-Hellman, for every group", tp=["~grp: DD.DhGroup"], SK="NB.BnNat",
         PK="NB.BnNat", secret="PD.PkDh.secret(~grp)", public="PD.PkDh.public(~grp)", pk_of="PD.PkDh.pk_of(~grp)",
         pk_to="PD.PkDh.pk_to(~grp)", shared="PD.PkDh.shared(~grp)"),
    dict(name="ecdh", title="ECDH, for every curve", tp=[PRM], SK="NB.BnNat", PK="EE.EcPoint",
         secret="PE.PkEcdh.secret(~prm)", public="PE.PkEcdh.public(~prm)", pk_of="PE.PkEcdh.pk_of(~prm)",
         pk_to="PE.PkEcdh.pk_to(~prm)", shared="PE.PkEcdh.shared(~prm)"),
]

# ---------------------------------------------------------------- schemas

LAWS, PROOFS = [], []


def law(name, comment, params, stmt):
    head = "".join("  for %s\n" % p for p in params)
    com = "".join("# %s\n" % l for l in textwrap.wrap(comment, 76))
    LAWS.append("%slaw %s:\n%s  %s\n" % (com, name, head, stmt))


def proof(text):
    PROOFS.append(text)


def call(fn, *args):
    """a def given with its template arguments, called on args"""
    if fn.endswith(")"):
        return fn[:-1] + "".join(", " + a for a in args) + ")" if args else fn
    return "%s(%s)" % (fn, ", ".join(args)) if args else fn


def res(E, A):
    return "Result<&2, &2, %s, %s>" % (E, A)


def tnames(c):
    return "".join(t.split(":")[0].strip("~ ") + ", " for t in c["tp"])


def fmt_law(f):
    """pk_format: a public key read from bytes o is read again from the
    bytes written for it, given the package's round trip at o (hr)"""
    c = f
    n, PK = c["name"], c["PK"]
    R, RE = res("Cr.CrError", PK), res(f["E"], PK)
    law("%s_pk_format_if" % n,
        "%s: a public key read from bytes o is read again from the bytes written for it, given %s at o (hr)" % (c["title"], f["law"]),
        c["tp"] + ["+o: B.Octets", "+p: %s" % PK, "h: {%s == Done{p} : %s}" % (call(c["pk_of"], "o"), R),
         "hr: {Result.bind(&2, &2, %s, %s, %s, %s, q => %s) == %s : %s}"
         % (f["E"], PK, PK, call(f["raw_of"], "o"), call(f["raw_of"], call(f["raw_to"], "q")), call(f["raw_of"], "o"), RE)],
        "{%s == Done{p} : %s}" % (call(c["pk_of"], call(c["pk_to"], "p")), R))
    proof("def Laws.%s_pk_format_if(%so, p, h, hr):\n  Laws.lift_pk_format(~%s, ~%s, ~%s, x => %s, q => %s, %s, p, h, hr)\n"
          % (n, tnames(c), f["E"], PK, f["err"], call(f["raw_of"], "x"), call(f["raw_to"], "q"), call(f["raw_of"], "o")))


def sign_laws(c):
    n, SK, PK = c["name"], c["SK"], c["PK"]
    R = res("Cr.CrError", PK)
    pub = call(c["public"], "sk")
    sig = call(c["sign"], "sk", "m")
    law("%s_verify_bytes_if" % n,
        "%s (crypto's sign_verify_bytes_if): a signature checked from the public key's bytes is accepted, for every key and message, when the public key survives its bytes (hf) and the scheme accepts the signature (ha)" % c["title"],
        c["tp"] + ["+sk: %s" % SK, "+m: B.Octets", "hf: {%s == Done{%s} : %s}" % (call(c["pk_of"], call(c["pk_to"], pub)), pub, R),
         "ha: {%s == True{} : Bool}" % call(c["verify"], pub, "m", sig)],
        "{Sg.CrSign.verify_bytes(~%s, ~%s, ~%s, %s, m, %s) == True{} : Bool}" % (PK, c["pk_of"], c["verify"], call(c["pk_to"], pub), sig))
    proof("def Laws.%s_verify_bytes_if(%ssk, m, hf, ha):\n"
          "  %%Equal.sym(%s, %s, Done{%s}, hf) : {Sg.cr.sign.check(~%s, ~%s, _, m, %s) == True{} : Bool}\n"
          "  ha\n" % (n, tnames(c), R, call(c["pk_of"], call(c["pk_to"], pub)), pub, PK, c["verify"], sig))


def kex_laws(c):
    n, SK, PK = c["name"], c["SK"], c["PK"]
    RS, RP, RO = res("Cr.CrError", SK), res("Cr.CrError", PK), res("Cr.CrError", "B.Octets")
    px, py = call(c["public"], "x"), call(c["public"], "y")
    fx, fy = call(c["pk_of"], call(c["pk_to"], px)), call(c["pk_of"], call(c["pk_to"], py))

    def agree(k, peer):
        return "Kx.CrKex.agree(~%s, ~%s, ~%s, ~%s, ~%s, %s, %s)" % (SK, PK, c["secret"], c["pk_of"], c["shared"], k, peer)

    def with_(sk, pk):
        return "Kx.cr.kex.with(~%s, ~%s, ~%s, %s, %s)" % (SK, PK, c["shared"], sk, pk)

    lhs, rhs = agree("a", call(c["pk_to"], py)), agree("b", call(c["pk_to"], px))
    law("%s_agree_if" % n,
        "%s (crypto's kex_agree_if): two parties agree from each other's public-key bytes, for every pair of keys, when the keys parse (hx, hy), the public keys survive their bytes (hfx, hfy) and the shared secrets agree (h)" % c["title"],
        c["tp"] + ["+a: B.Octets", "+b: B.Octets", "+x: %s" % SK, "+y: %s" % SK,
         "hx: {%s == Done{x} : %s}" % (call(c["secret"], "a"), RS), "hy: {%s == Done{y} : %s}" % (call(c["secret"], "b"), RS),
         "hfx: {%s == Done{%s} : %s}" % (fx, px, RP), "hfy: {%s == Done{%s} : %s}" % (fy, py, RP),
         "h: {%s == %s : %s}" % (call(c["shared"], "x", py), call(c["shared"], "y", px), RO)],
        "{%s == %s : %s}" % (lhs, rhs, RO))
    sx = call(c["shared"], "x", py)
    proof("def Laws.%s_agree_if(%sa, b, x, y, hx, hy, hfx, hfy, h):\n" % (n, tnames(c))
          + "  %%Equal.sym(%s, %s, Done{x}, hx) : {%s == %s : %s}\n" % (RS, call(c["secret"], "a"), with_("_", fy), rhs, RO)
          + "  %%Equal.sym(%s, %s, Done{%s}, hfy) : {%s == %s : %s}\n" % (RP, fy, py, with_("Done{x}", "_"), rhs, RO)
          + "  %%Equal.sym(%s, %s, Done{y}, hy) : {%s == %s : %s}\n" % (RS, call(c["secret"], "b"), sx, with_("_", fx), RO)
          + "  %%Equal.sym(%s, %s, Done{%s}, hfx) : {%s == %s : %s}\n" % (RP, fx, px, sx, with_("Done{y}", "_"), RO)
          + "  h\n")


for c in SIGN:
    sign_laws(c)
for c in KEX:
    kex_laws(c)
for f in FMT:
    fmt_law(f)

# ---------------------------------------------------------------- regions

REGIONS = [("LAWS.bend", "laws", lambda: "\n".join(LAWS)), ("PROOF.bend", "proofs", lambda: "\n".join(PROOFS))]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fname, name, body in REGIONS:
        path = os.path.join(PKG, fname)
        with open(path) as f:
            text = f.read()
        begin = "# BEGIN GENERATED by gen/instances.py: %s\n" % name
        end = "# END GENERATED: %s\n" % name
        i, j = text.index(begin) + len(begin), text.index(end)
        new = text[:i] + body() + text[j:]
        if new != text:
            stale.append("%s (%s)" % (fname, name))
            if not check:
                with open(path, "w", newline="\n") as f:
                    f.write(new)
    if check:
        if stale:
            print("out of date (run gen/instances.py): " + ", ".join(stale))
            sys.exit(1)
        print("generated regions up to date")


if __name__ == "__main__":
    main()
