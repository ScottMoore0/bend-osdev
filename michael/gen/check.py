#!/usr/bin/env python3
"""Writes michael/check.bend: Michael on the specification's vectors, whole and in
three pieces, through the public interface, with the expected output (the
specification's values, from ref/model.py's tables) as the file's #|
lines.

  python3 gen/check.py           rewrite check.bend
  python3 gen/check.py --check   only check that it is up to date

Beside the laws' vectors, check.bend runs the vectors in pieces and the
block function 1000 times (Table J-1's last row).
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.join(PKG, "ref"))
import model  # noqa: E402


def octets(bs):
    s = bs.decode("latin-1")
    if all(32 <= ord(c) < 127 and c not in '"\\' for c in s):
        return 'B.Octets.of_string("%s")' % s
    return "B.Octets.of_list([%s])" % ", ".join(str(b) for b in bs)

HEADER = '''# Generated by gen/check.py; do not edit by hand.
#
# Michael on the six vectors of IEEE Std 802.11-2024's Table J-2 (each key
# the previous tag), whole and in three pieces, its block function 1000
# times (Table J-1), and IEEE 802.11-2012 M.6.3's TKIP frame (as hostap's
# wlantest/test_vectors.c gives it), with a short key refused. The values
# are the specifications' (the #| lines).
import Base
import ../bytes/bytes.bend as B
import ../md-engine/md-engine.bend as Hs
import ./michael.bend as MI

# a byte string in three pieces: [0, n/3), [n/3, 2n/3), [2n/3, n)
def third(+o: B.Octets) -> Nat:
  Nat.div(B.Octets.len(o), 3n)

def p1(+o: B.Octets) -> B.Octets:
  B.Octets.take(third(o), o)

def p2(+o: B.Octets) -> B.Octets:
  B.Octets.take(third(o), B.Octets.drop(third(o), o))

def p3(+o: B.Octets) -> B.Octets:
  B.Octets.drop(Nat.mul(2n, third(o)), o)

def mic.of(r: Result<&2, &2, Hs.HsError, Hs.HsW2>, +m: B.Octets) -> String:
  match r:
    case Done{+k}:
      B.Octets.hex(MI.HsMichael.mic(k, m)) ++ " " ++ B.Octets.hex(MI.HsMichael.final(MI.HsMichael.update(MI.HsMichael.update(MI.HsMichael.update(MI.HsMichael.init(k), p1(m)), p2(m)), p3(m))))
    case Fail{e}:
      match e:
        case Hs.HsBadKeyLength{n}:
          "bad key length " ++ U32.show(U32.from_nat(n))

def mic(k: B.Octets, m: B.Octets) -> String:
  mic.of(MI.HsMichael.key(k), m)

# Michael's block function applied n times
def michael.iter(n: Nat, lr: Hs.HsW2) -> Hs.HsW2:
  match n:
    case 0n:
      lr
    case 1n+p:
      michael.iter(p, MI.hs.michael.b(lr))

def michael.pair(lr: Hs.HsW2) -> String:
  match lr:
    case Hs.HsW2{l, r}:
      U32.show(l) ++ " " ++ U32.show(r)
'''


def body():
    lines, want = [], []
    for k, m, v in model.MICHAEL_V:
        lines.append('    IO.print("michael %s " ++ mic(%s, %s))' % (k, octets(bytes.fromhex(k)), octets(m)))
        want.append("michael %s %s %s" % (k, v, v))
    for (l, r), n, (l2, r2) in [b for b in model.MICHAEL_B if b[1] > 1]:
        lines.append('    IO.print("michael b %d times on (%d, %d): " ++ michael.pair(michael.iter(%dn, Hs.HsW2{%d, %d})))' % (n, l, r, n, l, r))
        want.append("michael b %d times on (%d, %d): %d %d" % (n, l, r, l2, r2))
    lines.append('    IO.print("michael tkip m.6.3 " ++ mic(%s, %s))' % (octets(model.TKIP_M63_KEY), octets(model.TKIP_M63_INPUT)))
    want.append("michael tkip m.6.3 %s %s" % (model.TKIP_M63_MIC, model.TKIP_M63_MIC))
    lines.append('    IO.print("michael short key: " ++ mic(B.Octets.zeros(7n), B.Octets.empty()))')
    want.append("michael short key: bad key length 7")
    return (HEADER + "\ndef main() -> IO(Unit):\n  do IO<Unit>:\n" + "\n".join(lines) + "\n\n"
            + "".join("#|%s\n" % w for w in want))


def main():
    path = os.path.join(PKG, "check.bend")
    new = body()
    old = open(path).read() if os.path.exists(path) else None
    if "--check" in sys.argv[1:]:
        if old != new:
            print("out of date (run gen/check.py): check.bend")
            sys.exit(1)
        print("check.bend up to date")
    elif old != new:
        with open(path, "w", newline="\n") as f:
            f.write(new)


if __name__ == "__main__":
    main()
