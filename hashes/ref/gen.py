#!/usr/bin/env python3
"""Differential test cases for bend-osdev-hashes.

Writes ref/cases.bend (a Bend program printing, for each case, the digest
in one call, then the digest of the same message fed in three pieces
through init / update / final) and ref/expected.txt (the same from
implementations outside this package):
  * MD5, SHA-1: Python's hashlib (OpenSSL);
  * RIPEMD-160, SM3: hashlib, where OpenSSL provides them (otherwise the
    models below, said so on the last line);
  * MD4, Streebog-256, Streebog-512, Michael: ref/model.py, which Python
    lacks here (OpenSSL 3 keeps MD4 in its legacy provider; it has no
    Streebog or Michael). The models share an author with the package:
    model.py checks each against its specification's vectors first, and
    its MD5, SHA-1, RIPEMD-160 and SM3 against hashlib, before any case is
    written.

The messages are a linear congruential generator's bytes (the same
generator in Bend and here), of lengths around every block boundary up to
three blocks, and some longer ones; the pieces are cut at random points.
"""
import hashlib, os, random, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True
sys.path.insert(0, HERE)
import model  # noqa: E402

HEADER = """# Generated by ref/gen.py; do not edit by hand.
import Base
import ../../bytes/bytes.bend as B
import ../hashes.bend as Hs
import ../md4.bend as M4
import ../md5.bend as M5
import ../sha1.bend as S1
import ../ripemd160.bend as RM
import ../sm3.bend as SM
import ../streebog.bend as ST
import ../michael.bend as MI

# n bytes of a linear congruential generator from seed s (last generated
# first, as gen.py's msg() reverses them)
def msg.go(n: Nat, +s: U32, acc: List<&2, U32>) -> List<&2, U32>:
  match n:
    case 0n:
      acc
    case 1n+p:
      +s2 = U32.add(U32.mul(s, 1103515245), 12345)
      msg.go(p, s2, Con{U32.and(U32.shrn(s2, 16n), 255), acc})

def msg(s: U32, n: Nat) -> B.Octets:
  B.Octets.of_list(msg.go(n, s, Nil{}))

# the pieces [0, i), [i, j), [j, end) of o
def p1(+i: Nat, +o: B.Octets) -> B.Octets:
  B.Octets.take(i, o)

def p2(+i: Nat, +j: Nat, +o: B.Octets) -> B.Octets:
  B.Octets.take(Nat.sub(j, i), B.Octets.drop(i, o))

def p3(+j: Nat, +o: B.Octets) -> B.Octets:
  B.Octets.drop(j, o)

def mic.of(r: Result<&2, &2, Hs.HsError, Hs.HsW2>, +o: B.Octets, +i: Nat, +j: Nat) -> String:
  match r:
    case Done{+k}:
      B.Octets.hex(MI.HsMichael.mic(k, o)) ++ " " ++ B.Octets.hex(MI.HsMichael.final(MI.HsMichael.update(MI.HsMichael.update(MI.HsMichael.update(MI.HsMichael.init(k), p1(i, o)), p2(i, j, o)), p3(j, o))))
    case Fail{e}:
      "bad key"
"""

# name: (Bend init, update, final, digest; reference)
HASHES = {
    "md4": ("M4.HsMd4.init()", "M4.HsMd4.update", "M4.HsMd4.final", "M4.HsMd4.digest", model.md4, "model"),
    "md5": ("M5.HsMd5.init()", "M5.HsMd5.update", "M5.HsMd5.final", "M5.HsMd5.digest", lambda m: hashlib.md5(m).digest(), "hashlib"),
    "sha1": ("S1.HsSha1.init()", "S1.HsSha1.update", "S1.HsSha1.final", "S1.HsSha1.digest", lambda m: hashlib.sha1(m).digest(), "hashlib"),
    "ripemd160": ("RM.HsRipemd160.init()", "RM.HsRipemd160.update", "RM.HsRipemd160.final", "RM.HsRipemd160.digest", None, None),
    "sm3": ("SM.HsSm3.init()", "SM.HsSm3.update", "SM.HsSm3.final", "SM.HsSm3.digest", None, None),
    "streebog256": ("ST.HsStreebog.init256()", "ST.HsStreebog.update", "ST.HsStreebog.final256", "ST.HsStreebog.digest256", model.streebog256, "model"),
    "streebog512": ("ST.HsStreebog.init512()", "ST.HsStreebog.update", "ST.HsStreebog.final512", "ST.HsStreebog.digest512", model.streebog512, "model"),
}
for name, f in [("ripemd160", model.ripemd160), ("sm3", model.sm3)]:
    if name in hashlib.algorithms_available:
        HASHES[name] = HASHES[name][:4] + ((lambda n: lambda m: hashlib.new(n, m).digest())(name), "hashlib")
    else:
        HASHES[name] = HASHES[name][:4] + (f, "model")


def msg(s, n):
    out = []
    for _ in range(n):
        s = (s * 1103515245 + 12345) & 0xFFFFFFFF
        out.append((s >> 16) & 255)
    return bytes(reversed(out))


LENGTHS = [0, 1, 2, 3, 4, 5, 7, 8, 31, 55, 56, 57, 63, 64, 65, 100, 119, 120, 127, 128, 129, 183, 191, 192, 193, 1000, 4103]


def main():
    model.check_vectors()
    rng = random.Random(int(sys.argv[1]) if len(sys.argv) > 1 else 2026)
    lines, want = [], []
    for name, (init, upd, fin, dig, ref, src) in HASHES.items():
        for n in LENGTHS:
            s = rng.getrandbits(32)
            i = rng.randint(0, n)
            j = rng.randint(i, n)
            m = msg(s, n)
            o = "msg(%d, %dn)" % (s, n)
            pieces = "%s(%s(%s(%s(%s, p1(%dn, %s)), p2(%dn, %dn, %s)), p3(%dn, %s)))" % (fin, upd, upd, upd, init, i, o, i, j, o, j, o)
            lines.append('    IO.print("%s %d " ++ B.Octets.hex(%s(%s)) ++ " " ++ B.Octets.hex(%s))' % (name, n, dig, o, pieces))
            d = ref(m).hex()
            want.append("%s %d %s %s" % (name, n, d, d))
    for n in LENGTHS:
        k = bytes(rng.getrandbits(8) for _ in range(8))
        s = rng.getrandbits(32)
        i = rng.randint(0, n)
        j = rng.randint(i, n)
        lines.append('    IO.print("michael %d " ++ mic.of(MI.HsMichael.key(B.Octets.of_list([%s])), msg(%d, %dn), %dn, %dn))'
                     % (n, ", ".join(str(b) for b in k), s, n, i, j))
        d = model.michael(k, msg(s, n)).hex()
        want.append("michael %d %s %s" % (n, d, d))
    with open(os.path.join(HERE, "cases.bend"), "w", newline="\n") as f:
        f.write(HEADER + "\ndef main() -> IO(Unit):\n  do IO<Unit>:\n" + "\n".join(lines) + "\n")
    with open(os.path.join(HERE, "expected.txt"), "w", newline="\n") as f:
        f.write("\n".join(want) + "\n")
    srcs = {}
    for name, h in HASHES.items():
        srcs.setdefault(h[5], []).append(name)
    srcs.setdefault("model", []).append("michael")
    print("%d cases (%s)" % (len(want), "; ".join("%s: %s" % (k, ", ".join(v)) for k, v in sorted(srcs.items()))))


if __name__ == "__main__":
    main()
