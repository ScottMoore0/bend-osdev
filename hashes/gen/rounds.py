#!/usr/bin/env python3
"""Writes the compression functions of the 32-bit hashes, unrolled, from
the specifications' tables (gen/spec.py).

  python3 gen/rounds.py           rewrite the generated regions
  python3 gen/rounds.py --check   only check that they are up to date

Each region lies between "# BEGIN GENERATED by gen/rounds.py: <name>" and
"# END GENERATED: <name>" in <name>.bend; everything else is written by hand.
A region holds one def, hs.<name>.rounds(x, cv): the sixteen words of a
block and the chaining value in, the next chaining value out. Every step of
the specification is one line, binding a fresh name (v<i> for chaining
words, w<j> for the expanded message), so the code reads as the
specification's step list and needs no indexing at run time.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")
sys.dont_write_bytecode = True
sys.path.insert(0, HERE)
import spec  # noqa: E402

XS = ", ".join("+x%d" % i for i in range(16))
W16 = "Hs.HsW16{%s}" % XS


def rot(n, j):
    """the constant n rotated left by j"""
    j %= 32
    return ((n << j) | (n >> (32 - j))) & 0xFFFFFFFF if j else n


class Names:
    def __init__(self):
        self.i = 0

    def new(self):
        self.i += 1
        return "v%d" % self.i


def add(*xs):
    t = xs[0]
    for x in xs[1:]:
        t = "U32.add(%s, %s)" % (t, x)
    return t


def md4():
    out = ["def hs.md4.rounds(x: Hs.HsW16, cv: Hs.HsW4) -> Hs.HsW4:",
           "  match x cv:",
           "    case %s Hs.HsW4{+a0, +b0, +c0, +d0}:" % W16]
    F = ["hs.md4.f", "hs.md4.g", "hs.md4.h"]
    a, b, c, d = "a0", "b0", "c0", "d0"
    n = Names()
    for r in range(3):
        out.append("      # round %d" % (r + 1))
        for i in range(16):
            v = n.new()
            k = spec.MD4_X[r][i]
            s = spec.MD4_S[r][i % 4]
            out.append("      +%s = hs.md4.step(%s, %s(%s, %s, %s), x%d, %d, %dn)" % (v, a, F[r], b, c, d, k, spec.MD4_K[r], s))
            a, b, c, d = d, v, b, c
    out.append("      Hs.HsW4{%s}" % ", ".join("U32.add(%s, %s)" % p for p in [("a0", a), ("b0", b), ("c0", c), ("d0", d)]))
    return "\n".join(out) + "\n"


def md5():
    out = ["def hs.md5.rounds(x: Hs.HsW16, cv: Hs.HsW4) -> Hs.HsW4:",
           "  match x cv:",
           "    case %s Hs.HsW4{+a0, +b0, +c0, +d0}:" % W16]
    F = ["hs.md5.f", "hs.md5.g", "hs.md5.h", "hs.md5.i"]
    a, b, c, d = "a0", "b0", "c0", "d0"
    n = Names()
    for j in range(64):
        r = j // 16
        if j % 16 == 0:
            out.append("      # round %d" % (r + 1))
        v = n.new()
        out.append("      +%s = hs.md5.step(%s, %s, %s(%s, %s, %s), x%d, %d, %dn)"
                   % (v, a, b, F[r], b, c, d, spec.MD5_X[r][j % 16], spec.MD5_T[j], spec.MD5_S[r][j % 4]))
        a, b, c, d = d, v, b, c
    out.append("      Hs.HsW4{%s}" % ", ".join("U32.add(%s, %s)" % p for p in [("a0", a), ("b0", b), ("c0", c), ("d0", d)]))
    return "\n".join(out) + "\n"


def sha1():
    out = ["def hs.sha1.rounds(x: Hs.HsW16, cv: Hs.HsW5) -> Hs.HsW5:",
           "  match x cv:",
           "    case %s Hs.HsW5{+a0, +b0, +c0, +d0, +e0}:" % W16]
    F = ["hs.sha1.ch", "hs.sha1.parity", "hs.sha1.maj", "hs.sha1.parity"]
    W = ["x%d" % i for i in range(16)]
    a, b, c, d, e = "a0", "b0", "c0", "d0", "e0"
    n = Names()
    for t in range(80):
        if t % 20 == 0:
            out.append("      # steps %d to %d" % (t, t + 19))
        if t >= 16:
            w = "w%d" % t
            out.append("      +%s = Hs.hs.rotl(U32.xor(U32.xor(%s, %s), U32.xor(%s, %s)), 1n)" % (w, W[t - 3], W[t - 8], W[t - 14], W[t - 16]))
            W.append(w)
        v = n.new()
        out.append("      +%s = %s" % (v, add("Hs.hs.rotl(%s, 5n)" % a, "%s(%s, %s, %s)" % (F[t // 20], b, c, d), e, str(spec.SHA1_K[t // 20]), W[t])))
        nb = n.new()
        out.append("      +%s = Hs.hs.rotl(%s, 30n)" % (nb, b))
        a, b, c, d, e = v, a, nb, c, d
    out.append("      Hs.HsW5{%s}" % ", ".join("U32.add(%s, %s)" % p for p in [("a0", a), ("b0", b), ("c0", c), ("d0", d), ("e0", e)]))
    return "\n".join(out) + "\n"


def ripemd160():
    out = ["def hs.ripemd160.rounds(x: Hs.HsW16, cv: Hs.HsW5) -> Hs.HsW5:",
           "  match x cv:",
           "    case %s Hs.HsW5{+h0, +h1, +h2, +h3, +h4}:" % W16]
    F = ["hs.rmd.f1", "hs.rmd.f2", "hs.rmd.f3", "hs.rmd.f4", "hs.rmd.f5"]
    n = Names()

    def line(side, R, S, K, fs):
        a, b, c, d, e = "h0", "h1", "h2", "h3", "h4"
        for j in range(80):
            r = j // 16
            if j % 16 == 0:
                out.append("      # %s line, round %d" % (side, r + 1))
            v = n.new()
            out.append("      +%s = hs.rmd.step(%s, %s(%s, %s, %s), x%d, %d, %dn, %s)"
                       % (v, a, fs[r], b, c, d, R[r][j % 16], K[r], S[r][j % 16], e))
            nc = n.new()
            out.append("      +%s = Hs.hs.rotl(%s, 10n)" % (nc, c))
            a, e, d, c, b = e, d, nc, b, v
        return a, b, c, d, e

    al, bl, cl, dl, el = line("left", spec.RMD_R, spec.RMD_S, spec.RMD_K, F)
    ar, br, cr, dr, er = line("right", spec.RMD_RP, spec.RMD_SP, spec.RMD_KP, F[::-1])
    out.append("      Hs.HsW5{%s, %s, %s, %s, %s}" % (add("h1", cl, dr), add("h2", dl, er), add("h3", el, ar),
                                                    add("h4", al, br), add("h0", bl, cr)))
    return "\n".join(out) + "\n"


def sm3():
    out = ["def hs.sm3.rounds(x: Hs.HsW16, cv: Hs.HsW8) -> Hs.HsW8:",
           "  match x cv:",
           "    case %s Hs.HsW8{+a0, +b0, +c0, +d0, +e0, +f0, +g0, +h0}:" % W16]
    W = ["x%d" % i for i in range(16)]

    def expand(j):
        w = "w%d" % j
        out.append("      +%s = U32.xor(U32.xor(hs.sm3.p1(U32.xor(U32.xor(%s, %s), Hs.hs.rotl(%s, 15n))), Hs.hs.rotl(%s, 7n)), %s)"
                   % (w, W[j - 16], W[j - 9], W[j - 3], W[j - 13], W[j - 6]))
        W.append(w)

    A, B, C, D, E, F, G, H = "a0", "b0", "c0", "d0", "e0", "f0", "g0", "h0"
    n = Names()
    for j in range(64):
        if j % 16 == 0:
            out.append("      # rounds %d to %d" % (j, j + 15))
        while len(W) <= j + 4:
            expand(len(W))
        ff, gg = ("hs.sm3.ff0", "hs.sm3.gg0") if j < 16 else ("hs.sm3.ff1", "hs.sm3.gg1")
        a12 = n.new()
        out.append("      +%s = Hs.hs.rotl(%s, 12n)" % (a12, A))
        ss1 = n.new()
        out.append("      +%s = Hs.hs.rotl(%s, 7n)" % (ss1, add(a12, E, str(rot(spec.SM3_T[j], j)))))
        tt1 = n.new()
        out.append("      +%s = %s" % (tt1, add("%s(%s, %s, %s)" % (ff, A, B, C), D, "U32.xor(%s, %s)" % (ss1, a12), "U32.xor(%s, %s)" % (W[j], W[j + 4]))))
        tt2 = n.new()
        out.append("      +%s = %s" % (tt2, add("%s(%s, %s, %s)" % (gg, E, F, G), H, ss1, W[j])))
        nc, ng, ne = n.new(), n.new(), n.new()
        out.append("      +%s = Hs.hs.rotl(%s, 9n)" % (nc, B))
        out.append("      +%s = Hs.hs.rotl(%s, 19n)" % (ng, F))
        out.append("      +%s = hs.sm3.p0(%s)" % (ne, tt2))
        A, B, C, D = tt1, A, nc, C
        E, F, G, H = ne, E, ng, G
    out.append("      Hs.HsW8{%s}" % ", ".join("U32.xor(%s, %s)" % p for p in
                                             [("a0", A), ("b0", B), ("c0", C), ("d0", D), ("e0", E), ("f0", F), ("g0", G), ("h0", H)]))
    return "\n".join(out) + "\n"


REGIONS = [("md4.bend", "md4", md4), ("md5.bend", "md5", md5), ("sha1.bend", "sha1", sha1),
           ("ripemd160.bend", "ripemd160", ripemd160), ("sm3.bend", "sm3", sm3)]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fname, name, body in REGIONS:
        path = os.path.join(PKG, fname)
        with open(path) as f:
            text = f.read()
        begin = "# BEGIN GENERATED by gen/rounds.py: %s\n" % name
        end = "# END GENERATED: %s\n" % name
        i, j = text.index(begin) + len(begin), text.index(end)
        new = text[:i] + body() + text[j:]
        if new != text:
            stale.append(fname)
            if not check:
                with open(path, "w", newline="\n") as f:
                    f.write(new)
    if check:
        if stale:
            print("out of date (run gen/rounds.py): " + ", ".join(stale))
            sys.exit(1)
        print("generated regions up to date")


if __name__ == "__main__":
    main()
