#!/usr/bin/env python3
"""Writes hashes/check.bend: every hash on its specification's vectors,
whole and in three pieces, through the public interface, with the expected
output (the specifications' values, from ref/model.py's tables) as the
file's #| lines.

  python3 gen/check.py           rewrite check.bend
  python3 gen/check.py --check   only check that it is up to date

Beside the laws' vectors, check.bend runs the ones too long for the
kernel: Streebog's whole digests (RFC 6986's M1 and M2, both sizes), and a
million bytes "a" through RIPEMD-160 (the RIPEMD-160 page's value) and
SHA-1 (FIPS 180-2's third example, which hashlib also gives).
"""
import hashlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.join(PKG, "ref"))
import model  # noqa: E402

MILLION_A_SHA1 = "34aa973cd4c4daa4f61eeb2bdbad27316534016f"
MILLION_A_RMD = "52783243c1697bdbe16d37f97f68f08325dc1528"
assert hashlib.sha1(b"a" * 1000000).hexdigest() == MILLION_A_SHA1


def octets(bs):
    s = bs.decode("latin-1")
    if all(32 <= ord(c) < 127 and c not in '"\\' for c in s):
        return 'B.Octets.of_string("%s")' % s
    return "B.Octets.of_list([%s])" % ", ".join(str(b) for b in bs)


HASHES = {  # name: (digest, init, update, final)
    "md4": ("M4.HsMd4.digest", "M4.HsMd4.init()", "M4.HsMd4.update", "M4.HsMd4.final"),
    "md5": ("M5.HsMd5.digest", "M5.HsMd5.init()", "M5.HsMd5.update", "M5.HsMd5.final"),
    "sha1": ("S1.HsSha1.digest", "S1.HsSha1.init()", "S1.HsSha1.update", "S1.HsSha1.final"),
    "ripemd160": ("RM.HsRipemd160.digest", "RM.HsRipemd160.init()", "RM.HsRipemd160.update", "RM.HsRipemd160.final"),
    "sm3": ("SM.HsSm3.digest", "SM.HsSm3.init()", "SM.HsSm3.update", "SM.HsSm3.final"),
    "streebog256": ("ST.HsStreebog.digest256", "ST.HsStreebog.init256()", "ST.HsStreebog.update", "ST.HsStreebog.final256"),
    "streebog512": ("ST.HsStreebog.digest512", "ST.HsStreebog.init512()", "ST.HsStreebog.update", "ST.HsStreebog.final512"),
}

VECTORS = ([("md4", m, v) for m, v in zip(model.ASCII, model.MD4_V)]
           + [("md5", m, v) for m, v in zip(model.ASCII, model.MD5_V)]
           + [("sha1", m, v) for m, v in model.SHA1_V]
           + [("ripemd160", m, v) for m, v in model.RMD_V]
           + [("sm3", m, v) for m, v in model.SM3_V]
           + [("streebog%d" % bits, m, bytes.fromhex(v)[::-1].hex()) for m, bits, v in model.STB_V])

HEADER = '''# Generated by gen/check.py; do not edit by hand.
#
# Every hash on its specification's vectors, through the public interface:
# the digest in one call, then the same message fed in three pieces
# (init, three updates, final). Then Streebog's transformations on RFC
# 6986's example 1, a million bytes "a" through SHA-1 and RIPEMD-160, and
# Michael on the standard's six vectors (each key the previous tag) with a
# short key refused. The values are the specifications' (the #| lines).
import Base
import ../bytes/bytes.bend as B
import ./hashes.bend as Hs
import ./md4.bend as M4
import ./md5.bend as M5
import ./sha1.bend as S1
import ./ripemd160.bend as RM
import ./sm3.bend as SM
import ./streebog.bend as ST
import ./michael.bend as MI

# a byte string in three pieces: [0, n/3), [n/3, 2n/3), [2n/3, n)
def third(+o: B.Octets) -> Nat:
  Nat.div(B.Octets.len(o), 3n)

def p1(+o: B.Octets) -> B.Octets:
  B.Octets.take(third(o), o)

def p2(+o: B.Octets) -> B.Octets:
  B.Octets.take(third(o), B.Octets.drop(third(o), o))

def p3(+o: B.Octets) -> B.Octets:
  B.Octets.drop(Nat.mul(2n, third(o)), o)

def mic.of(r: Result<&2, &2, Hs.HsError, Hs.HsW2>, +m: B.Octets) -> String:
  match r:
    case Done{+k}:
      B.Octets.hex(MI.HsMichael.mic(k, m)) ++ " " ++ B.Octets.hex(MI.HsMichael.final(MI.HsMichael.update(MI.HsMichael.update(MI.HsMichael.update(MI.HsMichael.init(k), p1(m)), p2(m)), p3(m))))
    case Fail{e}:
      match e:
        case Hs.HsBadKeyLength{n}:
          "bad key length " ++ U32.show(U32.from_nat(n))

def mic(k: B.Octets, m: B.Octets) -> String:
  mic.of(MI.HsMichael.key(k), m)

# n bytes "a", built tail-recursively
def as.go(n: Nat, acc: List<&2, U32>) -> List<&2, U32>:
  match n:
    case 0n:
      acc
    case 1n+p:
      as.go(p, Con{97, acc})

def million_a() -> B.Octets:
  B.Octets.of_list(as.go(1000000n, Nil{}))
'''


def body():
    lines, want = [], []
    for i, (name, m, v) in enumerate(VECTORS):
        dig, init, upd, fin = HASHES[name]
        o = octets(m)
        lines.append('    IO.print("%s %d " ++ B.Octets.hex(%s(%s)) ++ " " ++ B.Octets.hex(%s(%s(%s(%s(%s, p1(%s)), p2(%s)), p3(%s)))))'
                     % (name, len(m), dig, o, fin, upd, upd, upd, init, o, o, o))
        want.append("%s %d %s %s" % (name, len(m), v, v))
    z = "B.Octets.zeros(64n)"
    h1 = bytes.fromhex(model.STB_EX1[1])[::-1]
    for label, call, v in [
            ("lps(0)", "ST.HsStreebog.lps(%s)" % z, model.STB_EX1[0]),
            ("g_N(0, M1)", "ST.HsStreebog.g(%s, %s, %s)" % (z, z, octets(model.STB_M1 + bytes([1]))), model.STB_EX1[1]),
            ("g_0(h, 504)", "ST.HsStreebog.g(%s, %s, B.Octets.of_list([248, 1]))" % (z, octets(h1)), model.STB_EX1[2])]:
        lines.append('    IO.print("streebog %s " ++ B.Octets.hex(%s))' % (label, call))
        want.append("streebog %s %s" % (label, bytes.fromhex(v)[::-1].hex()))
    lines.append('    IO.print("sha1 million a " ++ B.Octets.hex(S1.HsSha1.digest(big)))')
    want.append("sha1 million a " + MILLION_A_SHA1)
    lines.append('    IO.print("ripemd160 million a " ++ B.Octets.hex(RM.HsRipemd160.digest(big)))')
    want.append("ripemd160 million a " + MILLION_A_RMD)
    for k, m, v in model.MICHAEL_V:
        lines.append('    IO.print("michael %s " ++ mic(%s, %s))' % (k, octets(bytes.fromhex(k)), octets(m)))
        want.append("michael %s %s %s" % (k, v, v))
    lines.append('    IO.print("michael short key: " ++ mic(B.Octets.zeros(7n), B.Octets.empty()))')
    want.append("michael short key: bad key length 7")
    return (HEADER + "\ndef main() -> IO(Unit):\n  +big = million_a()\n  do IO<Unit>:\n" + "\n".join(lines) + "\n\n"
            + "".join("#|%s\n" % w for w in want))


def main():
    path = os.path.join(PKG, "check.bend")
    new = body()
    old = open(path).read() if os.path.exists(path) else None
    if "--check" in sys.argv[1:]:
        if old != new:
            print("out of date (run gen/check.py): check.bend")
            sys.exit(1)
        print("check.bend up to date")
    elif old != new:
        with open(path, "w", newline="\n") as f:
            f.write(new)


if __name__ == "__main__":
    main()
