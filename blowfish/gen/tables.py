#!/usr/bin/env python3
"""Blowfish's P-array and S-boxes, and the generator of the Bend code that
holds them.

  python3 gen/tables.py           rewrite the generated regions
  python3 gen/tables.py --check   only check that they are up to date

The data below is transcribed from the specification; what can be
computed from a specification's definition is computed instead:
  * the fractional part of pi in hex (Schneier, "Description of a New
    Variable-Length Key, 64-Bit Block Cipher (Blowfish)", FSE 1993),
    computed here by Machin's formula, not copied.

They are checked when ref/gen.py runs: Schneier's test vectors, and
Python's cryptography (Blowfish).

Regions, each between "# BEGIN GENERATED by gen/tables.py: <name>" and
"# END GENERATED: <name>":
  blowfish.bend "tables"   bf.pi.list() (the 1042 words of pi, P then S)
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")

# ---------------------------------------------------------------- computed

def pi_words(n):
    """the first n 32-bit words of the fractional part of pi"""
    bits = 32 * n
    prec = bits + 64
    one = 1 << prec

    def atan_inv(x):
        s, t, k, sign, x2 = 0, one // x, 1, 1, x * x
        while t:
            s += sign * (t // k)
            t //= x2
            k += 2
            sign = -sign
        return s

    frac = 16 * atan_inv(5) - 4 * atan_inv(239) - (3 << prec)
    frac >>= 64
    return [(frac >> (bits - 32 * (i + 1))) & 0xFFFFFFFF for i in range(n)]


PI = pi_words(18 + 4 * 256)
assert PI[0] == 0x243F6A88 and PI[17] == 0x8979FB1B and PI[18] == 0xD1310BA6


# ---------------------------------------------------------------- Bend

def bend_list(name, ws, comment):
    rows = []
    for i in range(0, len(ws), 8):
        rows.append(", ".join(str(w) for w in ws[i:i + 8]))
    return "# %s\ndef %s() -> List<&2, U32>:\n  [%s]\n" % (comment, name, ",\n    ".join(rows))


def blowfish_region():
    return bend_list("bf.pi.list", PI, "the first 1042 words of the fractional part of pi: P1 .. P18, then\n# S1, S2, S3, S4 (256 words each)")


REGIONS = [("blowfish.bend", "tables", blowfish_region)]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fname, name, body in REGIONS:
        path = os.path.join(PKG, fname)
        with open(path, encoding="utf-8", newline="") as f:
            src = f.read()
        begin = "# BEGIN GENERATED by gen/tables.py: %s\n" % name
        end = "# END GENERATED: %s\n" % name
        i = src.index(begin) + len(begin)
        j = src.index(end, i)
        new = src[:i] + body() + src[j:]
        if new != src:
            stale.append("%s (%s)" % (fname, name))
            if not check:
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(new)
    if check:
        if stale:
            print("out of date (run gen/tables.py): " + ", ".join(stale))
            sys.exit(1)
        print("generated tables up to date")


if __name__ == "__main__":
    main()

