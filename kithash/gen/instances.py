#!/usr/bin/env python3
"""The instances of crypto's hash and MAC interfaces in bend-osdev-kithash,
and their laws.

  python3 gen/instances.py           rewrite the generated regions
  python3 gen/instances.py --check   only check that they are up to date

Each region lies between "# BEGIN GENERATED by gen/instances.py: <name>" and
"# END GENERATED: <name>":
  * "laws" in LAWS.bend: one law per instance and law schema;
  * "proofs" in PROOF.bend: their proofs.
Everything outside the regions is written by hand.

The schemas. A hash (HASH, inst_hash.bend) is the buffered state KhBuf with
a one-shot digest, so its streaming, split and split3 laws are the generic
laws khbuf_* (LAWS.bend, by hand) at its digest, and its length law follows
from the length of its value's big-endian bytes (be32_len or be64_len in
PROOF.bend). A MAC (MAC, inst_mac.bend) takes crypto's named default verify,
so its accepts and agrees laws follow from bytes' octets_is_eq_refl, for
every key and message (and every parameter set, for siphash's).

Why written out per instance rather than imported from crypto: crypto's
PROOF.bend takes over 2 GB of the checker's memory, and these proofs are
one line each.

Adding an instance: a row in HASH (its name, title, template parameters,
digest def and value, and the value's width) or MAC (its key type, key,
compute and verify defs); then run this script.
"""
import os, sys, textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")

# name, title, template parameters, digest def (with its template
# arguments), the value of the bytes b (for the length proof), the width
HASH = [
    dict(name="crc32", title="CRC-32 (bend-kit-hash)", tp=[], digest="IH.KhCrc32.digest",
         value="K.KhCrc32.value(b)", width=32),
    dict(name="adler32", title="Adler-32 (bend-kit-hash)", tp=[], digest="IH.KhAdler32.digest",
         value="K.KhAdler32.value(b)", width=32),
    dict(name="fnv1a32", title="FNV-1a 32 (bend-kit-hash)", tp=[], digest="IH.KhFnv1a32.digest",
         value="K.KhFnv1a32.value(b)", width=32),
    dict(name="fnv1a64", title="FNV-1a 64 (bend-kit-hash)", tp=[], digest="IH.KhFnv1a64.digest",
         value="K.KhFnv1a64.value(b)", width=64),
    dict(name="xxh32", title="XXH32 (bend-kit-hash), for every seed", tp=["~seed: U32"],
         digest="IH.KhXxh32.digest(~seed)", value="K.KhXxh32.value(seed, b)", width=32),
    dict(name="xxh64", title="XXH64 (bend-kit-hash), for every seed", tp=["~seed: W.W64"],
         digest="IH.KhXxh64.digest(~seed)", value="K.KhXxh64.value(seed, b)", width=64),
]

# name, title, template parameters, key type, compute and verify defs
MAC = [
    dict(name="siphash", title="SipHash-c-d (the siphash package), for every parameter set",
         tp=["~prm: S.SipParams"], K="S.SipKey", compute="IM.KhSip.compute(~prm)", verify="IM.KhSip.verify(~prm)"),
    dict(name="kit_siphash13", title="bend-kit-hash's SipHash-1-3", tp=[], K="S.SipKey",
         compute="IM.KhSip13.compute", verify="IM.KhSip13.verify"),
    dict(name="halfsiphash", title="HalfSipHash-c-d (the siphash package), for every parameter set",
         tp=["~prm: S.SipParams"], K="HS.HsipKey", compute="IM.KhHsip.compute(~prm)", verify="IM.KhHsip.verify(~prm)"),
]

LAWS, PROOFS = [], []


def law(name, comment, params, stmt):
    head = "".join("  for %s\n" % p for p in params)
    com = "".join("# %s\n" % l for l in textwrap.wrap(comment, 76))
    LAWS.append("%slaw %s:\n%s  %s\n" % (com, name, head, stmt))


def call(fn, *args):
    """a def given with its template arguments, called on args"""
    if fn.endswith(")"):
        return fn[:-1] + "".join(", " + a for a in args) + ")" if args else fn
    return "%s(%s)" % (fn, ", ".join(args)) if args else fn


def tnames(c):
    return "".join(t.split(":")[0].strip("~ ") + ", " for t in c["tp"])


def hash_laws(c):
    n, d = c["name"], c["digest"]
    fin = "IH.KhBuf.final(~%s, %%s)" % d
    law("%s_hash_split" % n, "%s: in two pieces, the one-shot digest of the whole" % c["title"],
        c["tp"] + ["+a: B.Octets", "+b: B.Octets"],
        "{%s == %s : B.Octets}" % (fin % "IH.KhBuf.update(IH.KhBuf.update(IH.KhBuf.init(), a), b)",
                                    call(d, "B.Octets.append(a, b)")))
    PROOFS.append("def Laws.%s_hash_split(%sa, b):\n  Laws.khbuf_split(~%s, a, b)\n" % (n, tnames(c), d))
    law("%s_hash_split3" % n, "%s: in three pieces, the one-shot digest of the whole" % c["title"],
        c["tp"] + ["+a: B.Octets", "+b: B.Octets", "+c: B.Octets"],
        "{%s == %s : B.Octets}" % (fin % "IH.KhBuf.update(IH.KhBuf.update(IH.KhBuf.update(IH.KhBuf.init(), a), b), c)",
                                    call(d, "B.Octets.append(a, B.Octets.append(b, c))")))
    PROOFS.append("def Laws.%s_hash_split3(%sa, b, c):\n  Laws.khbuf_split3(~%s, a, b, c)\n" % (n, tnames(c), d))
    law("%s_hash_length" % n, "%s: the digest has %d bytes, from every state" % (c["title"], c["width"] // 8),
        c["tp"] + ["s: IH.KhBuf"], "{B.Octets.len(%s) == %dn : Nat}" % (fin % "s", c["width"] // 8))
    PROOFS.append("def Laws.%s_hash_length(%ss):\n  match s:\n    case IH.KhBuf{b}:\n      be%d_len(%s)\n"
                  % (n, tnames(c), c["width"], c["value"]))


def mac_laws(c):
    n, K = c["name"], c["K"]
    tag = call(c["compute"], "k", "m")
    law("%s_mac_accepts" % n, "%s: verify accepts the computed tag, for every key and message" % c["title"],
        c["tp"] + ["+k: %s" % K, "+m: B.Octets"], "{%s == True{} : Bool}" % call(c["verify"], "k", "m", tag))
    PROOFS.append("def Laws.%s_mac_accepts(%sk, m):\n  BL.octets_is_eq_refl(%s)\n" % (n, tnames(c), tag))
    law("%s_mac_agrees" % n, "%s: verify accepts exactly the computed tag" % c["title"],
        c["tp"] + ["+k: %s" % K, "+m: B.Octets", "t: B.Octets"],
        "{%s == B.Octets.is_eq(%s, t) : Bool}" % (call(c["verify"], "k", "m", "t"), tag))
    PROOFS.append("def Laws.%s_mac_agrees(%sk, m, t):\n  {==}\n" % (n, tnames(c)))


for c in HASH:
    hash_laws(c)
for c in MAC:
    mac_laws(c)

REGIONS = [("LAWS.bend", "laws", lambda: "\n".join(LAWS)), ("PROOF.bend", "proofs", lambda: "\n".join(PROOFS))]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fname, name, body in REGIONS:
        path = os.path.join(PKG, fname)
        with open(path) as f:
            text = f.read()
        begin = "# BEGIN GENERATED by gen/instances.py: %s\n" % name
        end = "# END GENERATED: %s\n" % name
        i, j = text.index(begin) + len(begin), text.index(end)
        new = text[:i] + body() + text[j:]
        if new != text:
            stale.append("%s (%s)" % (fname, name))
            if not check:
                with open(path, "w", newline="\n") as f:
                    f.write(new)
    if check:
        if stale:
            print("out of date (run gen/instances.py): " + ", ".join(stale))
            sys.exit(1)
        print("generated regions up to date")


if __name__ == "__main__":
    main()
