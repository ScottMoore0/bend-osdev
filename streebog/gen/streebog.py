#!/usr/bin/env python3
"""Writes Streebog's tables and its LPS transformation (streebog.bend),
from RFC 6986's Pi', tau and A (gen/spec.py).

  python3 gen/streebog.py           rewrite the generated regions
  python3 gen/streebog.py --check   only check that they are up to date

LPS = L(P(S(x))) on a 512-bit x, as eight 64-bit chunks (chunk k is bytes
8k .. 8k+7 of x, least significant first; RFC 6986 writes x = a_63 || ... ||
a_0, so byte i is a_i). P moves byte 8j + k of S(x) to byte 8k + j (tau is
the transposition of an 8 x 8 byte matrix), so chunk k of P(S(x)) is the
sum over j of Pi(byte k of chunk j) shifted up 8j bits, and L is linear,
so
    chunk k of LPS(x) = XOR over j of T_j[byte k of chunk j],
    T_j[b] = l(Pi(b) << 8j),
where l(v) is the XOR of the rows A_(63-i) of A for the bits i set in v
(RFC 6986, section 7: l(b) = b_63 A_0 xor ... xor b_0 A_63). The eight
tables T_0 .. T_7 (256 entries of 64 bits each) are written here, and LPS is
unrolled over them; main() first checks the tables' LPS against the
definition (S, then P, then L, directly from Pi', tau and A) on random
inputs.

The iteration constants C_1 .. C_12 (RFC 6986, 6.5) are written as 512-bit
vectors (sixteen 32-bit words, least significant first).
"""
import os, random, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")
sys.dont_write_bytecode = True
sys.path.insert(0, HERE)
import spec  # noqa: E402

M64 = (1 << 64) - 1


def l64(v):
    r = 0
    for i in range(64):
        if v >> i & 1:
            r ^= spec.STB_A[63 - i]
    return r


T = [[l64(spec.STB_PI[b] << (8 * j)) for b in range(256)] for j in range(8)]


def lps_direct(x):
    bs = x.to_bytes(64, "little")
    bs = bytes(spec.STB_PI[b] for b in bs)
    bs = bytes(bs[spec.STB_TAU[i]] for i in range(64))
    return sum(l64(int.from_bytes(bs[8 * k:8 * k + 8], "little")) << (64 * k) for k in range(8))


def lps_tables(x):
    out = 0
    for k in range(8):
        c = 0
        for j in range(8):
            c ^= T[j][(x >> (64 * j + 8 * k)) & 255]
        out |= c << (64 * k)
    return out


def words(v, n=16):
    return [(v >> (32 * i)) & 0xFFFFFFFF for i in range(n)]


def tables():
    out = []
    for j in range(8):
        out.append("# T_%d[b] = l(Pi(b) << %d): each entry's low and high 32 bits" % (j, 8 * j))
        out.append("def hs.stb.t%d.list() -> List<&2, Hs.HsW2>:" % j)
        rows = ["Hs.HsW2{%d, %d}" % (e & 0xFFFFFFFF, e >> 32) for e in T[j]]
        lines = [", ".join(rows[i:i + 4]) for i in range(0, 256, 4)]
        out.append("  [" + ",\n    ".join(lines) + "]")
        out.append("")
    out.append("def HsStreebog.tables() -> HsStbTabs:")
    out.append("  HsStbTabs{%s}" % ", ".join("hs.stb.tab(hs.stb.t%d.list())" % j for j in range(8)))
    return "\n".join(out) + "\n"


def consts():
    out = []
    for i, c in enumerate(spec.STB_C):
        out.append("def hs.stb.c%d() -> Hs.HsW16:" % (i + 1))
        out.append("  Hs.HsW16{%s}" % ", ".join(str(w) for w in words(c)))
        out.append("")
    return "\n".join(out)


def lps():
    out = ["# LPS(x): chunk k of the result is the XOR over j of T_j[byte k of chunk j]",
           "def hs.stb.lps(+t: HsStbTabs, x: Hs.HsW16) -> Hs.HsW16:",
           "  match t x:",
           "    case HsStbTabs{+t0, +t1, +t2, +t3, +t4, +t5, +t6, +t7} Hs.HsW16{%s}:" % ", ".join("+x%d" % i for i in range(16))]
    for k in range(8):
        es = []
        for j in range(8):
            w, sh = 2 * j + k // 4, 8 * (k % 4)
            byte = "U32.and(255, U32.shrn(x%d, %dn))" % (w, sh) if sh else "U32.and(255, x%d)" % w
            es.append("hs.stb.get(t%d, %s)" % (j, byte))
        out.append("      +o%d = hs.stb.x8(%s)" % (k, ", ".join(es)))
    out.append("      hs.stb.join(%s)" % ", ".join("o%d" % k for k in range(8)))
    return "\n".join(out) + "\n"


REGIONS = [("tables", tables), ("consts", consts), ("lps", lps)]


def main():
    rng = random.Random(6986)
    for _ in range(200):
        x = rng.getrandbits(512)
        assert lps_direct(x) == lps_tables(x)
    check = "--check" in sys.argv[1:]
    path = os.path.join(PKG, "streebog.bend")
    with open(path) as f:
        text = f.read()
    new = text
    for name, body in REGIONS:
        begin = "# BEGIN GENERATED by gen/streebog.py: %s\n" % name
        end = "# END GENERATED: %s\n" % name
        i, j = new.index(begin) + len(begin), new.index(end)
        new = new[:i] + body() + new[j:]
    if check:
        if new != text:
            print("out of date (run gen/streebog.py): streebog.bend")
            sys.exit(1)
        print("generated regions up to date")
    elif new != text:
        with open(path, "w", newline="\n") as f:
            f.write(new)


if __name__ == "__main__":
    main()
