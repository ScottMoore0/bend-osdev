#!/usr/bin/env python3
"""Writes the generated lemmas of PROOF.bend: the case splits too long to
write by hand. Run it from deflate/ and it replaces the block between the
BEGIN and END marker lines in PROOF.bend.

  * fbh.n: for each n from 1 to 255, the inflater reads the header of a
    stored block of n bytes, as stored_stream writes it ([0, n, 0, 255 - n,
    255], masked), into the state that copies n bytes;
  * fbh.k: for every m <= 254, the header of a block of m + 1 bytes, by
    cases on m (one def per case, each passing the rest on).
"""

BEGIN = "# BEGIN generated by gen/proofs.py"
END = "# END generated by gen/proofs.py"

RUN = "I.DflRun{I.DflCore{%s, win, Nil{}}, acc, r}"
NL = "\n"


def header(n):
    return ("def fbh.n%d(+win: W.DflWin, +acc: List<&2, U32>, +r: Nat) -> {I.drv.go(B.mask(D.fb.hdr(%dn)), %s) == %s : I.DflDrv}:" % (n, n, RUN % "I.inf.head()", RUN % ("I.DflStored{%dn, False{}}" % n))
            + NL + "  {==}" + NL)


def step_goal(k, m):
    succ = "1n+" * (k + 1)
    return "{I.drv.go(B.mask(D.fb.hdr(%s%s)), %s) == %s : I.DflDrv}" % (
        succ, m, RUN % "I.inf.head()", RUN % ("I.DflStored{%s%s, False{}}" % (succ, m)))


def step(k):
    # m <= 254 - k: the header for k + 1 + m bytes
    lines = [
        "def fbh.k%d(m: Nat, +win: W.DflWin, +acc: List<&2, U32>, +r: Nat, h: {Nat.is_le(m, %dn) == True{} : Bool}) -> %s:" % (k, 254 - k, step_goal(k, "m")),
        "  match m:",
        "    case 0n:",
        "      fbh.n%d(win, acc, r)" % (k + 1),
        "    case 1n+p:",
    ]
    if k == 254:
        lines.append("      Empty.absurd(%s, absurd.ft(h))" % step_goal(k, "1n+p"))
    else:
        lines.append("      fbh.k%d(p, win, acc, r, h)" % (k + 1))
    return NL.join(lines) + NL


def generate():
    out = [BEGIN, ""]
    for n in range(1, 256):
        out.append(header(n))
    for k in range(254, -1, -1):
        out.append(step(k))
    out.append(END)
    return NL.join(out)


def main():
    import sys
    p = sys.argv[1] if len(sys.argv) > 1 else "PROOF.bend"
    s = open(p).read()
    i = s.index(BEGIN)
    j = s.index(END) + len(END)
    s = s[:i] + generate() + s[j:]
    with open(p, "w", newline="\n") as f:
        f.write(s)


if __name__ == "__main__":
    main()
