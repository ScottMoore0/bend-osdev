#!/usr/bin/env python3
"""Writes fixed.bend: the decoding trees of RFC 1951's fixed codes (3.2.6),
built here by 3.2.2's canonical assignment, as constants, so the inflater
need not build them for each fixed block (LAWS.bend's fixed_trees proves
them equal to huff_tree of the fixed lengths).

  python3 gen/fixed.py > fixed.bend
"""

LIT = [8] * 144 + [9] * 112 + [7] * 24 + [8] * 8
DIST = [5] * 32


def canon(lens):
    mx = max(lens)
    count = [0] * (mx + 2)
    for l in lens:
        if l:
            count[l] += 1
    code, nxt = 0, [0] * (mx + 2)
    for b in range(1, mx + 1):
        code = (code + count[b - 1]) << 1
        nxt[b] = code
    out = {}
    for i, l in enumerate(lens):
        if l:
            out[i] = (nxt[l], l)
            nxt[l] += 1
    return out


def tree(lens):
    root = {}
    for sym, (code, n) in canon(lens).items():
        node = root
        for i in range(n - 1, -1, -1):
            b = (code >> i) & 1
            if i == 0:
                node[b] = sym
            else:
                node = node.setdefault(b, {})
    return root


def term(t):
    if t is None:
        return "H.DflHNil{}"
    if isinstance(t, int):
        return "H.DflHLeaf{%d}" % t
    return "H.DflHNode{%s, %s}" % (term(t.get(0)), term(t.get(1)))


def defs(name, t, depth=0):
    """One def per subtree four levels down, so no line is too long."""
    out = []
    counter = [0]

    def go(t, d):
        if t is None or isinstance(t, int):
            return term(t)
        if d == 4:
            counter[0] += 1
            n = "%s.t%d" % (name, counter[0])
            out.append((n, go_top(t)))
            return n + "()"
        return "H.DflHNode{%s, %s}" % (go(t.get(0), d + 1), go(t.get(1), d + 1))

    def go_top(t):
        return "H.DflHNode{%s, %s}" % (go(t.get(0), 1), go(t.get(1), 1))

    top = go_top(t)
    return out, top


print("""# bend-osdev-deflate, generated by gen/fixed.py (do not edit): the decoding
# trees of the fixed Huffman codes (RFC 1951, 3.2.6), as constants.
# LAWS.bend's fixed_trees: they are huff_tree of the fixed code lengths.
import Base
import ./huffman.bend as H
""")
for name, lens in [("fixed.lit", LIT), ("fixed.dist", DIST)]:
    sub, top = defs(name, tree(lens))
    for n, body in sub:
        print("def %s() -> H.DflTree:\n  %s\n" % (n, body))
    print("def %s() -> H.DflTree:\n  %s\n" % (name, top))
