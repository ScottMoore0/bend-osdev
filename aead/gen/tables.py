#!/usr/bin/env python3
"""The AES S-box of aesround.bend, computed from its definition.

  python3 gen/tables.py           rewrite the generated region
  python3 gen/tables.py --check   only check that it is up to date

FIPS 197, section 5.1.1: the S-box maps a byte to its multiplicative inverse
in GF(2^8) modulo x^8 + x^4 + x^3 + x + 1 (0 to 0), then applies the affine
transformation b_i ^ b_(i+4) ^ b_(i+5) ^ b_(i+6) ^ b_(i+7) ^ c_i with
c = 0x63. The region lies between "# BEGIN GENERATED by gen/tables.py: sbox"
and "# END GENERATED: sbox" in aesround.bend.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")


def gf_mul(a, b):
    r = 0
    for _ in range(8):
        if b & 1:
            r ^= a
        hi = a & 0x80
        a = (a << 1) & 255
        if hi:
            a ^= 0x1B
        b >>= 1
    return r


def aes_sbox():
    out = []
    for x in range(256):
        b = 0
        if x:
            b = 1
            for _ in range(254):
                b = gf_mul(b, x)
        s = b
        for i in range(1, 5):
            s ^= ((b << i) | (b >> (8 - i))) & 255
        out.append(s ^ 0x63)
    return out


SBOX = aes_sbox()
assert SBOX[0] == 0x63 and SBOX[0x53] == 0xED


def region():
    rows = [", ".join(str(v) for v in SBOX[i:i + 16]) for i in range(0, 256, 16)]
    return "def ad.aes.sbox.list() -> List<&2, U32>:\n  [%s]\n" % ",\n    ".join(rows)


def main():
    check = "--check" in sys.argv[1:]
    path = os.path.join(PKG, "aesround.bend")
    with open(path, encoding="utf-8", newline="") as f:
        src = f.read()
    begin = "# BEGIN GENERATED by gen/tables.py: sbox\n"
    end = "# END GENERATED: sbox\n"
    i = src.index(begin) + len(begin)
    j = src.index(end, i)
    new = src[:i] + region() + src[j:]
    if check:
        if new != src:
            print("aesround.bend differs from what gen/tables.py generates")
            sys.exit(1)
        print("aesround.bend is up to date")
        return
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)


if __name__ == "__main__":
    main()
