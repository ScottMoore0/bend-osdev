#!/usr/bin/env python3
"""Writes RIPEMD-160's compression function, unrolled, from the specification's
tables (gen/spec.py).

  python3 gen/rounds.py           rewrite the generated region
  python3 gen/rounds.py --check   only check that it is up to date

The region lies between "# BEGIN GENERATED by gen/rounds.py: ripemd160" and
"# END GENERATED: ripemd160" in ripemd160.bend; everything else is written by hand.
It holds one def, hs.ripemd160.rounds(x, cv): the sixteen words of a block and
the chaining value in, the next chaining value out. Every step of the
specification is one line, binding a fresh name (v<i> for chaining words,
w<j> for the expanded message), so the code reads as the specification's
step list and needs no indexing at run time.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")
sys.dont_write_bytecode = True
sys.path.insert(0, HERE)
import spec  # noqa: E402

XS = ", ".join("+x%d" % i for i in range(16))
W16 = "Hs.HsW16{%s}" % XS


class Names:
    def __init__(self):
        self.i = 0

    def new(self):
        self.i += 1
        return "v%d" % self.i


def add(*xs):
    t = xs[0]
    for x in xs[1:]:
        t = "U32.add(%s, %s)" % (t, x)
    return t


def ripemd160():
    out = ["def hs.ripemd160.rounds(x: Hs.HsW16, cv: Hs.HsW5) -> Hs.HsW5:",
           "  match x cv:",
           "    case %s Hs.HsW5{+h0, +h1, +h2, +h3, +h4}:" % W16]
    F = ["hs.rmd.f1", "hs.rmd.f2", "hs.rmd.f3", "hs.rmd.f4", "hs.rmd.f5"]
    n = Names()

    def line(side, R, S, K, fs):
        a, b, c, d, e = "h0", "h1", "h2", "h3", "h4"
        for j in range(80):
            r = j // 16
            if j % 16 == 0:
                out.append("      # %s line, round %d" % (side, r + 1))
            v = n.new()
            out.append("      +%s = hs.rmd.step(%s, %s(%s, %s, %s), x%d, %d, %dn, %s)"
                       % (v, a, fs[r], b, c, d, R[r][j % 16], K[r], S[r][j % 16], e))
            nc = n.new()
            out.append("      +%s = Hs.hs.rotl(%s, 10n)" % (nc, c))
            a, e, d, c, b = e, d, nc, b, v
        return a, b, c, d, e

    al, bl, cl, dl, el = line("left", spec.RMD_R, spec.RMD_S, spec.RMD_K, F)
    ar, br, cr, dr, er = line("right", spec.RMD_RP, spec.RMD_SP, spec.RMD_KP, F[::-1])
    out.append("      Hs.HsW5{%s, %s, %s, %s, %s}" % (add("h1", cl, dr), add("h2", dl, er), add("h3", el, ar),
                                                    add("h4", al, br), add("h0", bl, cr)))
    return "\n".join(out) + "\n"


REGIONS = [("ripemd160.bend", "ripemd160", ripemd160)]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fname, name, body in REGIONS:
        path = os.path.join(PKG, fname)
        with open(path) as f:
            text = f.read()
        begin = "# BEGIN GENERATED by gen/rounds.py: %s\n" % name
        end = "# END GENERATED: %s\n" % name
        i, j = text.index(begin) + len(begin), text.index(end)
        new = text[:i] + body() + text[j:]
        if new != text:
            stale.append(fname)
            if not check:
                with open(path, "w", newline="\n") as f:
                    f.write(new)
    if check:
        if stale:
            print("out of date (run gen/rounds.py): " + ", ".join(stale))
            sys.exit(1)
        print("generated regions up to date")


if __name__ == "__main__":
    main()
