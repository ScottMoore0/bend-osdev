#!/usr/bin/env python3
"""Writes the generated regions of PROOF_pkcs7.bend.

  python3 gen/pkcs7_proof.py           rewrite the regions
  python3 gen/pkcs7_proof.py --check   only check that they are up to date

Two regions, each between "# BEGIN GENERATED by gen/pkcs7_proof.py: <name>"
and "# END GENERATED: <name>":

  * bits: pk.bb, B.byte(B.byte(u)) == B.byte(u), on the 32 bits of u
    (a deep pattern, then computation);
  * u8: pk.u8, U32.to_nat(B.byte(U32.from_nat(p))) == p for every p of at
    most 255, by computation on each value: the values are split into
    chunks of 32, one def each (pk.u8 for 0 to 31, pk.u8.c1 for 32 to 63,
    ...), each matching its value one successor at a time and passing what
    is left to the next chunk; past 255 the bound is False.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROOF = os.path.join(HERE, "..", "PROOF_pkcs7.bend")
CHUNK = 32


def u32(p):
    """the pattern splitting a U32 into its bits p0 .. p31"""
    return "U32{" + "".join("WCon{%s%d, " % (p, i) for i in range(32)) + "WNil{}" + "}" * 32 + "}"


def bits_region():
    return ("# a byte's byte is itself\n"
            "def pk.bb(u: U32) -> {B.byte(B.byte(u)) == B.byte(u) : U32}:\n"
            "  match u:\n    case %s:\n      {==}\n" % u32("u"))


def name(i):
    return "pk.u8" if i == 0 else "pk.u8.c%d" % i


def stmt(k, var):
    t = "%dn+%s" % (k, var) if k else var
    return "{Nat.is_le(%s, 255n) == True{} : Bool} -> {U32.to_nat(B.byte(U32.from_nat(%s))) == %s : Nat}" % (t, t, t)


def u8_region():
    starts = list(range(0, 256, CHUNK))
    defs = []
    for i, k in enumerate(starts):
        lines = ["# the values %d to %d" % (k, k + CHUNK - 1),
                 "def %s(r: Nat) -> %s:" % (name(i), stmt(k, "r"))]
        ind, var = "  ", "r"
        for j in range(CHUNK):
            nxt = "r%d" % (j + 1)
            lines += [ind + "match %s:" % var, ind + "  case 0n:", ind + "    h => {==}", ind + "  case 1n+%s:" % nxt]
            ind += "    "
            var = nxt
        if k + CHUNK >= 256:
            t = "%dn+%s" % (k + CHUNK, var)
            lines.append(ind + "h => pk.absurd({U32.to_nat(B.byte(U32.from_nat(%s))) == %s : Nat}, h)" % (t, t))
        else:
            lines.append(ind + "%s(%s)" % (name(i + 1), var))
        defs.append("\n".join(lines) + "\n")
    # each chunk calls the next, so the last comes first
    return "\n".join(reversed(defs))


REGIONS = [("bits", bits_region), ("u8", u8_region)]


def main():
    check = "--check" in sys.argv[1:]
    with open(PROOF) as f:
        text = f.read()
    new = text
    for nm, fn in REGIONS:
        begin = "# BEGIN GENERATED by gen/pkcs7_proof.py: %s\n" % nm
        end = "# END GENERATED: %s\n" % nm
        i, j = new.index(begin) + len(begin), new.index(end)
        new = new[:i] + fn() + new[j:]
    if check:
        if new != text:
            print("PROOF_pkcs7.bend: out of date (run gen/pkcs7_proof.py)")
            sys.exit(1)
        print("PROOF_pkcs7.bend: up to date")
        return
    with open(PROOF, "w", newline="\n") as f:
        f.write(new)


if __name__ == "__main__":
    main()
