#!/usr/bin/env python3
"""Writes the proofs of the small-parameter exhaustive laws.

  python3 gen/exhaustive.py           rewrite the generated regions
  python3 gen/exhaustive.py --check   only check that they are up to date

A law "for every x below X (and y below Y): P(x, y)" is stated in LAWS.bend
(the "exhaustive" region, written from the table below) with Nat variables
and the hypotheses {Nat.is_lt(x, X) == True}. Its proof (the "exhaustive"
region of PROOF.bend) splits x (and y) into their values by nested matches
on 0n and 1n+p: each value's case is a lemma of its own, proved by
computation ({==}), so --verdict's step budget is spent one case at a time;
past the bound, the hypothesis is False == True, a contradiction. Each
region lies between "# BEGIN GENERATED by gen/exhaustive.py: exhaustive"
and "# END GENERATED: exhaustive".
"""
import os, sys, textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..")

# name, comment, [(var, bound)], statement with {x} {y} for the variables'
# terms and {L} for the laws file's own defs ("" in LAWS.bend, "Laws." in
# PROOF.bend)
TABLE = [
    ("toy_agree",
     "in the group p = 23, q = 11, g = 2, both sides of every pair of private keys x, y in [1, 10] compute the same shared secret (the primitive on g^y with x, and on g^x with y)",
     [("x", 10), ("y", 10)],
     "{{D.Dh.primitive({L}dhlaw.toy(), {L}dhlaw.nat1({x}), D.Dh.public({L}dhlaw.toy(), {L}dhlaw.nat1({y}))) == D.Dh.primitive({L}dhlaw.toy(), {L}dhlaw.nat1({y}), D.Dh.public({L}dhlaw.toy(), {L}dhlaw.nat1({x}))) : Result<&2, &2, D.DhError, B.Octets>}}"),
    ("toy_check_safe",
     "in the safe-prime group p = 23, full validation by the Legendre symbol (check_safe) agrees with full validation by y^q mod p = 1 (check_full), for every y below 23",
     [("y", 23)],
     "{{D.Dh.check_safe({L}dhlaw.toy(), {L}dhlaw.nat({y})) == D.Dh.check_full({L}dhlaw.toy(), {L}dhlaw.nat({y})) : Bool}}"),
]


def stmt(t, L, vals):
    return t.format(L=L, **vals)


def law(name, comment, vs, t):
    out = "".join("# %s\n" % l for l in textwrap.wrap(comment, 76)) + "law %s:\n" % name
    for v, _ in vs:
        out += "  for %s: Nat\n" % v
    for v, b in vs:
        out += "  for h%s: {Nat.is_lt(%s, %dn) == True{} : Bool}\n" % (v, v, b)
    out += "  " + stmt(t, "", {v: v for v, _ in vs}) + "\n"
    return out


def proof(name, vs, t):
    out = []
    names = [v for v, _ in vs]

    def leaf(vals):
        return "ex.%s.c%s" % (name, "_".join(str(vals[v]) for v in names))

    def lit(vals):
        return {v: ("%dn" % vals[v]) if isinstance(vals[v], int) else vals[v] for v in names}

    # the leaves
    def leaves(k, vals):
        if k == len(vs):
            out.append("def %s() -> %s:\n  {==}\n" % (leaf(vals), stmt(t, "Laws.", lit(vals))))
            return
        v, b = vs[k]
        for i in range(b):
            leaves(k + 1, dict(vals, **{v: i}))
    leaves(0, {})

    # the split
    body = ["def Laws.%s(%s):" % (name, ", ".join(names + ["h" + v for v in names]))]

    def split(k, vals, ind):
        if k == len(vs):
            body.append(ind + "%s()" % leaf(vals))
            return
        v, b = vs[k]
        var = v
        for i in range(b):
            body.append(ind + "match %s:" % var)
            body.append(ind + "  case 0n:")
            split(k + 1, dict(vals, **{v: i}), ind + "    ")
            body.append(ind + "  case 1n+%s%d:" % (v, i))
            var = "%s%d" % (v, i)
            ind += "    "
        # past the bound: one more match makes the hypothesis compute to
        # False == True, whatever the rest is
        last = "%s%d" % (v, b - 1)
        body.append(ind + "match %s:" % last)
        for pat, val in [("0n", "%dn" % b), ("1n+%sz" % v, "%dn+%sz" % (b + 1, v))]:
            rest = dict(vals, **{v: val})
            for w in names[k + 1:]:
                rest[w] = w
            body.append(ind + "  case %s:" % pat)
            body.append(ind + "    Empty.absurd(%s, ex.absurd(h%s))" % (stmt(t, "Laws.", lit(rest)), v))
    split(0, {}, "  ")
    out.append("\n".join(body) + "\n")
    return "\n".join(out)


SUPPORT = """def ex.bdisc(+b: Bool) -> Type:
  match b:
    case True{}:
      Empty
    case False{}:
      Unit

def ex.absurd(+e: {False{} == True{} : Bool}) -> Empty:
  %e : ex.bdisc(_)
  Unit{}
"""


def regions():
    laws = "\n".join(law(n, c, vs, t) for n, c, vs, t in TABLE)
    proofs = SUPPORT + "\n" + "\n".join(proof(n, vs, t) for n, c, vs, t in TABLE)
    return [("LAWS.bend", laws), ("PROOF.bend", proofs)]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fname, body in regions():
        path = os.path.join(PKG, fname)
        with open(path) as f:
            text = f.read()
        begin = "# BEGIN GENERATED by gen/exhaustive.py: exhaustive\n"
        end = "# END GENERATED: exhaustive\n"
        i, j = text.index(begin) + len(begin), text.index(end)
        new = text[:i] + body + text[j:]
        if new != text:
            stale.append(fname)
            if not check:
                with open(path, "w", newline="\n") as f:
                    f.write(new)
    if check:
        if stale:
            print("out of date (run gen/exhaustive.py): " + ", ".join(stale))
            sys.exit(1)
        print("generated regions up to date")


if __name__ == "__main__":
    main()
