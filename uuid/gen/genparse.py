#!/usr/bin/env python3
"""Writes uuid/PROOF_parse.bend (run from anywhere: python3 uuid/gen/genparse.py).

With --check, writes nothing and fails if PROOF_parse.bend differs from what
it would write.

The proof that every string parse accepts is shown back in lower case. A
character is a U32 of 32 bits: a hex digit's value is shown back as the
digit in lower case, proved by cases on the bits, most significant first,
stopping where parse's comparisons already answer None (this script works out
where, by evaluating them on the bits known so far, as the checker does). A
dash likewise. The rest is induction over the digits read, two at a time.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
OUT = os.path.join(PKG, "PROOF_parse.bend")

L = []
def w(s=""):
    L.append(s)

def ind(k, s):
    return "  " * k + s

# The bits of a character: b0 is the least significant
W32 = "WNil{}"
for i in reversed(range(32)):
    W32 = "WCon{b%d, %s}" % (i, W32)
CH = "Chr{U32{%s}}" % W32
BITS_DOWN = ", ".join("b%d" % i for i in reversed(range(32)))
PARAMS_DOWN = ", ".join("+b%d: Bool" % i for i in reversed(range(32)))

# Evaluating a comparison of a character with a constant when only its top
# bits are known: Word.cmp works out the most significant bits first and keeps
# the first difference, so it answers once a known bit differs from k's.
def cmp(known, k):
    for i in reversed(range(32)):
        if i not in known:
            return None
        b, kb = known[i], (k >> i) & 1
        if b != kb:
            return "LT" if b < kb else "GT"
    return "EQ"

def ge(c):
    return None if c is None else c in ("GT", "EQ")

def le(c):
    return None if c is None else c in ("LT", "EQ")

def band(a, b):
    if a is None:
        return None
    return b() if a else False

def in_range(known, lo, hi):
    return band(ge(cmp(known, lo)), lambda: le(cmp(known, hi)))

# hexval: "some", "none", or None (not yet answered)
def hexval(known):
    for lo, hi in [(48, 57), (97, 102), (65, 70)]:
        r = in_range(known, lo, hi)
        if r is None:
            return None
        if r:
            return "some"
    return "none"

def is_dash(known):
    c = cmp(known, 45)
    return None if c is None else c == "EQ"

def nib_leaf(known, d):
    if len(known) < 32:
        return "Unit{}"
    return "{==}" if d == "some" else "Unit{}"

def dash_leaf(known, d):
    if len(known) < 32:
        return "Unit{}"
    return "{==}" if d else "Unit{}"

# a case tree on the bits from b31 down, split until decide answers a
# definite failure (the claim is then Unit), or every bit is known
def tree_full(k, bit, known, decide, leaf):
    d = decide(known)
    failed = d is False or d == "none"
    if failed or bit < 0:
        w(ind(k, leaf(known, d)))
        return
    w(ind(k, "match b%d:" % bit))
    for v, name in [(0, "False{}"), (1, "True{}")]:
        w(ind(k + 1, "case %s:" % name))
        kn = dict(known)
        kn[bit] = v
        tree_full(k + 2, bit - 1, kn, decide, leaf)

T8 = "List<&2, Word(8n)>"
RU = "Result<&2, &2, U.UuidError, U.Uuid>"

w("import Base")
w("import ../word64/word64.bend as W")
w("import ./uuid.bend as U")
w("import ./LAWS_parse.bend as Laws")
w()
w("# Generated by gen/genparse.py: edit that, not this file.")
w("#")
w("# Every string parse accepts is shown back in lower case. Each claim is")
w("# stated as a type computed from a result, Unit where the result is a")
w("# failure, so the case analyses need no contradictions.")
w()
w("def bool_t(b: Bool) -> Type:")
w("  match b:")
w("    case True{}:")
w("      Unit")
w("    case False{}:")
w("      Empty")
w()
w("def ft(e: {False{} == True{} : Bool}) -> Empty:")
w("  %Equal.sym(Bool, False{}, True{}, e) : bool_t(_)")
w("  Unit{}")
w()
w("def and_l(a: Bool, -b: Bool, e: {Bool.and(a, b) == True{} : Bool}) -> {a == True{} : Bool}:")
w("  match a:")
w("    case True{}:")
w("      {==}")
w("    case False{}:")
w("      Empty.absurd({False{} == True{} : Bool}, ft(e))")
w()
w("def and_r(a: Bool, -b: Bool, e: {Bool.and(a, b) == True{} : Bool}) -> {b == True{} : Bool}:")
w("  match a:")
w("    case True{}:")
w("      e")
w("    case False{}:")
w("      Empty.absurd({b == True{} : Bool}, ft(e))")
w()
w("# A hex digit's value is shown back as the digit in lower case")
w("def NT(m: Maybe<&2, Word(4n)>, c: Char) -> Type:")
w("  match m:")
w("    case None{}:")
w("      Unit")
w("    case Some{n}:")
w("      {U.Uuid.hexdigit(n) == Char.to_lower(c) : Char}")
w()
w("def nibr.bits(%s) -> NT(U.Uuid.hexval(%s), %s):" % (PARAMS_DOWN, CH, CH))
tree_full(1, 31, {}, hexval, nib_leaf)
w()
w("def nibr(c: Char) -> NT(U.Uuid.hexval(c), c):")
w("  match c:")
w("    case %s:" % CH)
w("      nibr.bits(%s)" % BITS_DOWN)
w()
w("# A dash is a dash in lower case")
w("def DT(b: Bool, c: Char) -> Type:")
w("  match b:")
w("    case True{}:")
w("      {Char.to_lower(c) == '-' : Char}")
w("    case False{}:")
w("      Unit")
w()
w("def dash.bits(%s) -> DT(U.Uuid.is_dash(%s), %s):" % (PARAMS_DOWN, CH, CH))
tree_full(1, 31, {}, is_dash, dash_leaf)
w()
w("def dash(c: Char) -> DT(U.Uuid.is_dash(c), c):")
w("  match c:")
w("    case %s:" % CH)
w("      dash.bits(%s)" % BITS_DOWN)
w()
w("def dashf(+c: Char, h: {U.Uuid.is_dash(c) == True{} : Bool}) -> {Char.to_lower(c) == '-' : Char}:")
w("  %h : DT(_, c)")
w("  dash(c)")
w()
w("# An octet read from two digits shows them back")
N4a = "WCon{a0, WCon{a1, WCon{a2, WCon{a3, WNil{}}}}}"
N4d = "WCon{d0, WCon{d1, WCon{d2, WCon{d3, WNil{}}}}}"
for name, f, rhs in [("cat_hi", "hi", "a"), ("cat_lo", "lo", "d")]:
    w("def %s(a: Word(4n), d: Word(4n)) -> {W.W64.bits.%s(4n, 4n, W.W64.bits.cat(4n, 4n, d, a)) == %s : Word(4n)}:" % (name, f, rhs))
    w("  match a:")
    w("    case %s:" % N4a)
    w("      match d:")
    w("        case %s:" % N4d)
    w("          {==}")
    w()
for k, nib, cv, other in [(1, "hi", "c1", "c2"), (2, "lo", "c2", "c1")]:
    w("def BT%d(m: Maybe<&2, Word(8n)>, %s) -> Type:" % (k, "c1: Char, -c2: Char" if k == 1 else "-c1: Char, c2: Char"))
    w("  match m:")
    w("    case None{}:")
    w("      Unit")
    w("    case Some{b}:")
    w("      {U.Uuid.hexdigit(U.Uuid.nibble.%s(b)) == Char.to_lower(%s) : Char}" % (nib, cv))
    w()
for k, nib, cv, mv in [(1, "hi", "c1", "m1"), (2, "lo", "c2", "m2")]:
    sig = "+c1: Char, -c2: Char" if k == 1 else "-c1: Char, +c2: Char"
    w("def Bh%d(m1: Maybe<&2, Word(4n)>, m2: Maybe<&2, Word(4n)>, %s, nc: NT(%s, %s)) -> BT%d(U.Uuid.hexval.join(m1, m2), c1, c2):" % (k, sig, mv, cv, k))
    w("  match m1 m2:")
    w("    case Some{+a} Some{+d}:")
    lem = "cat_hi" if k == 1 else "cat_lo"
    val = "a" if k == 1 else "d"
    w("      %%Equal.sym(Word(4n), W.W64.bits.%s(4n, 4n, W.W64.bits.cat(4n, 4n, d, a)), %s, %s(a, d)) : {U.Uuid.hexdigit(_) == Char.to_lower(%s) : Char}" % (nib, val, lem, cv))
    w("      nc")
    for pat in ["Some{a} None{}", "None{} Some{d}", "None{} None{}"]:
        w("    case %s:" % pat)
        w("      Unit{}")
    w()
    w("def B%d(+c1: Char, +c2: Char) -> BT%d(U.Uuid.rdbyte(c1, c2), c1, c2):" % (k, k))
    w("  Bh%d(U.Uuid.hexval(c1), U.Uuid.hexval(c2), c1, c2, nibr(%s))" % (k, cv))
    w()
w("# the characters in lower case")
w("def tl(cs: List<&2, Char>) -> List<&2, Char>:")
w("  match cs:")
w("    case Nil{}:")
w("      Nil{}")
w("    case Con{c, t}:")
w("      Con{Char.to_lower(c), tl(t)}")
w()
w("# The octets read from digits show the digits back in lower case")
w("def HT(m: Maybe<&2, %s>, cs: List<&2, Char>) -> Type:" % T8)
w("  match m:")
w("    case None{}:")
w("      Unit")
w("    case Some{bs}:")
w("      {U.Uuid.digits(bs) == tl(cs) : List<&2, Char>}")
w()
LC = "List<&2, Char>"
w("def HLc(m: Maybe<&2, Word(8n)>, r: Maybe<&2, %s>, +c1: Char, +c2: Char, +t: %s, b1: BT1(m, c1, c2), b2: BT2(m, c1, c2), ih: HT(r, t)) -> HT(U.Uuid.cons_m(m, r), Con{c1, Con{c2, t}}):" % (T8, LC))
w("  match m r:")
w("    case Some{+b} Some{+bs}:")
HD = "U.Uuid.hexdigit(U.Uuid.nibble.hi(b))"
LD = "U.Uuid.hexdigit(U.Uuid.nibble.lo(b))"
w("      %%b1 : {U.Uuid.digits(Con{b, bs}) == Con{_, Con{Char.to_lower(c2), tl(t)}} : %s}" % LC)
w("      %%b2 : {U.Uuid.digits(Con{b, bs}) == Con{%s, Con{_, tl(t)}} : %s}" % (HD, LC))
w("      %%ih : {U.Uuid.digits(Con{b, bs}) == Con{%s, Con{%s, _}} : %s}" % (HD, LD, LC))
w("      {==}")
for pat in ["Some{b} None{}", "None{} Some{bs}", "None{} None{}"]:
    w("    case %s:" % pat)
    w("      Unit{}")
w()
w("def HL(cs: %s) -> HT(U.Uuid.hexlist(cs), cs):" % LC)
w("  match cs:")
w("    case Nil{}:")
w("      {==}")
w("    case Con{c1, Nil{}}:")
w("      Unit{}")
w("    case Con{+c1, Con{+c2, +t}}:")
w("      HLc(U.Uuid.rdbyte(c1, c2), U.Uuid.hexlist(t), c1, c2, t, B1(c1, c2), B2(c1, c2), HL(t))")
w()
w("# The octets of the Uuid read from 16 octets are those octets")
w("def OT(r: %s, bs: %s) -> Type:" % (RU, T8))
w("  match r:")
w("    case Fail{x}:")
w("      Unit")
w("    case Done{u}:")
w("      {U.Uuid.octets(u) == bs : %s}" % T8)
w()
def byte_pat(k):
    s = "WNil{}"
    for i in reversed(range(8)):
        s = "WCon{x%d_%d, %s}" % (k, i, s)
    return s
w("def O(bs: %s) -> OT(U.Uuid.length_ok(U.Uuid.of_octets(bs)), bs):" % T8)
w("  match bs:")
for k in range(16):
    d = 2 + 2 * k
    w(ind(d, "case Nil{}:"))
    w(ind(d + 1, "Unit{}"))
    w(ind(d, "case Con{%s, r%d}:" % (byte_pat(k), k + 1)))
    w(ind(d + 1, "match r%d:" % (k + 1)))
d = 2 + 2 * 16
w(ind(d, "case Nil{}:"))
w(ind(d + 1, "{==}"))
w(ind(d, "case Con{h, t}:"))
w(ind(d + 1, "Unit{}"))
w()
w("# The digits of the Uuid read from digits are those digits in lower case")
w("def RT(r: %s, cs: %s) -> Type:" % (RU, LC))
w("  match r:")
w("    case Fail{x}:")
w("      Unit")
w("    case Done{u}:")
w("      {U.Uuid.digits(U.Uuid.octets(u)) == tl(cs) : %s}" % LC)
w()
w("def R3(r: %s, +bs: %s, +cs: %s, o: OT(r, bs), hl: {U.Uuid.digits(bs) == tl(cs) : %s}) -> RT(r, cs):" % (RU, T8, LC, LC))
w("  match r:")
w("    case Done{+u}:")
w("      %%Equal.sym(%s, U.Uuid.octets(u), bs, o) : {U.Uuid.digits(_) == tl(cs) : %s}" % (T8, LC))
w("      hl")
w("    case Fail{x}:")
w("      Unit{}")
w()
w("def R2(m: Maybe<&2, %s>, +cs: %s, hl: HT(m, cs)) -> RT(U.Uuid.of_digits(m), cs):" % (T8, LC))
w("  match m:")
w("    case None{}:")
w("      Unit{}")
w("    case Some{+bs}:")
w("      R3(U.Uuid.length_ok(U.Uuid.of_octets(bs)), bs, cs, O(bs), hl)")
w()
w("# The text")
w("def PT(r: %s, s: String) -> Type:" % RU)
w("  match r:")
w("    case Fail{x}:")
w("      Unit")
w("    case Done{u}:")
w("      {U.Uuid.show(u) == String.to_lower(s) : String}")
w()
C = ["c%d" % i for i in range(36)]
def scons(xs):
    s = "SNil{}"
    for x in reversed(xs):
        s = "SCon{%s, %s}" % (x, s)
    return s
S36 = scons(C)
DASH = [8, 13, 18, 23]
LST = "[" + ", ".join(C[i] for i in range(36) if i not in DASH) + "]"
CPARAMS = ", ".join("+%s: Char" % c for c in C)
CARGS = ", ".join(C)
D = "Bool.and(U.Uuid.is_dash(c8), Bool.and(U.Uuid.is_dash(c13), Bool.and(U.Uuid.is_dash(c18), U.Uuid.is_dash(c23))))"
w("def Q2(r: %s, %s, d8: {Char.to_lower(c8) == '-' : Char}, d13: {Char.to_lower(c13) == '-' : Char}, d18: {Char.to_lower(c18) == '-' : Char}, d23: {Char.to_lower(c23) == '-' : Char}, rt: RT(r, %s)) -> PT(r, %s):" % (RU, CPARAMS, LST, S36))
w("  match r:")
w("    case Fail{x}:")
w("      Unit{}")
w("    case Done{+u}:")
w("      %%Equal.sym(%s, U.Uuid.digits(U.Uuid.octets(u)), tl(%s), rt) : {U.Uuid.show.dashes(_) == String.to_lower(%s) : String}" % (LC, LST, S36))
low = ["Char.to_lower(%s)" % c for c in C]
for i in DASH:
    cur = list(low)
    cur[i] = "_"
    w("      %%Equal.sym(Char, Char.to_lower(c%d), '-', d%d) : {U.Uuid.show.dashes(tl(%s)) == %s : String}" % (i, i, LST, scons(cur)))
    low[i] = "'-'"
w("      {==}")
w()
w("def Q(ok: Bool, %s, +hok: {%s == ok : Bool}) -> PT(U.Uuid.parse.go(U.Uuid.strip.check(ok, %s)), %s):" % (CPARAMS, D, LST, S36))
w("  match ok:")
w("    case False{}:")
w("      Unit{}")
w("    case True{}:")
r1 = "Bool.and(U.Uuid.is_dash(c13), Bool.and(U.Uuid.is_dash(c18), U.Uuid.is_dash(c23)))"
r2 = "Bool.and(U.Uuid.is_dash(c18), U.Uuid.is_dash(c23))"
h1 = "and_r(U.Uuid.is_dash(c8), %s, hok)" % r1
h2 = "and_r(U.Uuid.is_dash(c13), %s, %s)" % (r2, h1)
d8 = "dashf(c8, and_l(U.Uuid.is_dash(c8), %s, hok))" % r1
d13 = "dashf(c13, and_l(U.Uuid.is_dash(c13), %s, %s))" % (r2, h1)
d18 = "dashf(c18, and_l(U.Uuid.is_dash(c18), U.Uuid.is_dash(c23), %s))" % h2
d23 = "dashf(c23, and_r(U.Uuid.is_dash(c18), U.Uuid.is_dash(c23), %s))" % h2
w("      Q2(U.Uuid.of_digits(U.Uuid.hexlist(%s)), %s, %s, %s, %s, %s, R2(U.Uuid.hexlist(%s), %s, HL(%s)))" % (LST, CARGS, d8, d13, d18, d23, LST, LST, LST))
w()
w("def TP(s: String) -> PT(U.Uuid.parse(s), s):")
w("  match s:")
for k in range(36):
    d = 2 + 2 * k
    w(ind(d, "case SNil{}:"))
    w(ind(d + 1, "Unit{}"))
    w(ind(d, "case SCon{+c%d, s%d}:" % (k, k + 1)))
    w(ind(d + 1, "match s%d:" % (k + 1)))
d = 2 + 2 * 36
w(ind(d, "case SNil{}:"))
w(ind(d + 1, "Q(%s, %s, {==})" % (D, CARGS)))
w(ind(d, "case SCon{h, t}:"))
w(ind(d + 1, "Unit{}"))
w()
w("def Laws.text_parse_show(s, u, e):")
w("  %e : PT(_, s)")
w("  TP(s)")

text = "\n".join(L).rstrip() + "\n"
if "--check" in sys.argv[1:]:
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if old != text:
        print("uuid/PROOF_parse.bend is not what gen/genparse.py writes")
        sys.exit(1)
    print("uuid/PROOF_parse.bend ok")
else:
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
