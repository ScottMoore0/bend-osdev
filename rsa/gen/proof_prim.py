#!/usr/bin/env python3
"""Writes rsa/PROOF_prim.bend: the proofs of the primitives' laws
(LAWS_prim.bend).

  python3 gen/proof_prim.py

A key Rsa.private_of accepts is the RsaPrivate of its integers with dP = d
mod (p - 1), dQ = d mod (q - 1) and qInv = BnMod.inv(q, p) (which is Some),
and the checks it makes are True (kp.kb1, kp.kb2, kp.kmi, kp.ksk: every
other case is a Fail); from them, by bignum's value laws, n = p q, p q is odd
(bignum's is_odd_value), d e = 1 modulo p - 1 and q - 1 (BnMod.mul and the
value of p - 1), q qInv = 1 mod p (inv_value), so p and q are distinct
(mod_inv_ne). The CRT form's value is bignum's crt_exp_nat expression
(kp.crtv: add, mul, BnMod.mul, BnMod.sub, BnMod.exp, mod and sub laws), so
c^d mod n; every result is below n (nat_mod_lt), so the range checks pass,
and RSAEP's value after it is (c^d mod n)^e mod n = c (nat_pow_mod,
rsa_nat_rev, nat_mod_small; rsa_nat the other way). The Nat chains come from
scripts/natproof.py.
"""
